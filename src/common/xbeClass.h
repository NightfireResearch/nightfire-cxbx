#ifndef COMMON_XBECLASS_H_
#define COMMON_XBECLASS_H_

#include <stddef.h>
#include <stdint.h>

// ---------------------------------------------------------------------------------------------------------------
// Overlay classes: C++ classes that stand in for one of the game's, so that a replacement can be a member
// function and `this->field` lands where the game keeps it. See docs/driving-injection-framework.md, section 4.
//
// The rules, each of which is a way this silently goes wrong otherwise:
//
//   - The exact layout, field by field, checked with XBE_CLASS_SIZE and XBE_FIELD below against what the game
//     uses (Ghidra's structure, or the offsets in the disassembly).
//   - No `virtual` keyword. A class with a vtable declares `void **vtable;` as its first member; the compiler
//     must never add a vtable pointer of its own. A virtual method is replaced by patching the function the
//     vtable points at, like any other, and called - reaching the object's own override - by declaring it
//     with // VIRTUAL(n), n its vtable slot (see Event::DeletingDestructor, Schedule::Process).
//   - Never constructed by our code. Instances are the game's, and `this` is reinterpreted; objects are made by
//     calling the game's own constructors.
//   - Everything public. Single, public, non-virtual inheritance only, and only where Ghidra's structure says
//     so: its first field is super_<Base>, of the base's type (Ghidra's own convention for a base class). The
//     generated layout then holds only the derived class's own fields, from the end of the base, and the build
//     refuses a class whose declared base disagrees with Ghidra's in either direction. The base's vtable pointer
//     is the derived class's too, as in the game (RAutonomousObj : RSceneObj is the worked example).
//   - Constructors and destructors are ordinary methods (Construct, Destruct) tagged with FUNC_AT or
//     AUTOGEN(address), since the language will not give their addresses.
//
// Methods not yet reimplemented are declared in the class with `// AUTOGEN` above them, and tools/preprocess.py
// generates a body that calls the original through `this` (src/driving/autogenerated_functions.inc).
// ---------------------------------------------------------------------------------------------------------------

// The field checks use offsetof on classes with a base, which is not standard-layout. MSVC, clang and GCC all give
// the right answer for single, non-virtual inheritance; clang and GCC also warn, which is noise here.
#if defined(__clang__) || defined(__GNUC__)
#pragma GCC diagnostic ignored "-Winvalid-offsetof"
#endif

// A layout check that holds on 32-bit only. A structure that lives only in memory has native pointers, so on 64-bit
// it grows; structures read in place from the game's files keep plain static_asserts (docs/driving/64-bit.md).
#define LAYOUT_32(condition, message) static_assert(sizeof(void *) != 4 || (condition), message)

// The size a memory-only structure is on the Xbox, for allocations that must lie where the game's did
// (src/action/XboxHeap.h): XBOX_SIZE beside the structure says it (and checks it on 32-bit), XBOX_SIZEOF asks.
template <typename T> struct XboxSizeOf;
template <typename T> struct XboxSizeOf<T *> { static const size_t value = 4; };
#define XBOX_SIZE(Type, size)                                                                               \
    LAYOUT_32(sizeof(Type) == (size), #Type " is " #size " bytes on the Xbox");                             \
    template <> struct XboxSizeOf<Type> { static const size_t value = (size); }
#define XBOX_SIZEOF(Type) (XboxSizeOf<Type>::value)
// On 64-bit those structures are bigger than on the Xbox, and the allocation functions named *Xbox take their Xbox
// sizes as well; on 32-bit the sizes are the same and those names are the plain calls (the shadow tests' fakes stand
// in for the plain functions)
#define XBOX_SIZES_DIFFER (UINTPTR_MAX > 0xffffffffu)

// Overlay classes are the game's objects in memory: their checks are LAYOUT_32's.
#define XBE_CLASS_SIZE(Class, size)                                                                          \
    LAYOUT_32(sizeof(Class) == (size), #Class " is not the size of the game's (" #size " bytes)")

#define XBE_FIELD(Class, field, offset)                                                                      \
    LAYOUT_32(offsetof(Class, field) == (offset), #Class "::" #field " is not at the game's offset (" #offset ")")

#endif // COMMON_XBECLASS_H_
