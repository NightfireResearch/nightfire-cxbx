// ---------------------------------------------------------------------------------------------------------------
// The renderer (Ghidra: RRenderer, one instance at fgRenderer): EAGL's device, render context and full-screen
// viewport, the screen's resolution, the frame bracket and the screen capture, the debug font, and two draw groups
// that hold the translucent instances deferred to the end of a view. RRenderSharedData sets the lighting up per
// view port, per world instance and per scene object as the model draws ask. The instance draws pick an article's
// model by distance, set the lighting up for it and draw it with its effects, or keep it for its draw group when it
// is in another pass; their shadow maps are loaded per track. See Renderer.cpp.
// ---------------------------------------------------------------------------------------------------------------

