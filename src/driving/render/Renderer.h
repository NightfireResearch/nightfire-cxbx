// The lighting's per-draw setup (Ghidra: RRenderSharedData; statics only). The model draws call one of the
// SendPer*Instance functions by the article's render type before each model, through a table.
class RRenderSharedData {
public:
    static void Init();                                                                         // 0x0007e190
    // Answers the old setting
    static bool SetVehiclesAllowed(bool allowed);                                               // 0x0007e1a0
    // Forgets the scene object the lighting was last set up for
    static void MarkAsDirty();                                                                  // 0x0007e1b0
    static void SendPerViewPort();                                                              // 0x0007e1c0
    static void SendPerWorldInstance();                                                         // 0x0007e1f0
    // A world position's brightness from the track's shadow maps, by its instance's shadow record; unrounded
    static double GetShadowBrightness(Coord3 position, int instanceIndex);                      // 0x0007e200
    static void SendPerObjectInstance(CARP::Instance *instance, RSceneObj *sceneObj);           // 0x0007e2b0
    static void SendPerCarInstance(CARP::Instance *instance, RSceneObj *sceneObj);              // 0x0007e310
};

