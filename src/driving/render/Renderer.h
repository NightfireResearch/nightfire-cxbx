// The draws a group defers (Ghidra: RDrawGroup, one word): camera/DirectorQueue.h's reverse draw list, allocated
// by the constructor under the name "RReverseDrawList".
class RDrawGroup {
public:
    ReverseDrawList *translucent;       // +0x00

    RDrawGroup* Construct();                                                                    // 0x0007cf40
    void Destruct();                                                                            // 0x0007cae0
    // Draws the kept instances in the order they came, and empties the list
    void FlushDrawLists();                                                                      // 0x0007c9e0
    void AddToTranslucentList(const ReverseDrawEntry *draw);                                      // 0x0007cfa0
};
static_assert(sizeof(RDrawGroup) == 4, "a draw group is one pointer");

// The renderer (0x90 bytes, FastAlloc'd by Init under "RRenderer").
class RRenderer {
public:
    // videoMode: ConfigureRes sets 0, or 2 for a wide screen; the constructor tests for 3
    enum VideoMode : int32_t {
        kVideoNormal = 0,
        kVideoLetterbox = 1,            // RRenderHigh: a single view's extents are the middle three quarters
        kVideoWide = 2,
        kVideoMode3 = 3,
    };

    uint32_t unknown00;
    RViewCamera *currentView;           // +0x04 the view being drawn (RViewCamera::SetRenderCamera's); EndView clears it
    RDrawGroup drawGroups[2];           // +0x08
    RDrawGroup *currentDrawGroup;       // +0x10 drawGroups[0] from the constructor on
    uint32_t cpuFeatures;               // +0x14 CPU_detect's
    uint32_t unknown18;                 // +0x18 zero
    uint8_t unknown1C;                  // +0x1c the constructor's third argument
    uint8_t screenCapturePending;       // +0x1d EndFrame saves the frame to a .tga
    uint8_t alphaWrites;                // +0x1e Enable/DisableAlphaWrites
    uint8_t unknown1F;
    uint32_t unknown20;                 // +0x20 cleared by RPlayerViewCamera::ConfigureView
    uint32_t frameCount;                // +0x24 EndFrame counts the frames; RRenderHigh::RestartTrackRender clears it
    uint8_t unknown28[8];
    Coord4 cameraPosition;              // +0x30 the view's camera's, w 1
    int32_t screenWidth;                // +0x40
    int32_t screenHeight;               // +0x44
    int32_t videoMode;                  // +0x48 VideoMode
    uint8_t widescreen;                 // +0x4c 16:9
    uint8_t presentFlag100;             // +0x4d RenderContext::SetPresentFlag100 at construction; ConfigureRes clears it
    uint8_t unknown4E[2];
    float unknown50;                    // +0x50 1; unknown50 / unknown54 scales RRenderHigh's AspectScale
    float unknown54;                    // +0x54 1
    float fieldOfViewScale;             // +0x58 1
    int32_t ps2Mipmap;                  // +0x5c "PS2 mipmap"; -128 from the constructor
    EAGL::Device *device;               // +0x60
    EAGL::RenderContext *renderContext; // +0x64
    EAGL::ViewPort *viewPort;           // +0x68 the full screen, in pixels, orthographic
    FNTXFont *debugFont;                // +0x6c FONT_create's
    void *debugFontData;                // +0x70 "data/render/debug.xfn"
    uint8_t framePending;               // +0x74 a frame has ended since the last Flush
    uint8_t unknown75[0x1b];

    // The two pointer arguments are not read; Render_InitLibRender passes an uninitialised stack buffer and 0
    RRenderer* Construct(void *unused1, int unused2, bool unknown1C);                           // 0x0007d2a0
    void Destruct();                                                                            // 0x0007d670
    static RRenderer* Init(void *unused1, int unused2, bool unknown1C);                         // 0x0007d5e0
    static void Shutdown();                                                                     // 0x0007d740

    void ConfigureRes();                                                                        // 0x0007cfb0
    void LoadDebugFont();                                                                       // 0x0007d560
    void FlushDrawLists();                                                                      // 0x0007d020
    // The view being drawn, which is forgotten
    RViewCamera* EndView();                                                                     // 0x0007d030
    void StartFrame();                                                                          // 0x0007d060
    void EndFrame();                                                                            // 0x0007d5b0
    // Two empty frames, if a frame has ended since the last Flush or `force`
    void Flush(bool force);                                                                     // 0x0007d070
    // Each answers whether alpha writes were already on
    bool EnableAlphaWrites();                                                                   // 0x0007d0b0
    bool DisableAlphaWrites();                                                                  // 0x0007d0e0
    void DoScreenCapture();                                                                     // 0x0007d110
    // The original calls FUN_00013c80, the same code as FnDefaultAnimBank::Init
    void SetCurrentView(RViewCamera *view) { currentView = view; }
};
static_assert(sizeof(RRenderer) == 0x90, "RRenderer is 0x90 bytes");
static_assert(offsetof(RRenderer, currentDrawGroup) == 0x10 && offsetof(RRenderer, alphaWrites) == 0x1e &&
              offsetof(RRenderer, cameraPosition) == 0x30 && offsetof(RRenderer, screenWidth) == 0x40 &&
              offsetof(RRenderer, widescreen) == 0x4c && offsetof(RRenderer, fieldOfViewScale) == 0x58 &&
              offsetof(RRenderer, renderContext) == 0x64 && offsetof(RRenderer, framePending) == 0x74,
              "RRenderer layout");

#define fgRenderer (*(RRenderer **)0x001ebff4)

