// ---- the track's shadow maps

// A shadow map image in the track's _S.xsh file: 8-bit samples (the name is ours)
struct ShadowMapImage {
    uint32_t type;                      // +0x00
    int16_t width;                      // +0x04
    int16_t height;                     // +0x06
    uint32_t unknown08;
    uint32_t flags;                     // +0x0c
    uint8_t pixels[1];                  // +0x10 rows SHAPE_rowbytes apart
};

// A render instance's shadow record (16 bytes, the name is ours), by the high half of the instance's +0x2c word:
// where a world position falls in which shadow map.
struct ShadowMapInfo {
    float offsetU;                      // +0x00
    int32_t image;                      // +0x04 the image's index
    float offsetV;                      // +0x08
    float scale;                        // +0x0c from world units to the image's 0..1
};

// Points the instances at the track's shadow records and loads its shadow maps ("data\track\<track>_S.xsh",
// images "0000", "0001", ... up to the first missing)
void RInstanceRender_SetShadowInformation(const ShadowMapInfo *info);                           // 0x0007daf0
// No shadow maps: an all-zero record and the default texture
void RInstanceRender_SetDefaultShadowInformation();                                             // 0x0007dbc0
// A shadow map's bilinear sample at (u, v) in pixels, mapped to (sample - 1) / 14; unrounded
double GetTextureVal(float u, float v, const ShadowMapImage *image);                            // 0x0007e040


