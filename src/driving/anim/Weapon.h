#ifndef DRIVING_ANIM_WEAPON_H_
#define DRIVING_ANIM_WEAPON_H_

// The weapons actors hold. ActWeaponDatabase loads each weapon's CARP file once (data\actors\weapons\<name>.crp,
// an ActWeaponAux), registered by name in URefCounter<WeaponInfo>, and makes an ActWeapon - a scene object drawing
// the file's article - for each actor using one. An ActWeapon follows its holder's matrices
// (SetTransformToWorldSpace), keeps eight muzzle flashes (StartMuzzleFlash) that ManualRender draws as they fade,
// and knows whether the player's object owns it. Also the compiled copies of URefCounter<WeaponInfo>'s tree, and
// an out-of-line fabs. See Weapon.cpp.

#include <stddef.h>
#include <stdint.h>

#include "../autogenerated_layouts.h"   // MATRIX4
#include "../data/CoordConvert.h"       // Coord3, Coord4
#include "../engine/URefCounter.h"      // RefCounterTree
#include "../render/RSceneObj.hpp"

struct RCARPFile;
struct PhysicsObject;
struct Newton;

// A weapon's file (4 bytes, "ActWeaponAux")
struct ActWeaponAux {
    RCARPFile *carp;

    // Loads data\actors\weapons\<name>.crp, resolved (Ghidra's name; it is the record's constructor).
    void Load(const char *name);                                                // 0x0001ab50
};
static_assert(sizeof(ActWeaponAux) == 4, "an ActWeaponAux is 4 bytes");

// ActWeaponDatabase::WeaponInfo (0x18, operator new): what URefCounter<WeaponInfo> counts.
struct ActWeaponInfo {
    ActWeaponAux *aux;                // +0x00
    char name[0x14];                  // +0x04
};
static_assert(sizeof(ActWeaponInfo) == 0x18, "a WeaponInfo is 0x18 bytes");

// A muzzle flash (Ghidra: ActShellCasing)
struct ActWeaponFlash {
    Coord3 position;                  // +0x00
    int32_t endTick;                  // +0x0c drawn while the simulation's step count is below it
    float size;                       // +0x10
};
static_assert(sizeof(ActWeaponFlash) == 0x14, "a weapon's flash is 0x14 bytes");

// A weapon (0x170, "ActWeapon"): an RAutonomousObj with its own vtable (0x0018a440).
class ActWeapon : public RAutonomousObj {
public:
    enum {
        kFlashCount = 8,
    };
    enum Flags : uint32_t {
        kManualRender = 0x1,          // Render draws nothing: the holder calls ManualRender (always set)
        kPlayerOwned = 0x2,           // the owner is owned by the player's object (SetOwner)
    };

    ActWeaponAux *aux;                // +0x80
    ActWeaponFlash flashes[kFlashCount];   // +0x84
    Coord4 muzzleDirection;           // +0x124 the weapon's z axis when its last flash started
    int32_t muzzleFlashEndTick;       // +0x134
    uint32_t flags;                   // +0x138 Flags, and the user's bits from UseWeapon
    MATRIX4 *worldTransforms[2];      // +0x13c the holder's two matrices, new (SetTransformToWorldSpace)
    PhysicsObject *owner;             // +0x144
    uint8_t unknown148[8];
    Coord3 velocity;                  // +0x150 zero (GetVelocity)
    int32_t unknown15c;               // +0x15c 0
    int32_t unknown160;               // +0x160 0
    int32_t unknown164;               // +0x164 0
    uint8_t unknown168[8];

    ActWeapon* Construct(ActWeaponAux *aux, uint32_t flags);                    // 0x0001abd0
    void Destruct();                                                            // 0x0001acc0
    ActWeapon* Delete(unsigned flags);          // the scalar deleting destructor, vtable slot 0   0x0001b1b0

    // Registers the henchmen's muzzle flash size as a debug variable.
    static void LoadAttributes();                                               // 0x0001ab20

    void SetTransformToWorldSpace(const MATRIX4 *first, const MATRIX4 *second);   // 0x0001ad00
    void SetOwner(PhysicsObject *owner);                                        // 0x0001ad70
    void PlayEvent(int stimulus);                                               // 0x0001add0
    // A Newton of the weapon's instances thrown from `position`.
    Newton* SpawnWeapon(const Coord3 *position, const Coord3 *direction, const Coord3 *momentum,
                        const Coord3 *spin);                                    // 0x0001adf0
    // 1 just after a flash starts, falling to 0 over seven steps; left unrounded on the x87.
    double CurrentMuzzleFlashStrength();                                        // 0x0001ae30
    // A flash at `position` in the first free slot, if one is.
    void StartMuzzleFlash(const Coord3 *position);                              // 0x0001b270
    void RenderShellCasings();                                                  // 0x0001b020

    // The vtable's overrides
    void Render();                                      // slot 2               // 0x0001ae60
    void TransformToWorldSpace(MATRIX4 *matrix);        // slot 6               // 0x0001b050
    void TransformPointToWorldSpace(Coord4 *point);     // slot 7               // 0x0001b1e0
    void TransformMatrixToWorldSpace(MATRIX4 *matrix);  // slot 8               // 0x0001b090
    void SetEventDynamicData();                         // slot 11              // 0x0001adc0
    Coord3* GetVelocity();                              // slot 13              // 0x0001b130
    void ManualRender();                                // slot 19              // 0x0001ae70
};
static_assert(offsetof(ActWeapon, aux) == 0x80, "ActWeapon::aux is at +0x80");
static_assert(offsetof(ActWeapon, muzzleDirection) == 0x124, "ActWeapon::muzzleDirection is at +0x124");
static_assert(offsetof(ActWeapon, flags) == 0x138, "ActWeapon::flags is at +0x138");
static_assert(offsetof(ActWeapon, velocity) == 0x150, "ActWeapon::velocity is at +0x150");
static_assert(sizeof(ActWeapon) == 0x170, "an ActWeapon is 0x170 bytes");

class ActWeaponDatabase {             // 0x40 (ActManager's)
public:
    enum {
        kMaxWeapons = 14,
    };

    WeaponInfoRefCounter *references; // +0x00 the shared URefCounter<WeaponInfo>
    ActWeaponInfo *weapons[kMaxWeapons];   // +0x04 the ones this database loaded
    int32_t count;                    // +0x3c

    ActWeaponDatabase* Construct();                                             // 0x0001bf80
    void Destruct();                                                            // 0x0001bcb0
    // Loads the weapon `name` unless it is registered already.
    void LoadWeapon(const char *name);                                          // 0x0001bd60
    // A new ActWeapon of the loaded weapon `name`.
    ActWeapon* UseWeapon(const char *name, uint32_t flags);                     // 0x0001b3d0
    void StopUsingWeapon(const char *name, ActWeapon *weapon);                  // 0x0001b140
};
static_assert(offsetof(ActWeaponDatabase, count) == 0x3c, "ActWeaponDatabase::count is at +0x3c");
static_assert(sizeof(ActWeaponDatabase) == 0x40, "an ActWeaponDatabase is 0x40 bytes");

// URefCounter<WeaponInfo>'s tree (WeaponInfoRefCounter's map, at 0x001dda14): its compiled copies of
// RefCounterTree's code (engine/URefCounter.h).
class WeaponInfoRefTree : public RefCounterTree {
public:
    void EraseSubtree(RefCounterNode *node);                                    // 0x0001b450
    RefCounterNode** EraseAt(RefCounterNode **result, RefCounterNode *where);   // 0x0001b4a0
    RefCounterNode** InsertAt(RefCounterNode **result, bool addLeft, RefCounterNode *where,
                              const RefCounterValue *value);                    // 0x0001b810
    RefCounterNode** EraseRange(RefCounterNode **result, RefCounterNode *first,
                                RefCounterNode *last);                          // 0x0001ba00
    RefCounterInsertResult* InsertUnique(RefCounterInsertResult *result,
                                         const RefCounterValue *value);         // 0x0001baf0
    // The destructor's erase and free, without its subtree erase (only an exception unwind calls it).
    void DestroyRange();                                                        // 0x0001be20
};

// fabs, out of line: -0 stays -0, a NaN stays (Ghidra: FUN_0001b160; name ours).
float FloatAbs(float x);                                                        // 0x0001b160

#endif // DRIVING_ANIM_WEAPON_H_
