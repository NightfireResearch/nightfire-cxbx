#ifndef DRIVING_ANIM_POSER_H_
#define DRIVING_ANIM_POSER_H_

// ActPoser: poses an actor's skeleton each frame from its animation. It keeps the animation's time in frames
// (20 a second), evaluates the animation (or two, cross-fading, or two at times the actor sets) into the
// skeleton's pose buffers, turns the pose into the skeleton's local matrices, and moves the root bone by the
// poser's matrices: the actor's placement ("TbOu", set by the actor) and, unless the actor has a matrix callback,
// two matrices that take out the root bone's own heading and x/z position at the start of the animation. IK and
// the pose overrides then run over the matrices (DoSkeletonPose), and Skin makes the skinning matrices. Events
// keyed to the animation's time are fired by DoEventPose. See Poser.cpp.
//
// Matrices are row vectors with the translation in row 3. A pose is 12 floats a bone (EAGLAnim's: scale xyz, a
// length scale, quaternion xyzw, translation xyz, 1).

#include <stddef.h>
#include <stdint.h>

#include "../autogenerated_layouts.h"   // MATRIX4
#include "../data/CoordConvert.h"       // Coord3, Coord4
#include "Skeleton.h"                   // ActSkeleton

class ActAnimGroup;
class ActEvents;
class ActIKSolverArray;
class ActGlobalPoseOverrideArray;

// ActPoser's matrices (0x10c)
struct ActPoseMatrices {
    MATRIX4 matrices[4];              // +0x000
    MATRIX4 *current;                 // +0x100
    MATRIX4 *buffer;                  // +0x104 [count], new[]
    int32_t count;                    // +0x108

    // A new buffer of `count` matrices, not filled. The second matrix is copied from the source's first.
    ActPoseMatrices* ConstructCopy(const ActPoseMatrices *other);               // 0x00018410
    void Destruct();                                                            // 0x00018400
};
static_assert(sizeof(ActPoseMatrices) == 0x10c, "a poser's matrices are 0x10c bytes");

// ActCrossFadeBlendData (0x130, made by ActPoser::SetupCrossFadeBlend): the pose's matrices and animation as they
// were when the cross-fade began.
struct ActCrossFadeBlendData {
    ActPoseMatrices matrices;         // +0x000
    float length;                     // +0x10c the fade's length + 1
    float step;                       // +0x110 1 / the fade's length
    float frame;                      // +0x114
    float endFrame;                   // +0x118
    ActAnimGroup *animation;          // +0x11c a copy
    bool unknown120;                  // +0x120
    uint8_t unknown121[0xf];

    ActCrossFadeBlendData* Construct(float length, float frame, float endFrame, const ActAnimGroup *animation,
                                     const ActPoseMatrices *matrices, bool unknown);   // 0x00018490
    void Destruct();                                                            // 0x00018ac0
};
static_assert(sizeof(ActCrossFadeBlendData) == 0x130, "an ActCrossFadeBlendData is 0x130 bytes");
static_assert(offsetof(ActCrossFadeBlendData, animation) == 0x11c, "the cross-fade's animation is at +0x11c");

// The poser's four matrices (ActPoseMatrices::matrices). Names ours, from what the code builds.
enum ActPoseMatrix {
    kPoseTbOu = 0,                    // the actor's placement (Get/SetInitialTbOu); its row 3 the animation origin
    kPoseRootOffset = 1,              // a translation by minus the root bone's x and z
    kPoseRootTurn = 2,                // a turn about y taking out the root bone's heading
    kPoseToWorld = 3,                 // RootOffset * RootTurn * TbOu, what the root bone is moved by
};

enum ActPoseMode {
    kPoseModeNone = 0,
    kPoseModeNormal = 1,              // one animation (SetNormalAnimation)
    kPoseModeCrossFade = 2,           // fading from the cross-fade's copy into the animation
    kPoseModeManual = 3,              // two times of the animation blended by a weight, all set by the actor
};

class ActPoser {                      // 0x70 ("ActPoser", made by ActActor's constructor)
public:
    bool hasMatrixCallback;           // +0x00 the actor's: keeps the root bone where the animation puts it
    bool mirrored;                    // +0x01 the actor's: the x axis of the placement and root bone negated
    uint8_t unknown02[2];
    ActSkeleton *skeleton;            // +0x04
    float time;                       // +0x08 frames
    float nextTime;                   // +0x0c what the next DoMainPose poses at
    float previousTime;               // +0x10 time less one update's frames (not below 0)
    float length;                     // +0x14 the animation's, frames
    float endTime;                    // +0x18 the animation's length, or the cross-fade's
    ActAnimGroup *animation;          // +0x1c
    ActEvents *events;                // +0x20 the manager's, what the animations' events are resolved by
    ActPoseMatrices *matrices;        // +0x24
    float framesPerSecond;            // +0x28 20
    float secondsPerFrame;            // +0x2c 0.05
    float frameTime;                  // +0x30 the manager's, seconds an update
    float timeScale;                  // +0x34 1
    Coord4 *offset;                   // +0x38 (0, 0, 0, 0), new
    Coord4 *scale;                    // +0x3c (1, 1, 1, 1), new
    ActCrossFadeBlendData *crossFade; // +0x40 while cross-fading
    ActIKSolverArray *ikSolvers;      // +0x44
    ActGlobalPoseOverrideArray *poseOverrides;   // +0x48
    bool suppressTranslation;         // +0x4c the root bone's x and z left at 0 (ActActor::SetSuppressAnimationTranslation)
    uint8_t unknown4d[3];
    int32_t mode;                     // +0x50 ActPoseMode
    // kPoseModeManual's times and weight, written by the actor: pose = the first times blended towards the second
    // by the weight; the events fired between the last two.
    float manualFromPrevious;         // +0x54
    float manualFromTime;             // +0x58
    float manualToPrevious;           // +0x5c
    float manualToTime;               // +0x60
    float manualWeight;               // +0x64
    float manualEventPrevious;        // +0x68
    float manualEventTime;            // +0x6c

    ActPoser* Construct(ActSkeleton *skeleton, ActEvents *events, bool mirrored, bool hasMatrixCallback);   // 0x00018550
    void Destruct();                                                            // 0x00019580

    int GetBoneIndex(const char *name);                                         // 0x000186e0
    void GetRootBonePosOri(MATRIX4 *out);                                       // 0x000186f0
    // The global matrix of the skeleton's weapon bone (0) or clip bone (1)
    void GetWeaponBonePosOri(int which, MATRIX4 *out);                          // 0x00018720

    // The placement's translation, without recomputing the root's matrix (ChangeAnimationOrigin) or with it.
    void ChangeAnimationOrigin(const Coord3 *origin);                           // 0x00018750
    void SetAnimationOrigin(const Coord3 *origin);                              // 0x00018b30
    void GetAnimationOrigin(Coord3 *out);                                       // 0x00018780
    void GetInitialTbOu(MATRIX4 *out);                                          // 0x000187b0
    void SetInitialTbOu(const MATRIX4 *placement);                              // 0x00018b80
    // The placement turned by `turns` about y (Rotate) or x (RotateX), before it.
    void Rotate(float turns);                                                   // 0x00018bd0
    void RotateX(float turns);                                                  // 0x00018cf0

    // Starts the animation `seconds` in.
    void SetNormalAnimation(ActAnimGroup *animation, float seconds, const MATRIX4 *placement);   // 0x00018fe0
    // A copy of the current animation and matrices to fade from over `seconds`.
    void SetupCrossFadeBlend(float seconds, bool unknown);                      // 0x000187d0
    // Starts the animation from its first frame, fading from the copy SetupCrossFadeBlend made.
    void SetCrossFadeBlendAnimation(ActAnimGroup *animation, const MATRIX4 *placement);   // 0x00019040
    // The cross-fade's times: the copy's previous and current, the animation's, and the blend weight.
    void CalcCrossFadeTimes(float *fadePrevious, float *fadeTime, float *previous, float *time, float *weight);   // 0x00018850
    // Back to the animation alone, at the frame the fade had reached; the copy freed.
    void FinishCrossFadeBlend();                                                // 0x00019610
    // The placement, and the root-bone matrices from the animation's pose at the current time.
    void CalcSnapAndCorrectionMatrices(const MATRIX4 *placement);               // 0x00018e10

    void AdvanceTime();                                                         // 0x00019710
    void DoEventPose();                                                         // 0x00018960
    // The pose at nextTime into the skeleton's local matrices, the root bone moved by kPoseToWorld.
    void DoMainPose();                                                          // 0x000190b0
    void DoIK();                                                                // 0x000196d0
    void DoSkeletonPose();                                                      // 0x00019750
    // DoSkeletonPose at frame 0, nextTime kept.
    void DoInitialPoses();                                                      // 0x000197c0
    void Skin();                                                                // 0x00018940

    // The frames one update advances (inline in the original; CalcCrossFadeTimes multiplies frameTime by timeScale
    // first, the same exact product).
    double FrameStep() const {
        return (double)timeScale * frameTime * framesPerSecond;
    }

private:
    // kPoseToWorld = RootOffset * RootTurn * TbOu (inline in the original after each change).
    void UpdatePoseToWorld();
};
static_assert(offsetof(ActPoser, skeleton) == 0x04, "ActPoser::skeleton is at +0x04");
static_assert(offsetof(ActPoser, matrices) == 0x24, "ActPoser::matrices is at +0x24");
static_assert(offsetof(ActPoser, crossFade) == 0x40, "ActPoser::crossFade is at +0x40");
static_assert(offsetof(ActPoser, mode) == 0x50, "ActPoser::mode is at +0x50");
static_assert(sizeof(ActPoser) == 0x70, "an ActPoser is 0x70 bytes");

#endif // DRIVING_ANIM_POSER_H_
