#ifndef DRIVING_GAME_AISPLINEPATH_H_
#define DRIVING_GAME_AISPLINEPATH_H_

// ---------------------------------------------------------------------------------------------------------------
// AISplinePath (0xb0 bytes, new'd by AIVehicle::SetSplinePath and RWorldCamera): an AI spline (CARP::AISpline)
// played as a path. It holds an instance of its own and that instance's proc-anim state, and the renderer's path
// engine moves the instance along the spline's path; the AI reads the instance's frame. See AISplinePath.cpp.
// ---------------------------------------------------------------------------------------------------------------

#include <stddef.h>
#include <stdint.h>

#include "../autogenerated_layouts.h"   // MATRIX4
#include "../data/Carp.h"               // CARP::Instance, CARP::AISpline
#include "../world/World.h"             // ProcAnimState

struct RPathHandle;


class AISplinePath {
public:
    CARP::Instance instance;        // +0x00 what the path moves (axes and position from the identity at first)
    ProcAnimState procAnim;         // +0x40 a path's: the spline's path, running, at half speed
    RPathHandle *path;              // +0x60
    uint8_t unknown64[0xc];
    MATRIX4 placement;              // +0x70 the spline's transform (CARP::AISpline::GetApplyTransform)

    AISplinePath* Construct(CARP::AISpline *spline);                                            // 0x00035680
    void Destruct();                                                                            // 0x00035730
    // The path started again along the spline
    void Reset(CARP::AISpline *spline);                                                         // 0x00035740
    // The spline's path is the one taken at the end of the current one
    void SetNext(CARP::AISpline *spline);                                                       // 0x00035780
};
static_assert(sizeof(AISplinePath) == 0xb0, "an AI spline path is 0xb0 bytes");
static_assert(offsetof(AISplinePath, procAnim) == 0x40 && offsetof(AISplinePath, path) == 0x60 &&
              offsetof(AISplinePath, placement) == 0x70, "AISplinePath layout");

#endif // DRIVING_GAME_AISPLINEPATH_H_
