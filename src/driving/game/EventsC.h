// A place in the CARP data (0x40 bytes; the name is ours): a position, and a second vector 0x30 on - the direction
// EResetPlayerCarPos faces the car, the rotation EPlayGiottoEffect plays its effect at
struct EventPlace {
    Coord4 position;                    // +0x00
    uint8_t unknown10[0x20];
    Coord4 direction;                   // +0x30
};
static_assert(sizeof(EventPlace) == 0x40, "EventPlace is 0x40 bytes");

// ---- the paths

// Each tick while its path runs, moves its sound with the path; once the path has stopped, plays the end patch once
// where the path is, deletes the sound, and removes its own task and the task's data. (EPathSFX schedules it.)
class EPathSFXUpdate : public Event {
public:
    typedef PathSFXUpdateData Record;   // EventsB.h: the task's static data

    PathSFXUpdateData *data;            // +0x04 the task's data (its `self`)
    RPathHandle *path;                  // +0x08
    ASound *sound;                      // +0x0c
    const char *endPatch;               // +0x10 played once in the "Object Sounds" mix when the path stops
    uint32_t taskNum;                   // +0x14 Schedule::AddTask's

    void Process();
    void Destruct();                                                                    // 0x00048170
    EPathSFXUpdate* Delete(unsigned flags);                                             // 0x0004cda0
};
static_assert(sizeof(EPathSFXUpdate) == 0x18, "EPathSFXUpdate is 0x18 bytes");

