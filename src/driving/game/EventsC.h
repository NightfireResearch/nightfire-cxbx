// ---------------------------------------------------------------------------------------------------------------
// The mission events from EPathSFXUpdate to ESetRecSpeedOffset (game.events, package C): the path setters, the
// effects and sounds, the animation cameras and auto-drive, the power-ups, the mission's end, pause and restart, the
// counters and objectives, and the path events' helper.
//
// The event model is EventsA.h's: an event does its work when it is destroyed. Every vtable here has one slot, slot
// 0, the scalar deleting destructor (Delete), which runs the destructor (Destruct: the class's vtable, Process, then
// Event's vtable) and gives the bytes back to the event buffer. Each class's MakeEvent callback (Ghidra: GetEventName)
// news the event from its record and, for some, from what raised it (gEventDynamicData, world/Trigger.h); the
// ResolveEvent callbacks resolve a record's references when the track loads. A few events have no work at all
// (their destructor is Event's). See EventsC.cpp.
// ---------------------------------------------------------------------------------------------------------------

