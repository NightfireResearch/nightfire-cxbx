    uint8_t unknown209[7];
    Coord3 aimPoint;                // +0x210 the guns' aim (the events port's names)
    uint32_t unknown21C;
    Coord3 leadPoint;               // +0x220 the rockets' aim
    int16_t stuckEventStep;         // +0x22c
    uint8_t stuckEvent;             // +0x22e
    uint8_t unknown22F;
