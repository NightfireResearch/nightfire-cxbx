    uint8_t stuck;                  // +0x232 it moved less than 5 in five seconds
    uint8_t unknown233;
    uint8_t unknown234[0xc];
    Coord3 stuckPosition;           // +0x240 where the count began
    uint8_t facingNav;              // +0x24c the car faces its navigator
