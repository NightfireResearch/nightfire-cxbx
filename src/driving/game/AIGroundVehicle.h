    double GetLookAhead(float speed);                                                           // 0x0002dc90
    // The controls set to drive at `speed` towards the point: a car (DriveToPoint), traffic, a sub (pitching too)
    void DriveToPoint(Coord3 *point, float speed);                                              // 0x0002f610
