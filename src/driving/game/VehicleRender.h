// ---------------------------------------------------------------------------------------------------------------
// RVehicle (0x370 bytes, "RVehicle", vtable 0x001922d0): the render object of every car (PBondCar's) and helicopter
// (PHelicopter's, made without a car). An RSkeletalObj drawn last (kDrawLast) and marked kVehicle, placed by an
// instance of its own (`instance`, the identity, the source instance its constructor hands RSkeletalObj). It turns
// its wheel and hub bones from the car's wheel spin, steering and suspension (or a submarine's fins and rudders
// from its controls), keeps the dashboard needles in its proc-anim parameters, the damage zones and switch effects
// the article's render methods read through the symbol table ("EAGL::DamageZones", "GAME::SwitchData", copied
// into the shared buffers for each draw), two muzzle flashes, a colour dissolve, the car's particles, and the EMP
// effects (the victim flag, the shooting effect's intensity and the bolts). See VehicleRender.cpp.
//
// The vtable's slots (RSceneObj's 19): 0 Delete, 1 SetViewDrawList, 2 Render, 3 RSceneObj::RenderSimple,
// 4 RenderShadow, 5 RenderDeferredEffects, 6-8 empty, 9 GetRenderOffset, 10 RSkeletalObj::SetProcAnimState,
// 11 RSceneObj::SetEventDynamicData, 12 TriggerIlluminate, 13 RSceneObj::GetVelocity, 14 UpdatePosition,
// 15 TriggerFX, 16 empty, 17 PostLoad, 18 ResolveObjectData.
// ---------------------------------------------------------------------------------------------------------------

#include <stddef.h>
#include "../Vtables.h"   // our copies of the game's vtables
#include <stdint.h>

#include "../autogenerated_layouts.h"   // MATRIX4
#include "../data/Carp.h"               // CARP::Instance
#include "../data/CoordConvert.h"       // Coord3, Coord4
#include "../render/SkeletalObj.h"
#include "../../common/xbeClass.h"      // LAYOUT_32

namespace EAGL {
struct Model;
}
class REmpBolts;
class RVehicleParticle;
struct PVehicle;

void **const kRVehicleVtable = Vtable_RVehicle;

class RVehicle : public RSkeletalObj {
public:
    static constexpr int kMuzzles = 2;
    static constexpr int kWheels = 4;
    static constexpr int kDamageZones = 16;
    static constexpr int kSwitchEffects = 16;

    // TriggerFX's types past RSceneObj's
    enum FXType : int32_t {
        kFXSparks = 6,                  // the particles' sparks at the point, with the velocity
        kFXColourDissolve = 7,          // StartColourDissolve
        kFXMuzzleFlash = 8,             // StartMuzzleFlash: `which` the muzzle, `extra` the flash's type
        kFXSwitchOn = 11,               // switchIntensity[which] 1
        kFXSwitchOff = 12,              // ... 0
    };

    // The flash types RenderFX draws (muzzleType)
    enum MuzzleType : int32_t {
        kMuzzlePOV = 2,                 // RMuzzleFlash::DrawPOV; the others RMuzzleFlash::Draw with the type
        kMuzzleTurret = 3,
        kMuzzleSnowmobileTurret = 4,    // also StartMuzzleFlash's kFlashLarge
    };

    // The switch effects (GAME::SwitchData's entries; the tuning names: "Booster [0]" ... "Misc [15]")
    enum SwitchEffect {
        kSwitchLeftButton = 9,          // these two fade over 30 ticks from their TriggerIlluminate tick
        kSwitchRightButton = 10,
    };

    // The dashboard needles (GetNeedlePos' table; params[] the index)
    enum Needle {
        kNeedleSpeed = 1,
        kNeedleRevs = 2,
        kNeedleHours = 5,
        kNeedleMinutes = 6,
    };

    CARP::Instance instance;                    // +0x0a0 the identity: the source instance
    Coord4 damageZones[kDamageZones];           // +0x0e0 ComputeDamage's (ResolveObjectData answers it for
                                                //        "EAGL::DamageZones")
    Coord4 muzzlePosition[kMuzzles];            // +0x1e0 xyz StartMuzzleFlash's; w 1 from the constructor
    Coord4 muzzleDirection[kMuzzles];           // +0x200 xyz StartMuzzleFlash's; w 0
    uint32_t muzzleEndTick[kMuzzles];           // +0x220 drawn while GameTick is below it
    int32_t muzzleType[kMuzzles];               // +0x228 MuzzleType
    float muzzleSize[kMuzzles];                 // +0x230
    float wheelHeight[kWheels];                 // +0x238 the wheel instance's height over the article's (PostLoad)
    int32_t wheelBone[kWheels];                 // +0x248 "leftfrontwheel" ...: turned in x by the wheel's spin
    int32_t hubBone[kWheels];                   // +0x258 "leftfronthub" ... (a submarine's "leftfin" ...): turned
                                                //        in y by the steering
    float switchIntensity[kSwitchEffects];      // +0x268 GAME::SwitchData's fourth floats
    int32_t switchStartTick[kSwitchEffects];    // +0x2a8 TriggerIlluminate's; -10000 at construction
    uint8_t unknown2E8[0x40];
    float steer;                                // +0x328 ComputeWheels' last steering, limited in rate
    float pitch;                                // +0x32c a submarine's: its vertical steering, limited in rate
    uint32_t colourDissolveTick;                // +0x330 StartColourDissolve's GameTick
    uint32_t viewDrawCount;                     // +0x334 SetViewDrawList's
    float rudder;                               // +0x338 a submarine's: its brake, limited in rate
    uint8_t unknown33C[0xc];
    const uint16_t *viewDrawList;               // +0x348 SetViewDrawList's; NULL draws every instance
    uint32_t *colourDissolve;                   // +0x34c the model's 'id  ' record of the variation; its first
                                                //        word a variation
    EAGL::Model *shadowModel;                   // +0x350 the nearest model of the render-type-3 article (PostLoad);
                                                //        RenderShadowGeometry draws it
    EAGL::Model *renderType4Model;              // +0x354 ... of the render-type-4 article
    RVehicleParticle *particles;                // +0x358 for a car; NULL without one
    float empShootingIntensity;                 // +0x35c above 0: REmp::DrawShootingEffect at it
    uint8_t empVictim;                          // +0x360 SetEMPVictimEffect's; RenderFX clears it
    uint32_t empVictimTick;                     // +0x364 the simulation step it was set at
    REmpBolts *empBolts;                        // +0x368 TriggerEmpBolts', operator new
    uint32_t unknown36C;

    RVehicle* Construct(PVehicle *car);                                                         // 0x000953e0
    void Destruct();                                                                            // 0x00096430
    RVehicle* Delete(unsigned flags);           // the scalar deleting destructor, vtable slot 0 // 0x000967f0

    // ---- the vtable's overrides
    void SetViewDrawList(uint32_t index);                                       // slot 1       // 0x000955b0
    void Render();                                                              // slot 2       // 0x000965e0
    void RenderShadow();                                                        // slot 4       // 0x00095b30
    void RenderDeferredEffects();                                               // slot 5       // 0x00096770
    // Half the article's height (BaseDesc::height), plus that less half its box's height; unrounded
    double GetRenderOffset();                                                   // slot 9       // 0x00095cc0
    // Switch effect `index` on from `tick`; the third argument is not read
    void TriggerIlluminate(int index, int32_t tick, int unused);                // slot 12      // 0x000959b0
    // RSkeletalObj's, then the wheels and, for the player's car, the needles
    void UpdatePosition(bool update);                                           // slot 14      // 0x000964b0
    void TriggerFX(int type, uint32_t which, uint32_t extra, const Coord3 *point, const Coord3 *direction,
                   float intensity);                                            // slot 15      // 0x00095ed0
    void PostLoad();                                                            // slot 17      // 0x000955d0
    void* ResolveObjectData(const char *name, bool *found);                     // slot 18      // 0x00095560

    // ---- the shared buffers (GAME::SwitchData, EAGL::DamageZones)
    static void InitSharedBuffers();            // their defaults, and the switch effects' tuning // 0x000958a0
    static void ClearSharedBuffers();                                                           // 0x00095970
    // This car's switch intensities (the two buttons faded) and damage zones into them
    void SetPerObjectBuffers();                                                                 // 0x00095ff0

    // ---- effects
    void SetEMPVictimEffect(bool on);                                                           // 0x000959d0
    void TriggerTurboBoostSmoke(int ticks);     // the particles' tyre smoke                    // 0x000959f0
    void TriggerEmpBolts();                                                                     // 0x00095a10
    // A flash at the muzzle unless its last is still drawn; `type` 45 is a large one (kMuzzleSnowmobileTurret)
    void StartMuzzleFlash(const Coord3 *position, const Coord3 *direction, int muzzle, int type);  // 0x00095ce0
    // The model's colour variation record for the current variation, made current; the arguments are not read
    void StartColourDissolve(uint32_t unused1, uint32_t unused2);                               // 0x00095e20
    // The muzzle flashes, the particles, the EMP effects and the article's effects
    void RenderFX(const MATRIX4 *transform);                                                    // 0x00095b60

    // ---- drawing helpers
    // The car's damage zones into damageZones (zero without physics)
    void ComputeDamage();                                                                       // 0x00095a80
    // A needle's position for a value; unrounded
    double GetNeedlePos(int needle, float value);                                               // 0x00095c60
    // The wheel and hub bones from the car; answers the steering (0 without a car)
    float ComputeWheels();                                                                      // 0x00096060
    void RenderShadowGeometry();                // shadowModel, if any                          // 0x00096410
};
LAYOUT_32(sizeof(RVehicle) == 0x370, "RVehicle is 0x370 bytes");
LAYOUT_32(offsetof(RVehicle, instance) == 0xa0 && offsetof(RVehicle, damageZones) == 0xe0 &&
          offsetof(RVehicle, muzzlePosition) == 0x1e0 && offsetof(RVehicle, muzzleEndTick) == 0x220 &&
          offsetof(RVehicle, muzzleSize) == 0x230 && offsetof(RVehicle, wheelHeight) == 0x238 &&
          offsetof(RVehicle, hubBone) == 0x258 && offsetof(RVehicle, switchIntensity) == 0x268 &&
          offsetof(RVehicle, switchStartTick) == 0x2a8 && offsetof(RVehicle, steer) == 0x328 &&
          offsetof(RVehicle, rudder) == 0x338 && offsetof(RVehicle, viewDrawList) == 0x348 &&
          offsetof(RVehicle, particles) == 0x358 && offsetof(RVehicle, empVictim) == 0x360 &&
          offsetof(RVehicle, empBolts) == 0x368, "RVehicle layout");

// A switch effect's entry in GAME::SwitchData, what the article's render methods read
struct SwitchEffectData {
    float vScroll;                      // +0x00 "V Scroll"
    float glow;                         // +0x04 "Glow"
    float illuminate;                   // +0x08 "Illuminate"
    float intensity;                    // +0x0c the car being drawn's switchIntensity
};

// The buffers the symbol table hands the render methods ("GAME::SwitchData", "EAGL::DamageZones",
// data/RCARPFile.cpp's RegisterSymbols), filled for each car drawn
struct VehicleSharedBuffers {
    SwitchEffectData switches[RVehicle::kSwitchEffects];    // +0x000
    Coord4 damageZones[RVehicle::kDamageZones];             // +0x100
};
static_assert(sizeof(VehicleSharedBuffers) == 0x200, "the shared buffers are 0x200 bytes");

alignas(16) extern VehicleSharedBuffers VehicleBuffers;

extern uint32_t SwitchEffectIndex;          // the switch effects' tuning index (dbindex's)
extern int32_t ClearEmpVictim;              // 1: RenderFX clears empVictim (nothing sets it; the name is ours)

// FUN_00095f90: a switch effect's fade, EAX the tick now, ECX its start tick (the adaptor, under Ghidra's name)
void FUN_00095f90();
// ... its C++: 1 at the start falling to 0 over 30 ticks; 0 before the start or for a start of 0 or less (the name
// is ours)
float SwitchEffectFade(uint32_t now, int32_t start);

#endif // DRIVING_GAME_VEHICLERENDER_H_
