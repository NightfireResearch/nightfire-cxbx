// FUNC_AT(0x000e3fd0)
void GSystem::CURATOR_Init() {
    sprintf(GfxDataPath, "%s", "data/gfx/data/");
    GfxRandomMultiplier = 123456789;
    uint32_t seed = 987654321;
    for (int i = 0; i < 175; i++)
        seed = (seed * 0xffffcd15u) & 0xffff;   // times -13035
    GfxRandomState = seed;
    GFX::Init();
    LOCALE_LoadLanguage(GLocale::GetLanguage());
}

// FUNC_AT(0x000e3eb0)
void CURATOR_Shutdown() {
    GFX::Shutdown();
    if (LocaleFile != NULL) {
        MEM_free(LocaleFile);
        LocaleFile = NULL;
    }
}

