// FUNC_AT(0x000e3b40)
void GSystem::MATH_TransformPoints(Coord4 *point, const Coord4 *position, const Coord4 *orientation,
                                   const Coord4 *scale) {
    Coord4 rotation = *orientation;
    MATRIX4 transform;
    VU0_quattom4(&transform, &rotation);
    MATRIX4_multscale(&transform, scale, &transform);
    Coord4 transformed = *point;
    VU0_MATRIX4_vect4mult(&transformed, &transform, &transformed);
    *point = transformed;
    point->x = point->x + position->x;
    point->y = position->y + point->y;
    point->z = position->z + point->z;
}

// FUNC_AT(0x000e3c30)
uint32_t GSystem::COLOR_Interpolate(uint32_t from, uint32_t to, float t) {
    uint32_t colour = 0;
    for (int shift = 0; shift < 32; shift += 8) {
        int a = (from >> shift) & 0xff;
        int b = (to >> shift) & 0xff;
        uint8_t channel = uint8_t(Ftol(double(b - a) * t + a));
        colour |= uint32_t(channel) << shift;
    }
    return colour;
}

// FUNC_AT(0x000e3cf0)
void GSystem::COLOR_ReduceAlpha(uint32_t *colour, float alpha) {
    uint8_t reduced = uint8_t(Ftol(double(int(*colour >> 24)) * alpha));
    *colour = (*colour & 0x00ffffff) | uint32_t(reduced) << 24;
}

