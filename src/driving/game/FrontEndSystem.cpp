// FUNC_AT(0x000e3d20)
bool GSystem::IsEARS() {
    return MissionIs("junglea_mis13a") || MissionIs("jungleb_mis13b") || MissionIs("junglec_mis13c") ||
           MissionIs("junglea") || MissionIs("jungleb") || MissionIs("junglec");
}

// FUNC_AT(0x000e3db0)
bool GSystem::IsSavage() {
    return MissionIs("snow1a_mis3") || MissionIs("snow2a_mis4") || MissionIs("snow1a") || MissionIs("snow2a");
}

// FUNC_AT(0x000e3e20)
const char* GSystem::GetGalleryName() {
    if (IsSavage())
        return "sav_gall1.gal";
    if (IsEARS())
        return "ears_gall1.gal";
    return "gall1.gal";
}

// FUNC_AT(0x000e3e50)
const char* GetParticFileForMission() {
    if (GSystem::IsSavage())
        return "sav_partic01.xsh";
    if (GSystem::IsEARS())
        return "ears_partic01.xsh";
    if (MissionIs("uw_map") || MissionIs("uw_mis11"))
        return "partic02.xsh";
    return "partic01.xsh";
}
