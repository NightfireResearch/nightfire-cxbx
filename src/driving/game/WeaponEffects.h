#ifndef DRIVING_GAME_WEAPONEFFECTS_H_
#define DRIVING_GAME_WEAPONEFFECTS_H_

// ---------------------------------------------------------------------------------------------------------------
// The weapons' render effects (game tier). See WeaponEffects.cpp.
//   RBulletStreak: the tracers. Each shot adds a quad along its path to one of four batches (one per streak
//     texture), drawn and emptied once a frame; the look of each kind of shooter is tuning ("BulletStreak...").
//   RMissileStreak (0x610 bytes, inside each Missile and Grenade): the smoke trail, pairs of points either side of
//     the path laid every second update, drawn as a strip of the newest forty through one of three GeoPrims.
//   RMuzzleFlash: the flash at a gun's muzzle - a 26-vertex model drawn through one of five materials - and the
//     player's view of it, a quad with a texture picked at random from its type's three.
//   RScorchWorld: scorch marks, RDecalManager's quads laid on walls and the ground.
// ---------------------------------------------------------------------------------------------------------------

#include <stddef.h>
#include <stdint.h>

#include "../autogenerated_layouts.h"     // MATRIX4
#include "../data/CoordConvert.h"         // Coord3, Coord4
#include "../render/Materials.h"          // TexturedGeoPrim, UVolatileMaterial

namespace EAGL {
struct TAR;
}
class WWorldPos;

// ---- RBulletStreak

// One kind of shooter's streaks (0x18 bytes; dbindex "BulletStreakType": Henchmen, Vanquish, SuperSnowmobile, SUV,
// Captain, Ultralight, Sentinel)
struct BulletStreakKind {
    uint32_t colour;                    // +0x00 "BulletStreakColour", 0xAARRGGBB
    int32_t texture;                    // +0x04 "BulletStreakTexture": the batch, 0..3
    float width;                        // +0x08 "BulletStreakWidth": the quad's half width
    float length;                       // +0x0c "BulletStreakLength"
    float speed;                        // +0x10 "BulletStreakSpeed" (Shell and RayShell read it)
    int32_t count;                      // +0x14 "BulletStreakCount" (EFireWeapon reads it)
};
static_assert(sizeof(BulletStreakKind) == 0x18, "a bullet streak kind is 0x18 bytes");

constexpr int kBulletStreakKinds = 7;
constexpr int kBulletStreakTextures = 4;
constexpr int kBulletStreakVertices = 128;      // a batch's, six a streak

struct EffectUV {                       // a vertex's texture coordinates
    float u, v;
};

class RBulletStreak {
public:
    // The batches' textures, vertices and materials, and the tuning
    static void Init();                                                                         // 0x00099f10
    // Every batch drawn and emptied, depth writes off
    static void Draw();                                                                         // 0x00099e20
    // A quad from `position` back along `direction` (a unit vector), facing the first player's camera, into its
    // kind's batch unless that is full
    static void Add(const Coord4 *position, const Coord4 *direction, int kind);                 // 0x0009a1d0
    // The same from three-component vectors, their w 1
    static void Add(const Coord3 *position, const Coord3 *direction, int kind);                 // 0x0009a3b0
};

// The kinds' tuning (game code still reads it at its address)
#define BulletStreakKinds ((BulletStreakKind *)0x001f2e20)
// The batches: their vertex counts, textures, texture coordinates, positions, colours and materials
extern int32_t BulletStreakCounts[kBulletStreakTextures];
extern EAGL::TAR *BulletStreakTextures[kBulletStreakTextures];
extern EffectUV BulletStreakUVs[kBulletStreakTextures][kBulletStreakVertices];
extern Coord4 BulletStreakPositions[kBulletStreakTextures][kBulletStreakVertices];
extern uint32_t BulletStreakColours[kBulletStreakTextures][kBulletStreakVertices];
extern UVolatileMaterial BulletStreakMaterials[kBulletStreakTextures];     // the static initialisers construct them
extern uint32_t BulletStreakKindIndex;          // dbindex's
extern uint8_t BulletStreakColourFlag;          // dbattrib_argb's unused flag byte
extern const char *const BulletStreakKindNames[kBulletStreakKinds];

// ---- RMissileStreak

constexpr int kMissileStreakTypes = 3;
constexpr int kMissileStreakDrawn = 40;         // the strip's vertices at most

class RMissileStreak {
public:
    static constexpr int kMaxPoints = 0x60;

    int32_t count;                      // +0x00 the points laid, two at a time
    int32_t tick;                       // +0x04 the updates
    int32_t type;                       // +0x08 0..2: the GeoPrim, its texture, the width and jitter
    uint32_t unknown0C;
    Coord4 points[kMaxPoints];          // +0x10 in pairs, either side of the path

    // One more update with nothing laid (Missile::Render's when the missile's hit does not count)
    void Update();                                                                              // 0x000a0e90
    // A pair laid at `position` (every second update; between, the newest pair moves), until the trail is full
    void Update(const Coord4 *position);                                                        // 0x000a0ea0
    // The newest pairs as a strip, depth writes off
    void Draw();                                                                                // 0x000a1330
    // The three GeoPrims, their textures, colours and texture coordinates
    static void Init();                                                                         // 0x000a1070
    static void Kill();                 // the GeoPrims freed                                    // 0x000a1460
};
static_assert(sizeof(RMissileStreak) == 0x610, "a missile streak is 0x610 bytes");
static_assert(offsetof(RMissileStreak, points) == 0x10, "RMissileStreak layout");

extern TexturedGeoPrim *MissileStreakGeoPrims[kMissileStreakTypes];
extern uint32_t MissileStreakVertexCounts[kMissileStreakTypes][4];     // each GeoPrim's vertex count record
extern Coord4 MissileStreakUVs[kMissileStreakDrawn + 2];               // the strip's, from two phases
extern EAGL::GeoPrimState MissileStreakState;                          // the static initialisers construct it
extern uint32_t MissileStreakColours[kMissileStreakDrawn];
extern float MissileStreakHalfWidths[kMissileStreakTypes];
extern float MissileStreakJitter[kMissileStreakTypes];

// ---- RMuzzleFlash

constexpr int kMuzzleFlashTypes = 5;
constexpr int kMuzzleFlashVertices = 26;
constexpr int kMuzzleFlashPOVTypes = 8;

// One type of the player's view of a flash: three textures (0x18 bytes)
struct MuzzleFlashPOVType {
    uint32_t names[3];                  // +0x00
    EAGL::TAR *textures[3];             // +0x0c InitPOVLayer's
};
static_assert(sizeof(MuzzleFlashPOVType) == 0x18, "a POV flash type is 0x18 bytes");

class RMuzzleFlash {
public:
    // The five textures and materials, the POV quad, and the model turned a quarter round y
    static void Init();                                                                         // 0x000a1b50
    static void InitPOVLayer();                                                                 // 0x000a14b0
    // The model at `position` along `direction` (y up), scaled by a quarter of `size`, then by `transform`
    static void Draw(const MATRIX4 *transform, const Coord4 *position, const Coord4 *direction, int type,
                     float size);                                                               // 0x000a1870
    // The POV quad at `position`, scaled by `size`, then by `transform`; unpaused, a random texture and turn
    static void DrawPOV(const MATRIX4 *transform, const Coord4 *position, int type, float size);  // 0x000a19d0
};

extern EAGL::TAR *MuzzleFlashTextures[kMuzzleFlashTypes];
extern Coord4 MuzzleFlashPositions[kMuzzleFlashVertices];          // turned by every Init
extern const EffectUV MuzzleFlashUVs[kMuzzleFlashVertices];
extern uint32_t MuzzleFlashColours[kMuzzleFlashVertices];
extern UVolatileMaterial MuzzleFlashMaterials[kMuzzleFlashTypes];  // the static initialisers construct them
extern UVolatileMaterial MuzzleFlashPOVMaterial;                   // ... and this
extern Coord4 MuzzleFlashPOVPositions[4];
extern EffectUV MuzzleFlashPOVUVs[4][4];                      // four turns of the quad
extern MuzzleFlashPOVType MuzzleFlashPOVTypes[kMuzzleFlashPOVTypes];

// ---- RScorchWorld

class RScorchWorld {
public:
    // A mark `size` across on the face under `point` (`normal` its normal; the size at most 6), when the face
    // takes one; a wall's also runs down to the ground it stands on
    static void ScorchWorld(WWorldPos *place, const Coord4 *point, const Coord4 *normal, float size,
                            int type);                                                          // 0x000a50c0
    // A mark on the ground under `point`, half `size` round it at most (6 at most), shrunk by the height above it,
    // when the ground is level there (type 4 skips the test of the ground round it)
    static void ScorchGround(WWorldPos *place, const Coord4 *point, float size, int type);       // 0x000a5530
};

#endif // DRIVING_GAME_WEAPONEFFECTS_H_
