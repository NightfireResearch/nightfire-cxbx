// FUNC_AT(0x000d3730)
void CANVAS_GetPosQuat(GFXGallery::Canvas *effectData, Coord4 *position, Coord4 *orient) {
    if (Misaligned(effectData))
        AssertMessage(kAssertFormat, kGalleryFile, 44, "(unsigned)(&effectData)");
    if (Misaligned(position))
        AssertMessage(kAssertFormat, kGalleryFile, 45, "(unsigned)(&position)");
    if (Misaligned(orient))
        AssertMessage(kAssertFormat, kGalleryFile, 46, "(unsigned)(&orient)");

    if (effectData->sceneObj == NULL) {
        VU0_v4copy(&effectData->worldOrientation, orient);
        VU0_v3add(&effectData->position, &effectData->offset, position);
        position->w = 1.0f;
        return;
    }
    alignas(16) MATRIX4 transform;
    alignas(16) Coord4 rotation;
    effectData->sceneObj->GetInstancePosition(effectData->instance, &transform, true);
    VU0_m4toquat(&rotation, &transform);
    D3DXQuaternionMultiply(orient, &effectData->orientation, &rotation);
    position->x = effectData->offset.x;
    position->y = effectData->offset.y;
    position->z = effectData->offset.z;
    position->w = 1.0f;
    VU0_MATRIX4_vect4mult(position, &transform, position);
}

