// FUNC_AT(0x000d33f0)
void GFX::Init() {
    void *memory = OperatorNew(sizeof(GFXGallery));
    TheEffectsGallery = memory != NULL ? static_cast<GFXGallery *>(memory)->Construct(GSystem::GetGalleryName())
                                       : NULL;
}

// FUNC_AT(0x000d35d0)
void GFX::Shutdown() {
    GFXGallery *gallery = TheEffectsGallery;
    if (gallery != NULL) {
        gallery->Destruct();
        OperatorDelete(gallery);
    }
}

int GFX::Trigger(GFXGallery *gallery, bool incidental, UGroup *effect, const Coord3 *position,
                 const Coord4 *worldOrientation, const Coord3 *offset, const Coord4 *orientation,
                 RSceneObj *sceneObj, int instance, const Coord3 *velocity) {
    if (effect == NULL)
        return 0;
    uint32_t flags = 0;
    UData *item = effect->DataLocateTag(kTagFlags);
    if (item != effect->DataEnd())
        flags = *reinterpret_cast<const uint32_t *>(item->Data());
    Coord4 where = {position->x, position->y, position->z, 1.0f};
    Coord3 offsetCopy = *offset;
    bool flag01 = (flags & kEffectFlag01) != 0;
    bool takeVelocity = (flags & kEffectTakeVelocity) != 0;
    int handle = gallery->CANVAS_Add(effect, sceneObj, instance, &where, worldOrientation, &offsetCopy, orientation,
                                     velocity, flag01, takeVelocity, incidental && flag01);
    if (flag01)
        return 0;
    return handle;
}

// FUNC_AT(0x000d34e0)
int GFX::Trigger(UGroup *effect, const Coord3 *position, const Coord4 *worldOrientation, const Coord3 *offset, const Coord4 *orientation, RSceneObj *sceneObj, int instance, const Coord3 *velocity) {
    return Trigger(TheEffectsGallery, false, effect, position, worldOrientation, offset, orientation, sceneObj,
                   instance, velocity);
}

// FUNC_AT(0x000d3520)
int GFX::TriggerIncidental(UGroup *effect, const Coord3 *position, const Coord4 *worldOrientation,
                           const Coord3 *offset, const Coord4 *orientation, RSceneObj *sceneObj, int instance,
                           const Coord3 *velocity) {
    return Trigger(TheEffectsGallery, true, effect, position, worldOrientation, offset, orientation, sceneObj,
                   instance, velocity);
}

// FUNC_AT(0x000d3610)
int GFX::Trigger(const char *name, const Coord3 *position, const Coord4 *worldOrientation, const Coord3 *offset, const Coord4 *orientation, RSceneObj *sceneObj, int instance, const Coord3 *velocity) {
    return Trigger(TheEffectsGallery, false, LookupReference(name), position, worldOrientation, offset,
                   orientation, sceneObj, instance, velocity);
}

// FUNC_AT(0x000d35f0)
UGroup* GFX::LookupReference(const char *name) {
    // GGallery's GET_Canvas, which does not read `this`, called on the effects gallery
    return reinterpret_cast<GGallery *>(TheEffectsGallery)->GET_Canvas(TheEffectsGallery->GET_EffectsGallery(), name);
}

