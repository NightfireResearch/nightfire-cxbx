const char kGalleryFile[] = "d:\\ToBurn\\Bond\\source\\Giotto\\common\\GFXGallery.cpp";
const char kAssertFormat[] = "%s(%d):\nassertion failure\n(%s)\n";

bool Misaligned(const void *pointer) {
    return (reinterpret_cast<uintptr_t>(pointer) & 0xf) != 0;
}

