// ---- the zones

// AIZone::type (names ours): the types with a radius
enum AIZoneType : int32_t {
    kZoneType1 = 1,                 // never registered
    kZoneType2 = 2,
    kZoneType3 = 3,
    kZoneType4 = 4,
};
constexpr int kZoneTypes = 5;
constexpr int kZones = 30;

struct AIZone {
    uint8_t active;                 // +0x00
    uint8_t unknown01[3];
    Coord3 position;                // +0x04
    float radiusSquared;            // +0x10 the type's
    int16_t stepsLeft;              // +0x14 the zone ends when it reaches 0
    uint8_t unknown16[2];
    int32_t type;                   // +0x18 AIZoneType

    AIZone* Construct();                                                                        // 0x00036a00
};
static_assert(sizeof(AIZone) == 0x1c && offsetof(AIZone, stepsLeft) == 0x14 && offsetof(AIZone, type) == 0x18,
              "a zone is 0x1c bytes");

class AIZoneController {
public:
    static AIZoneController* Get();                                                             // 0x00036a10
    // The instance, the types' sizes and lives, and every zone ended
    static void Init();                                                                         // 0x00036a20
    // Each step: the zones' steps counted down, and ended at 0
    void Update();                                                                              // 0x00036ac0
    static void Shutdown();                                                                     // 0x00036b00
    // The point's distance squared from the zone, less `margin` (at least 0), within the zone's type's radius
    // squared; false for a zone not active
    bool InZone(int zone, const Coord3 *point, float margin);                                   // 0x00036b20
    // A new zone of the type at the position, unless the type has none or a young enough zone of the type
    // already covers it (or all thirty are active)
    void RegisterZone(int type, const Coord3 *position);                                        // 0x00036bb0
};
static_assert(sizeof(AIZoneController) == 1, "Init news one byte for the zone controller");

// The zone controller's statics (0x001e1ee8-0x001e2268; names ours). Type 0's entries are never set.
struct AIZoneStatics {
    float radiusSquared[kZoneTypes];    // +0x00 by type
    int16_t mergeSteps[kZoneTypes];     // +0x14 by type: a registration inside a zone of its type with this many
                                        //       steps left or more is dropped; 0 or less: none registered
    uint8_t unknown1e[2];
    int16_t lifeSteps[kZoneTypes];      // +0x20 by type: a new zone's steps
    uint8_t unknown2a[2];
    AIZoneController *instance;         // +0x2c
    int16_t activeCount;                // +0x30
    uint8_t unknown32[2];
    float unknown34;                    // +0x34 a static initialiser's constant (not the controller's)
    AIZone zones[kZones];               // +0x38
};
static_assert(sizeof(AIZoneStatics) == 0x380 && offsetof(AIZoneStatics, instance) == 0x2c &&
              offsetof(AIZoneStatics, zones) == 0x38, "the zone statics");

extern AIZoneStatics AIZoneData;

