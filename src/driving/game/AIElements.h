// ---- the elements

// The level's record is data/Carp.h's
using CARP::AIElement;
using CARP::AIElementCharacterInfo;
using CARP::AIElementType;
using CARP::kAIElementCharacter;
using CARP::kAIElementVehicle;

// AIElement::state (names ours)
enum AIElementState : int32_t {
    kElementAsleep = 0,             // WakeUp spawns it
    kElementAwake = 1,              // its objects are in the Simulation
    kElementDead = 2,               // it went to sleep dead (or its car wrecked): never woken again
};

// AIElement::flags
enum AIElementFlag : uint16_t {
    kElementFlag01 = 0x01,          // GoToSleep and SyncRuleInfo leave the transform as it is
    kElementDeactivated = 0x02,     // EDeactivateAIElement's: not woken, and sent to sleep while awake
    kElementForceAwake = 0x04,      // woken whatever its range, and never sent to sleep by its tracking
    kElementTargetBeacon = 0x08,    // ETargetBeaconOnOff's: a car spawns as class 2 rather than 4; a character
                                    //   registers a target
    kElementWoken = 0x10,           // WakeUp has run once: its enemies are counted only the first time
    kElementMightAsWellBeDead = 0x20,   // its car is crippled (CalcMightAsWellBeDead counts it)
    kElementNonScoreable = 0x40,    // EAIElementSetNonScoreable's
};

// AIElement::difficulty: the mission manager's difficulties (0-2) the element appears at; any other value, all
enum AIElementDifficulty : int16_t {
    kElementHarder = 1,             // 1 and 2
    kElementHardest = 2,            // 2
    kElementEasiest = 3,            // 0
    kElementMedium = 4,             // 1
    kElementEasier = 5,             // 0 and 1
    kElementNotMedium = 6,          // 0 and 2
};

// A member's seat in its vehicle (the attribute names say where it sits; names ours)
enum AIElementSeat : int32_t {
    kSeatWindow = 3,                // AICharacterEnemyWindow at AIC_EWIND_POS
    kSeatSunroof = 4,               // AICharacterEnemySunroof at AIC_ESUNR_POS
    kSeatSnow = 14,                 // AICharacterEnemySnow at AIC_ESNOW_POS
    kSeatGunner = 15,               // AICharacterEnemySSnow (weapon 1) at AIC_EVGUN_POS
    kSeatSnowDriver = 16,           // AICharacterEnemySSnow (weapon 0) at AIC_EVDRI_POS
    kSeatDriver = 17,               // AICharacterEnemyDriver at AIC_BOND_POS
};

// A character element's kind: the three made as ground enemies (names ours)
enum AIElementGroundKind : int32_t {
    kGroundEnemy = 0,
    kGroundEnemy10 = 10,            // the ground enemy's unknown17c set
    kGroundWorker = 18,             // the ground enemy's worker set
};

// AIElementCharacterInfo::skill: the character's range is multiplied (names ours)
enum AIElementSkill : int32_t {
    kSkill1 = 1,                    // a ground enemy dies where it stands (claustrophobic)
    kSkill2 = 2,                    // range doubled
    kSkill3 = 3,                    // a rider's range tripled, a ground enemy's multiplied by sqrt(30)
    kSkill4 = 4,                    // doubled, and claustrophobic
    kSkill5 = 5,                    // as kSkill3, and claustrophobic
};

// What the elements did while awake, from the controller's last Update (GetStats; the mission rules read them)
struct AIElementStats {
    float maxHitPoints;             // +0x00
    float minHitPoints;             // +0x04
    float maxDamage;                // +0x08 the most hit points lost in one look
    float maxSpeed;                 // +0x0c
    float minSpeed;                 // +0x10
    float maxDistance;              // +0x14 from the player
    float minDistance;              // +0x18
};
static_assert(sizeof(AIElementStats) == 0x1c, "the element stats are 7 floats");

// The controller's range list: an element and its tracking's closeness, for qsort
struct AIElementRange {
    int32_t index;
    float closeness;
};

class AIElementTracking {
public:
    int32_t nextUpdate;             // +0x00 the step it is next looked at
    int32_t interval;               // +0x04 steps between looks: 1 in range, else growing to 4
    float distance;                 // +0x08 from the player
    float closeness;                // +0x0c the camera's facing towards it (0 behind, 1 ahead) over the distance;
                                    //       1 when on the player
    float wakeRange;                // +0x10 200 unless the events set it
    float sleepRange;               // +0x14 20 more
    uint8_t inRange;                // +0x18 within wakeRange at the last look
    uint8_t wake;                   // +0x19 the controller's choice at its last Update
    uint8_t unknown1a[2];
    AIElement *element;             // +0x1c
    AIElementController *controller;    // +0x20
    uint8_t unknown24[0xc];
    Coord3 position;                // +0x30 the element's, at the last look
    float speed;                    // +0x3c
    float lastHitPoints;            // +0x40 at the last look (not set before the first)
    uint8_t unknown44[0xc];

    // The ranges (only a positive range is taken)
    void SetWakeRange(float range);                                                             // 0x00027cb0
    // "EMPTY", "BLOWOUT", "SMOKED", "OILED" or "AWAKE" of the element; false for any other name
    bool GetProperty(const char *name);                                                         // 0x00027ce0
    // position, distance, closeness, speed and lastHitPoints from the element, the controller's stats from them,
    // and kElementMightAsWellBeDead for a crippled car
    void UpdatePosition(const Coord4 *player);                                                  // 0x00027f00
    // When due: UpdatePosition, inRange and the interval, and the element sent to sleep if deactivated or beyond
    // sleepRange
    void Update(const Coord4 *player);                                                          // 0x00028ab0
};
static_assert(sizeof(AIElementTracking) == 0x50, "an element's tracking is 0x50 bytes");
static_assert(offsetof(AIElementTracking, inRange) == 0x18 && offsetof(AIElementTracking, element) == 0x1c &&
              offsetof(AIElementTracking, position) == 0x30 && offsetof(AIElementTracking, lastHitPoints) == 0x40,
              "element tracking layout");

class AIElementController {
public:
    int32_t characterSlots;         // +0x00 the level's HENCH_SLOTS_AVAIL, else 32
    int32_t carSlots;               // +0x04 VEHICLE_SLOTS_AVAIL, else 6
    int32_t helicopterSlots;        // +0x08 HELI_SLOTS_AVAIL, else 16
    AIElement *elements;            // +0x0c the copies
    AIElement *carpElements;        // +0x10 the level's records (RedirectCarpElement maps them to the copies)
    AIElementTracking *tracking;    // +0x14 by element
    AIElementTracking *trackingBlock;   // +0x18 its allocation
    AIElementStats stats;           // +0x1c
    int32_t *wakeList;              // +0x38 Update's sleeping elements in range
    AIElementRange *rangeList;      // +0x3c ... and every element in range
    int32_t count;                  // +0x40
    int32_t awakeCharacters;        // +0x44
    int32_t awakeCars;              // +0x48
    int32_t awakeHelicopters;       // +0x4c
    int32_t cars;                   // +0x50 the awake cars and those Update last wanted to wake
    int32_t mightAsWellBeDead;      // +0x54 CalcMightAsWellBeDead's

    // From the level's 'AIEl' data: the copies and their tracking, the cars' models and the characters loaded
    AIElementController* Construct(UData *data);                                                // 0x00028190
    // fgAIElementController, new (Ghidra: Construct)
    static void Create(UData *data);                                                            // 0x000285b0
    // ... deleted with its arrays (Ghidra: Destruct)
    static void Destroy();                                                                      // 0x00028b60

    AIElementStats* GetStats();                                                                 // 0x00028620
    // Every awake car stopped (no gas or brake, the hand brake on) and its AI told to stay
    void EveryoneChill();                                                                       // 0x00028630
    // Room for another car
    bool OkToSpawnHench();                                                                      // 0x000286b0
    // The copy, and the tracking, of a level record (by its index in the level's array)
    AIElement* RedirectCarpElement(AIElement *carpElement);                                     // 0x000286d0
    AIElementTracking* GetCarpElementTracking(AIElement *carpElement);                         // 0x00028700
    // mightAsWellBeDead: the scoreable crippled cars and their living riders
    void CalcMightAsWellBeDead();                                                               // 0x00028730
    int GetNumMightAsWellBeDead();                                                              // 0x000287c0
    // An awake element's objects deleted: its transform kept, asleep (or dead)
    void GoToSleep(AIElement *element);                                                         // 0x000287d0
    // GoToSleep for the awake vehicle element whose AI the vehicle is
    void ForceVehicleToSleep(AIVehicle *vehicle);                                               // 0x000289f0
    // An awake element's transform from its car or character
    void SyncRuleInfo(AIElement *element);                                                      // 0x00028a40
    // A sleeping element (of the difficulty) spawned: its car or helicopter and riders, or its character
    void WakeUp(AIElement *element);                                                            // 0x00028bb0
    // Each step: every element's tracking, then the elements in range woken - all of them if they fit the slots,
    // else the nearest ahead first - and those left out sent to sleep
    void Update();                                                                              // 0x00029880
};
static_assert(sizeof(AIElementController) == 0x58, "the element controller is 0x58 bytes");
static_assert(offsetof(AIElementController, stats) == 0x1c && offsetof(AIElementController, wakeList) == 0x38 &&
              offsetof(AIElementController, count) == 0x40 && offsetof(AIElementController, cars) == 0x50 &&
              offsetof(AIElementController, mightAsWellBeDead) == 0x54, "element controller layout");

// A new element's sleepRange
extern float DefaultSleepRange;

// The range list's order for qsort: the closest ahead first (never equal)
int CompareRanges(const void *a, const void *b);                                                // 0x00028a90

extern AIElementController *fgAIElementController;
// 1; no code writes it: EActivateAIElement and EAIElementForceAwake wake a vehicle element only within the hench
