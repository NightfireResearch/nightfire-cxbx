// ---------------------------------------------------------------------------------------------------------------
// PBondCar (0x420 bytes, Simulation::SpawnCarObject's "PBondCar"): every car, the player's and the AI's, and the
// other ground vehicles the game drives with the same code (snowmobiles, the submarine, spline-driven vehicles). A
// PVehicle with four wheels on the world's surface, its controls, damage zones, tyre tracks, weapons state and the
// render, audio and feedback objects it owns. Its vtable is 0x0018f580 (84 slots: PVehicle's 83 and one more).
//
// The methods are split by package: BondCarSimulate.cpp (construction, Simulate, ApplyDamage, InitAudioObject) and
// the other BondCar*.cpp files.
// ---------------------------------------------------------------------------------------------------------------

