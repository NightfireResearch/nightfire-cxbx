// What the wheel-force methods work from at each wheel (AddWheelForces, AddSimpleWheelForces, AddSnowmobileForces;
// the names are ours)
struct BondCarWheelInput {
    float grip;                 // +0x00 scales the tyre's sideways slip into a force
    float drive;                // +0x04 the push along the wheel's heading (negative: braking)
    float frictionLimit;        // +0x08 the most sideways force the tyre holds
    float handbrake;            // +0x0c a drag against the wheel's travel
};
static_assert(sizeof(BondCarWheelInput) == 0x10, "a wheel's input is 16 bytes");

// Simulate's scratch pad: a block of its stack frame (0x450 bytes, 16-byte aligned, not initialised) whose address
// it leaves in BondCarScratchPad for the Process*Physics methods it calls, their wheel-force methods and
// ImproveLanding. Simulate itself writes none of it. The names are ours.
struct BondCarScratch {
    uint8_t unknown000[0x100];
    MATRIX4 steeredOrientation;         // +0x100 the body's orientation turned by the steering
    Coord4 wheelHeading[2];             // +0x140 the front wheels' heading, the rear's
    Coord4 rollingResistance4;          // +0x160 rollingResistance as a Coord4
    BondCarWheelInput wheelInput[kCarWheels];   // +0x170
    float wheelSlip[kCarWheels];        // +0x1b0 the wheel forces' sideways force against its limit, 0 to 1
    Coord3 velocity;                    // +0x1c0 the body's, y cleared
    float forwardSpeed;                 // +0x1cc along the body's heading
    Coord3 rollingResistance;           // +0x1d0 velocity scaled by ROLLING_RESISTANCE (ProcessPhysics)
    float driveForce;                   // +0x1dc
    Coord3 forward;                     // +0x1e0 the body's heading (its orientation's row 2)
    float handbrake;                    // +0x1ec
    Coord3 steeredForward;              // +0x1f0 the front wheels' heading
    float frontGrip;                    // +0x1fc the front axle's share of the grip
    Coord3 position;                    // +0x200 the body's
    float rearGrip;                     // +0x20c the rear axle's
    MATRIX4 steeringTurn;               // +0x210 the steering's turn about y
    // The wheel-force methods' working vectors
    Coord4 lever;                       // +0x250 the wheel from the body's centre
    Coord4 lateral;                     // +0x260 across the wheel, then the sideways force
    Coord4 force;                       // +0x270 the wheel's force
    Coord4 axle;                        // +0x280 along the axle, then the suspension's force
    Coord4 pointVelocity;               // +0x290 the body's velocity at the wheel
    Coord4 rolling;                     // +0x2a0 along the wheel's heading on the ground, then the drive's force
    Coord4 torque;                      // +0x2b0
    Coord4 drag;                        // +0x2c0 the hand brake's drag
    uint8_t unknown2D0[0xc];
    RigidBodyInfo *forceInfo;           // +0x2dc the body's (the wheel-force methods'; ImproveLanding reads it)
    uint8_t unknown2E0[0xc];
    float compression;                  // +0x2ec the wheel's spring's
    Coord3 heading;                     // +0x2f0 the body's heading, level
    float compressionChange;            // +0x2fc
    Coord3 groundNormal;                // +0x300 the ground's normal, level
    float springForce;                  // +0x30c
    Coord3 spin;                        // +0x310 the body's spin at the wheel
    float lateralExcess;                // +0x31c the sideways force past the limit
    float lateralForce;                 // +0x320
    float liftAboveGround;              // +0x324 the most compression of a wheel off the ground
    uint8_t unknown328[8];
    int32_t wheelsOnGround;             // +0x330 the wheels whose springs pushed
    uint8_t unknown334[4];
    float slipFraction;                 // +0x338
    uint8_t unknown33C[4];
    MATRIX4 landing;                    // +0x340 ImproveLanding's level orientation
    MATRIX4 noseRotation;               // +0x380 NOSE_JUMP_ANGLE about x
    Coord4 up;                          // +0x3c0 (0, 1, 0)
    uint8_t unknown3D0[0x20];
    Coord4 landingQuat;                 // +0x3f0
    uint8_t unknown400[0x10];
    RigidBodyInfo *info;                // +0x410 the body's (the Process*Physics methods')
    float steeringInput;                // +0x414 the steering within -1..1 (ProcessSimplePhysics: pulled by
                                        //        shredded tyres)
    float shreddedDrag;                 // +0x418 ProcessSimplePhysics': with one tyre shredded 0.5, else 1
    float maxAcc;                       // +0x41c MAXACC by the gear's ratio
    float maxRevAcc;                    // +0x420 MAXREVACC, cut above the reversing speed
    float wheelSpeed;                   // +0x424 the wheels' turns per step at the body's speed, at most 1
    float boostAcc;                     // +0x428 BOOST_EXTRA_ACC while the boost lasts
    float scale42C;                     // +0x42c the steering's speed scale, then the friction's
    float unknown430;                   // +0x430
    float blend;                        // +0x434 1 / NUM_BLEND_STEPS (ImproveLanding)
    float boostGrip;                    // +0x438 the friction limits' scale while the boost lasts
    float counterSteer;                 // +0x43c the rear friction limit's scale when counter-steering
    uint8_t handbrakeOn;                // +0x440 the hand brake's force applied
    uint8_t shreddedTyres;              // +0x441 ProcessSimplePhysics'
    uint8_t wheelSpin;                  // +0x442
    uint8_t limited;                    // +0x443 the wheel's sideways force was cut to its limit
    uint8_t onGround;                   // +0x444 the wheel's
    uint8_t unknown445[0xb];
};
static_assert(sizeof(BondCarScratch) == 0x450, "Simulate's scratch pad is 0x450 bytes");
static_assert(offsetof(BondCarScratch, steeredOrientation) == 0x100 && offsetof(BondCarScratch, wheelInput) == 0x170 &&
              offsetof(BondCarScratch, velocity) == 0x1c0 && offsetof(BondCarScratch, steeringTurn) == 0x210 &&
              offsetof(BondCarScratch, lever) == 0x250 && offsetof(BondCarScratch, forceInfo) == 0x2dc &&
              offsetof(BondCarScratch, compression) == 0x2ec && offsetof(BondCarScratch, spin) == 0x310 &&
              offsetof(BondCarScratch, wheelsOnGround) == 0x330 && offsetof(BondCarScratch, slipFraction) == 0x338 &&
              offsetof(BondCarScratch, landing) == 0x340 && offsetof(BondCarScratch, landingQuat) == 0x3f0 &&
              offsetof(BondCarScratch, info) == 0x410 && offsetof(BondCarScratch, blend) == 0x434 &&
              offsetof(BondCarScratch, boostGrip) == 0x438 && offsetof(BondCarScratch, onGround) == 0x444,
              "scratch pad layout");

#define BondCarScratchPad (*(BondCarScratch **)0x001e7a88)

