// XBE_GLOBAL(0x0023f410, 0x4)
EAGL::ViewPort *HudViewPort;

namespace {

constexpr uint32_t kDepthAlways = 0x207;
constexpr float kLetterBoxBar = 0.125f;             // of the screen's height, above and below
constexpr float kHudLines = 480.0f;
constexpr float kWideOffsetX = 80.0f;
constexpr float kWideOffsetY = 60.0f;
constexpr float kWideScale = 0.75f;
constexpr float kNormalScale = 0.9f;
constexpr float kMargin = 0.050000012f;             // the original's constant, a little over 0.05
constexpr float kMarginY = 1.0f / 48.0f;
static_assert(std::bit_cast<uint32_t>(1.0f / kHudLines) == 0x3b088889, "1 / 480");
static_assert(std::bit_cast<uint32_t>(kNormalScale) == 0x3f666666, "0.9");
static_assert(std::bit_cast<uint32_t>(kMargin) == 0x3d4cccd0, "the margin");
static_assert(std::bit_cast<uint32_t>(kMarginY) == 0x3caaaaab, "1 / 48");

} // namespace

// FUNC_AT(0x000d7bf0)
void GOrthoHudView::PreRender() {
    viewPort->SetOrthographic(0.5f, 10.0f);
}

// FUNC_AT(0x000daac0)
void GOrthoHudView::PostRender() {
    if (fHudApp->exitRequested) {
        EExit *event = new EExit;
        if (event != NULL)
            event->Construct();
    }
    if (fHudApp->restartRequested) {
        ERestart *event = new ERestart;
        if (event != NULL)
            event->Construct();
    }
}

// FUNC_AT(0x000e1ce0)
void GOrthoHudView::DoRender() {
    HudViewPort = viewPort;
    fHudApp->gallery->SPRITE_Flush();
    if (gHudOn) {
        fHudApp->DrawScreenHits();
        fHudApp->DrawScreenFades();
        fHudApp->DrawBloodCurtain();
        if (fgRenderer->videoMode == RRenderer::kVideoLetterbox) {
            float bar = fHudApp->screenHeight * kLetterBoxBar;
            SimpleMaterial->SetDepthTestMethod(kDepthAlways);
            Draw::DrawBox(0.0f, 0.0f, fHudApp->screenWidth, bar, HudLetterBoxColour);
            Draw::DrawBox(0.0f, fHudApp->screenHeight - bar, fHudApp->screenWidth, bar, HudLetterBoxColour);
        }
        fgRenderer->renderContext->SetZWritesEnable(false);
        fHudApp->DrawLetterBox();
    }

    // The HUD's frame: scaled by the screen's height over 480, and moved in from the edges
    alignas(16) MATRIX4 view = *reinterpret_cast<const MATRIX4 *>(viewPort->GetViewMatrix());
    float scaleY = fHudApp->screenHeight * (1.0f / kHudLines);
    GetFoundationVideoMode();               // the answer is not used
    float scaleX, offsetX, offsetY;
    if (fgRenderer->widescreen) {
        offsetX = kWideOffsetX;
        scaleX = kWideScale;
        if (fgRenderer->videoMode == RRenderer::kVideoWide) {
            offsetY = 0.0f;
        } else {
            offsetY = kWideOffsetY;
            scaleY = scaleY * kWideScale;
        }
    } else {
        scaleX = kNormalScale;
        scaleY = scaleY * kNormalScale;
        offsetX = fHudApp->screenWidth * kMargin;
        offsetY = float(double(fHudApp->screenHeight) * kMargin + double(fHudApp->screenHeight) * kMarginY);
    }
    alignas(16) MATRIX4 scale;
    alignas(16) MATRIX4 translate;
    alignas(16) MATRIX4 frame;
    alignas(16) MATRIX4 transform;
    BuildScaleXYZ(&scale, scaleX, scaleY, 1.0f);
    BuildTranslate(&translate, offsetX, offsetY, 0.0f);
    VU0_MATRIX4_mult(&frame, &scale, &translate);
    VU0_MATRIX4_mult(&transform, &view, &frame);
    viewPort->SetViewMatrix(&transform.mtx[0][0]);
    fHudApp->targetScaleX = scaleX;
    fHudApp->targetScaleY = scaleY;
    fHudApp->targetOffsetX = offsetX;
    fHudApp->targetOffsetY = offsetY;
    fHudApp->Draw();
}
