// ---------------------------------------------------------------------------------------------------------------
// The mission rules (game tier). See MissionRules.cpp.
//   SMissionRule: one rule of the level's 'Rule' data, made by Instantiate after the record's kind. The mission
//     manager runs DoRule on its rules: while the rule is enabled its test (CheckRule, the vtable's slot 1), inverted
//     if the record says so, runs the rule's events when it passes; a rule marked once is disabled then.
//   The tests (SRule*): always; damage, death and health of a target; a weapon's ammunition; a mission timer passing
//     a time; the distance and speed of a target; a target's property; the player's heading against a target's; the
//     difficulty; a programmer event or counter.
//   SMissionRuleTarget: what a rule tests - the player, an AI element (the record's resolved reference) or the AI
//     controller's figures.
//   SMissionTimer: one of the mission manager's ten timers, counting simulation steps at a rate (negative: down),
//     beeping each second while ticking.
// ---------------------------------------------------------------------------------------------------------------

