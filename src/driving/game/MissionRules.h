struct TriggerEvents;                     // world/Trigger.h

// The kinds of rule (the record's type; Instantiate's switch)
enum MissionRuleKind : int32_t {
    kRuleAlways = 0,
    kRuleAmmo = 1,
    kRuleDamage = 2,
    kRuleDeath = 3,
    kRuleHealth = 4,
    kRulePIP = 5,
    kRuleProg = 6,
    kRuleRange = 7,
    kRuleSpeed = 8,
    kRuleTimer = 9,
    kRuleProperty = 10,
    kRuleCollision = 11,
    kRulePlayerDir = 12,
    kRuleDifficulty = 13,
    kRuleProgCounter = 14,
};

// A rule's record in the level's 'Rule' data (0x20 bytes; the PS2 build's CARP::Rule). For the kinds with a target
// the arguments start with the target's type and its AI element, a reference the CARP resolver turns into the
// element's address.
struct MissionRuleRecord {
    enum Flag : uint32_t {
        kEnabled = 0x1,
        kOnce = 0x2,                    // disabled once its events have run
        kInverted = 0x4,                // its events run when the test fails
    };

    int32_t type;                       // +0x00 MissionRuleKind
    uint32_t flags;                     // +0x04 Flag
    int32_t stage;                      // +0x08 the mission manager's stage it runs in; -1 every stage
    TriggerEvents *events;              // +0x0c
    union {
        int32_t args[4];                // +0x10 by kind
        float floatArgs[4];
        char text[16];
    };
};
static_assert(sizeof(MissionRuleRecord) == 0x20, "a rule's record is 32 bytes");
static_assert(offsetof(MissionRuleRecord, events) == 0x0c && offsetof(MissionRuleRecord, args) == 0x10,
              "rule record layout");

// SMissionRuleTarget's types
enum MissionRuleTargetType : int32_t {
    kTargetPlayer = 0,
    kTargetStats = 3,                   // the AI controller's figures (AIElementController::GetStats)
    kTargetElement = 4,                 // an AI element
};

// What a rule tests (8 bytes)
struct SMissionRuleTarget {
    int32_t type;                       // +0x00 MissionRuleTargetType
    uint32_t element;                   // +0x04 kTargetElement: the AI element's record; else 0

    void Construct(int32_t targetType, uint32_t targetElement) {
        type = targetType;
        element = targetType == kTargetElement ? targetElement : 0;
    }

    // The player's or the element's speed, truncated; 0 for the other types
    int GetSpeed();                                                                             // 0x000ba390
    // The player's or the element's position into x, y, z; nothing for the other types
    void GetPos(Coord4 *position);                                                              // 0x000ba3e0
    // The player's body's orientation, or an element's that has a physics object; false without one
    bool GetMatrix(MATRIX4 *matrix);                                                            // 0x000ba430
    // An element's property by name, or the player's: "NOBOOST", "ONEEMP", "2WHEELS"
    bool GetProperty(const char *name);                                                         // 0x000ba4a0
};
static_assert(sizeof(SMissionRuleTarget) == 8, "a rule's target is 8 bytes");

// An integer a rule watches cross a threshold (the names are ours): downwards with direction 0, else upwards.
// `last` starts one step on the far side, so a value already across passes the first test.
struct RuleIntCrossing {
    int32_t direction;                  // +0x00
    int32_t threshold;                  // +0x04
    int32_t last;                       // +0x08 the value at the last test

    void Construct(int32_t crossingDirection, int32_t crossingThreshold) {
        direction = crossingDirection;
        threshold = crossingThreshold;
        last = direction == 0 ? threshold - 1 : threshold + 1;
    }

    bool Crossed(int value) {
        bool crossed = false;
        if (direction == 0) {
            if (value < threshold && last >= threshold)
                crossed = true;
        } else {
            if (value > threshold && last <= threshold)
                crossed = true;
        }
        last = value;
        return crossed;
    }
};

// The same for a float (SRuleTimer's seconds)
struct RuleCrossing {
    int32_t direction;                  // +0x00
    float threshold;                    // +0x04
    float last;                         // +0x08

    bool Crossed(float value);                                                                  // 0x000b9c50
};

// ---- the rules (vtable: 0 the scalar deleting destructor, 1 CheckRule)

class SMissionRule {
public:
    void **vtable;                      // +0x00
    TriggerEvents *events;              // +0x04
    bool enabled;                       // +0x08
    bool once;                          // +0x09
    bool inverted;                      // +0x0a
    uint8_t unknown0b;

    void Construct(const MissionRuleRecord *record);    // inlined in each rule's constructor
    void Destruct();                                                                            // 0x000b9ac0
    SMissionRule* Delete(unsigned int flags);                                                   // 0x000b9cb0

    // The record's rule, allocated; NULL for an unknown kind
    static SMissionRule* Instantiate(const MissionRuleRecord *record);                          // 0x000ba150
    // The rule's events, with the event data cleared and the player's body in it
    void RunEvents();                                                                           // 0x000b9500
    void DoRule();                                                                              // 0x000b9590

    bool CheckRule();                   // slot 1
};
LAYOUT_32(sizeof(SMissionRule) == 0xc, "a mission rule is 12 bytes");

