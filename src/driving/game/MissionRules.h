float CompareWithinDegrees(float angle, float from, float to);                                  // 0x000b9ad0

// ---- SMissionTimer (0x14 bytes; the mission manager holds ten)

constexpr int kMissionTimers = 10;

struct SMissionTimer {
    bool running;                       // +0x00
    bool ticking;                       // +0x01 a beep each second while running
    uint8_t unknown02[2];
    int32_t startStep;                  // +0x04 the simulation step it started or was reset at
    int32_t value;                      // +0x08 at startStep
    int32_t rate;                       // +0x0c steps counted per step; negative counts down
    int32_t lastBeep;                   // +0x10 the second last beeped

    // The mission manager's constructor runs it over the ten (the vector constructor iterator)
    SMissionTimer* Construct();                                                                 // 0x000b95d0
    void Reset(int startValue);                                                                 // 0x000b95e0
    void Start(int countRate);                                                                  // 0x000b9600
    void Increment(int amount);                                                                 // 0x000b9620
    int GetValue();                                                                             // 0x000b9630
    bool IsReverse();                                                                           // 0x000b96a0
    void SetTicking(bool on);                                                                   // 0x000b96b0
    void Stop();                                                                                // 0x000b9ce0
};
static_assert(sizeof(SMissionTimer) == 0x14, "a mission timer is 20 bytes");

