// The warning beside a provisional port: code no shipped run reaches, ported from the listing. It says so once,
// the first time it runs.
inline void EmpEffectUntested(const char *what) {
    printf("[game] WARNING: %s ran - a provisional port that no shipped run reaches, UNTESTED in game. Check what "
           "it computes against the original.\n", what);
    fflush(stdout);
}

#define EMPEFFECT_UNTESTED(what) \
    do { \
        static bool warned_; \
        if (!warned_) { \
            warned_ = true; \
            EmpEffectUntested(what); \
        } \
    } while (0)

