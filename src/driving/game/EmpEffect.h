// The EMP effects (game.effects):
//
//   - REmp: the statics behind the shooting effect - a flat ring drawn twice round a transform, growing and fading
//     as its progress goes from 0 to 1 - and a sphere of six bands built beside it. Init and Kill run with the game
//     render (RRenderHigh::InitGameRender, KillGameRender), DrawShootingEffect from RVehicle::RenderFX.
//   - REmpBolts (0x22c bytes, RVehicle +0x368, made by RVehicle::TriggerEmpBolts): lightning bolts that crawl over
//     a car between its "emp" locators, or from one of them to the world, with a glowing light at the car. The
//     locators are grouped by their name's fourth character; a bolt joins two of the same group.
//   - the two std::maps REmpBolts uses (MSVC 7's _Tree, engine/RbTree.h): the anchors by group, whose code is here,
//     and FindAnchors' count per group, a map with the data layer's 0x18-byte nodes (data/Tree.h), whose compiled
//     copies are here too - with the node minimum every such map shares.
//
// See EmpEffect.cpp.
// ---------------------------------------------------------------------------------------------------------------

