// ---- the anchors: a car's "emp" locators

// One locator whose name is "emp" and at least one more character (names ours)
struct EmpAnchor {                      // 0x20
    const ArticleEffect *effect;        // +0x00 the locator
    uint32_t group;                     // +0x04 the name's fourth character, sign-extended
    uint32_t linkCount;                 // +0x08 the characters after it
    int32_t links[5];                   // +0x0c each of them, sign-extended (a longer name runs on into the next
                                        //       anchor, as in the original)
};
LAYOUT_32(sizeof(EmpAnchor) == 0x20, "an anchor is 32 bytes");

// The anchors of one group: an array and its length (the game's pointer-and-count array; the name is ours)
struct EmpAnchorList {
    EmpAnchor **anchors;                // +0x00 operator new[]'s
    int32_t count;                      // +0x04

    void Clear();                                                                               // 0x0009c370
    EmpAnchorList* Assign(const EmpAnchorList *other);                                          // 0x0009c3a0
};

// ---- std::map<uint32_t, EmpAnchorList>: the anchors by group (0x1c-byte nodes)

struct EmpAnchorGroup {                 // the map's value_type
    uint32_t group;                     // +0x00 the key
    EmpAnchorList list;                 // +0x04

    void Destruct();                    // only an exception unwind calls it                     // 0x0009c400
};

struct EmpAnchorNode : RbTreeNode<EmpAnchorNode, EmpAnchorGroup> {
    void DestroyValue();                // the list freed                                        // 0x0009c4a0
};
LAYOUT_32(sizeof(EmpAnchorNode) == 0x1c, "an anchor map node is 0x1c bytes");

// The map's compiled code. The rotations and iterator steps are the ones every map with 0x1c-byte nodes shares
// (data/AttributeContainers.h's AttributeMap); the minimum and maximum here are shared with AttributeMap too.
struct EmpAnchorMap : RbTree<EmpAnchorNode> {
    struct InsertResult {
        EmpAnchorNode *where;
        bool inserted;
        uint8_t unknown5[3];
    };

    static EmpAnchorNode* Max(EmpAnchorNode *node);                                             // 0x0009c330
    static EmpAnchorNode* Min(EmpAnchorNode *node);                                             // 0x0009c350
    static EmpAnchorNode* BuyHead();                                                            // 0x0009c420
    EmpAnchorNode* BuyNode(EmpAnchorNode *left, EmpAnchorNode *parent, EmpAnchorNode *right,
                           const EmpAnchorGroup *value, uint8_t color);                         // 0x0009c4c0
    // _Erase: frees a subtree without rebalancing
    void EraseSubtree(EmpAnchorNode *node);                                                     // 0x0009c570
    // _Insert: a new red node under `where`, on its left if `addLeft`, then rebalances
    EmpAnchorNode** InsertAt(EmpAnchorNode **result, bool addLeft, EmpAnchorNode *where,
                             const EmpAnchorGroup *value);                                      // 0x0009c5c0
    // erase(iterator): unlinks and frees the node, rebalances, answers the next one
    EmpAnchorNode** EraseAt(EmpAnchorNode **result, EmpAnchorNode *where);                      // 0x0009c980
    InsertResult* InsertUnique(InsertResult *result, const EmpAnchorGroup *value);              // 0x0009cf40
    EmpAnchorNode** EraseRange(EmpAnchorNode **result, EmpAnchorNode *first, EmpAnchorNode *last);  // 0x0009d0c0
    // operator[]: the group's list, a new empty one if there was none
    EmpAnchorList* Lookup(const uint32_t *group);                                               // 0x0009d240
    void Destruct();                                                                            // 0x0009d5f0
};
LAYOUT_32(sizeof(EmpAnchorMap) == 12, "a map is 12 bytes");

// ---- std::map<uint32_t, int>: FindAnchors' count of anchors per group (the data layer's tree, its key the
// TreePair's tag and its count the index). Its _Erase, _Insert, erase and erase(first, last) are the data layer's
// maps' instruction for instruction; InsertUnique compares the keys unsigned.

class EmpGroupCountMap : public Tree {
public:
    void EraseSubtree(TreeNode *node);                                                          // 0x0009c460
    TreeNode** InsertAt(TreeNode **result, bool addLeft, TreeNode *where, const TreePair *value);   // 0x0009c7a0
    TreeNode** EraseAt(TreeNode **result, TreeNode *where);                                     // 0x0009cc70
    TreeInsertResult* InsertUnique(TreeInsertResult *result, const TreePair *value);           // 0x0009d000
    TreeNode** EraseRange(TreeNode **result, TreeNode *first, TreeNode *last);                  // 0x0009d180
    void Destroy();                     // only an exception unwind calls it                     // 0x0009d960
};
LAYOUT_32(sizeof(EmpGroupCountMap) == 12, "a map is 12 bytes");

// The leftmost node under `node` (_Min), for every map with 0x18-byte nodes (the linker folded the copies)
TreeNode* SharedTreeMin(TreeNode *node);                                                        // 0x0009c310

// ---- REmpBolts

// A bolt alive on the car (the name is ours). Nothing in the game adds one: numBolts stays 0.
struct EmpBolt {                        // 0x10
    int32_t handle;                     // +0x00 RLightning's
    uint32_t unknown04[3];
};

class REmpBolts {
public:
    RSceneObj *vehicle;                 // +0x000 the RVehicle the bolts are on
    uint32_t lastUpdateTime;            // +0x004 the simulation step Update last ran at
    uint32_t startTime;                 // +0x008 the step it was made at
    float intensity;                    // +0x00c 1
    EmpAnchor *anchors;                 // +0x010 operator new[]'s
    int32_t numAnchors;                 // +0x014
    EmpAnchorMap groups;                // +0x018 pointers into anchors, by group (filled only for two anchors or
                                        //        more)
    EmpBolt bolts[32];                  // +0x024
    uint32_t numBolts;                  // +0x224
    uint32_t boltCursor;                // +0x228 the next bolt Update checks

    REmpBolts* Construct(RSceneObj *vehicle);                                                   // 0x0009dc90
    void Destruct();                                                                            // 0x0009d630

    // The "EMP bolts ..." debug variables
    static void LoadAttributes();                                                               // 0x0009bd50

    // Update, then the glow: a positional light at the car, scattered, its size a wave plus noise
    void Draw();                                                                                // 0x0009d7c0
    // Up to 8 bolts checked for death, then up to 4 spawns while fewer than "EMP bolts num alive" are alive
    void Update();                                                                              // 0x0009d6b0
    // A random anchor: a bolt from it to another of its group, or a bolt to where a ray out from the car hits
    // the world, with the hit's effects and a flash of light
    void TrySpawnBolt();                                                                        // 0x0009d320
    // A random anchor of the group, NULL if the group has none
    EmpAnchor* GetRandomAnchor(uint32_t group);                                                 // 0x0009d2d0
    // A rounded bolt round the car between two anchors, and sometimes sparks at the second
    void CreateVehicleBolt(EmpAnchor *from, EmpAnchor *to);                                     // 0x0009c0e0
    void CreateWorldBolt(EmpAnchor *from, const Coord3 *hit);                                   // 0x0009c260
    // The anchors from the car's handle's locators, and the groups
    void FindAnchors();                                                                         // 0x0009d9a0
};
LAYOUT_32(sizeof(REmpBolts) == 0x22c, "REmpBolts is 0x22c bytes");
LAYOUT_32(offsetof(REmpBolts, groups) == 0x18 && offsetof(REmpBolts, bolts) == 0x24 &&
          offsetof(REmpBolts, numBolts) == 0x224 && offsetof(REmpBolts, boltCursor) == 0x228,
          "REmpBolts layout");

