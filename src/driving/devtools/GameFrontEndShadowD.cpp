std::string MakeText() {
    std::string text;
    switch (Random(8)) {
    case 0:
        return Pick(kTexts);
    case 1:
        return std::string(Random(120), 'x');
    case 2:
        return std::string(Random(6), ' ') + "a b";
    default:
        break;
    }
    size_t length = Random(420);
    while (text.size() < length) {
        size_t word = Random(10) == 0 ? 40 + Random(30) : 1 + Random(12);
        for (size_t i = 0; i < word; i++)
            text += char('a' + Random(26));
        size_t spaces = Random(6) == 0 ? 1 + Random(4) : 1;
        text.append(spaces, ' ');
    }
    return text;
}

