void Report(const char *what, long index, const std::string &a, const std::string &b) {
    if (g_reported >= 10)
        return;
    g_reported++;
    printf("[gamefrontendshadowd] DIFF %s, case %ld\n  orig: %.300s\n  port: %.300s\n", what, index, a.c_str(),
           b.c_str());
    fflush(stdout);
}

