// The case's object in place: its cues and lines in fresh blocks
void ApplySubtitles(const SubtitlesCase &c) {
    memcpy(g_subtitles, c.bytes, sizeof(c.bytes));
    g_subtitles->cues = NULL;
    if (c.hasCues) {
        g_subtitles->cues = static_cast<SubtitleCue *>(OperatorNewArray(8 * sizeof(SubtitleCue)));
        memcpy(g_subtitles->cues, c.cues, sizeof(c.cues));
    }
    GSubtitleSplitter &sp = g_subtitles->splitter;
    for (int i = 0; i < GSubtitleSplitter::kMaxLines; i++) {
        if (i < c.lines) {
            sp.lines[i] = static_cast<char *>(OperatorNewArray(8));
            strcpy(sp.lines[i], kStaticLines[i]);
        } else {
            sp.lines[i] = NULL;
        }
    }
    sp.count = c.lines;
}

