// A shadow test of package GFE_D (the front end's system helpers, the locale, the subtitles, GFX, the HUD's view),
// run once from the first simulation tick when NIGHTFIRE_GAMEFRONTENDSHADOWD is set. Each case builds its state
// (synthetic subtitles, splitters, effect groups, canvases and sounds; a copy of the live HUD and renderer, put in
// place of fHudApp and fgRenderer for the case; the launch page's mission and language, the clocks, the video
// mode), then runs the ORIGINAL (the package's entries swapped back) and the PORT through the same entry address,
// the state rebuilt between the two. Every call out of the package is a recording fake on both sides: the clocks,
// the locale's strings, the font, the materials' depth and alpha states, Draw's boxes and depth, the view port, the
// HUD's draws, the effects gallery, the mixes, the scene object's instance transform, the assertion message, the
// files and their frees, the events, the mission manager's cinematic skip. Compared: the call logs, the objects'
// bytes after the call (lines and cues by content), the answers (strings by content), and the globals the package
// owns (the game's copy for the original, ours for the port).
//
// Not run here: GFX::Init and Shutdown, CURATOR_Init and CURATOR_Shutdown (they make and free the effects gallery
// and the locale's strings; every boot runs Init), GSubtitles::Delete with its flag set, and the register-argument
// GFX::Trigger at 0x000d32f0 on its own (it is not patched; the three Trigger entries run it).
//
// Mutations the test sees: GSubtitleSplitter::GetString moving on at > rather than >= (cases make the elapsed time
// equal a line's time exactly), GLocale::GetLanguage answering Swedish for 6 instead of 8 (every language from -2
// to 12 is run), DoRender's wide PAL frame scaling y by 0.75 (the wide cases run every video mode).
//
// One summary line: [gamefrontendshadowd] ...: N cases, M checks, D differ.
// ---------------------------------------------------------------------------------------------------------------

