template <class Call>
void RunCase(const char *what, const Call &call) {
    std::string results[2];
    uint32_t seed = g_seed;         // a case's own draws (FillSplitter's) the same on both sides
    for (int side = 0; side < 2; side++) {
        bool original = side == 0;
        g_seed = seed;
        std::string &log = results[side];
        g_log = &log;
        bool ok;
        if (original) {
            Originals window;
            ok = Guarded([&] { call(true); });
        } else {
            ok = Guarded([&] { call(false); });
        }
        g_log = NULL;
        if (!ok)
            log += "<fault>";
        RestoreLive();
    }
    g_cases++;
    g_checks++;
    if (results[0] != results[1]) {
        g_differ++;
        Report(what, g_cases, results[0], results[1]);
    }
}

