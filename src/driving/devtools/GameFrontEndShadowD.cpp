// An effect group with one data item: 'Flgs' (or another tag) holding a word
struct EffectGroup {
    UGroup group;
    UData item;
    uint32_t value;
    uint32_t pad[3];
};
alignas(16) EffectGroup g_effects[3];

void MakeEffect(EffectGroup &e, uint32_t tag, uint32_t value) {
    memset(&e, 0, sizeof(e));
    e.group.tag = 0x45666374;           // 'Efct'
    e.group.flags = kDataRelative;
    e.group.count = 1;
    e.group.data = 1;                   // the items, in records from the group
    e.item.tag = tag;
    e.item.flags = kDataRelative | (4 << 8);
    e.item.count = 1;
    e.item.data = sizeof(UData);        // the word, in bytes from the item
    e.value = value;
}

