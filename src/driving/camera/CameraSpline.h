// ---- the warning beside a provisional port: code no shipped data reaches, said once, the first time it runs

inline void CameraUntested(const char *what) {
    printf("[camera] WARNING: %s ran - a provisional port that no shipped data reaches, UNTESTED. Check what it "
           "computes against the original.\n", what);
    fflush(stdout);
}

#define CAMERA_UNTESTED(what) \
    do { \
        static bool warned_; \
        if (!warned_) { \
            warned_ = true; \
            CameraUntested(what); \
        } \
    } while (0)

// ---- std::list<T> as the game compiled it (MSVC 7): the allocator's byte, the head node (end()), the size. A node
//      is the links, then the value. Each instantiation has its own compiled copies of the members, entered by
//      address from its own class (CameraSpline.cpp's points, DirectorQueue.cpp's queue).

template <class T>
struct CameraListNode {
    CameraListNode *next;       // +0x00
    CameraListNode *prev;       // +0x04
    T value;                    // +0x08
};

template <class T>
struct CameraList {
    typedef CameraListNode<T> Node;

    uint8_t allocator;          // +0x00
    uint8_t unknown01[3];
    Node *head;                 // +0x04
    uint32_t size;              // +0x08

    static constexpr uint32_t kMaxSize = 0xffffffffu / sizeof(T);

    // begin(), as the compiled code reads it: NULL without a head
    Node *Begin() const { return head != NULL ? head->next : NULL; }

    // A node from the pools ("STL"), linked as given, its value a copy (ConstructListValue)
    Node *BuyNodeT(Node *next, Node *prev, const T *value) {
        Node *node = static_cast<Node *>(UMemory::FastAlloc(sizeof(Node), "STL"));
        if (node != NULL) {
            node->next = next;
            node->prev = prev;
            ConstructListValue(&node->value, value);
        }
        return node;
    }

    // The head, linked to itself
    Node *BuyHeadT() {
        Node *node = static_cast<Node *>(UMemory::FastAlloc(sizeof(Node), "STL"));
        if (node != NULL) {
            node->next = node;
            node->prev = node;
        }
        return node;
    }

    // erase(first, last): unlinks, destroys (DestroyListValue) and frees each node but the head; answers last
    Node **EraseT(Node **result, Node *first, Node *last) {
        while (first != last) {
            Node *node = first;
            first = first->next;
            if (node != head) {
                node->prev->next = node->next;
                node->next->prev = node->prev;
                DestroyListValue(node);
                UMemory::FastFree(node, sizeof(Node));
                size--;
            }
        }
        *result = first;
        return result;
    }

    // _Incsize: length_error past kMaxSize nodes
    void IncreaseSizeT(uint32_t count) {
        if (kMaxSize - size < count) {
            CAMERA_UNTESTED("list<T>::_Incsize (too long)");
            ThrowLengthError("list<T> too long");
        }
        size += count;
    }

    // push_back (inlined in the game)
    void PushBackT(const T *value) {
        Node *node = BuyNodeT(head, head->prev, value);
        IncreaseSizeT(1);
        head->prev = node;
        node->prev->next = node;
    }

    // ~list() (inlined in the game): every node erased, then the head freed
    void DestructT() {
        Node *end;
        EraseT(&end, Begin(), head);
        if (head != NULL)
            UMemory::FastFree(head, sizeof(Node));
        head = NULL;
        size = 0;
    }
};

// A list of points: the values are copied as they are, and need no destruction
inline void ConstructListValue(Coord4 *slot, const Coord4 *value) {
    *slot = *value;
}
inline void DestroyListValue(CameraListNode<Coord4> *) {
}

