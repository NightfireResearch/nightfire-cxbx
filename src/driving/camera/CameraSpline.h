// ---- RCameraMath

class RCameraMath {
public:
    // The quaternion turning `turns` about the unit axis.                                          0x0007a1e0
    static void BuildRotationQuat(Coord4 *quat, float turns, const Coord4 *axis);
    // The rotation matrix of the same.                                                             0x0007a280
    static void BuildRotationMat4(MATRIX4 *matrix, float turns, const Coord4 *axis);
    // An orthonormal frame whose row 2 is `forward` (a unit vector, usually the matrix's own row 2): row 0 the unit
    // cross product of straight up with it, row 1 row 2 x row 0, row 3 (0, 0, 0, 1); the w words of rows 0-2 zero.
    //                                                                                              0x0007a2b0
    static void VU0_GenerateMatrix4Unit(const Coord4 *forward, MATRIX4 *matrix);
    // The same with row 3 the position, its w 1 (name ours).                                       0x0007a320
    static void VU0_GenerateMatrix4UnitAt(const Coord4 *forward, const Coord4 *position, MATRIX4 *matrix);
    // The arc cosine in turns of a cosine clamped to [-1, 1], unrounded (name ours).               0x0007a3b0
    static double ACosTurns(float cosine);
    // The frame looking along `direction`: row 2 its unit vector, then VU0_GenerateMatrix4Unit (name ours).
    //                                                                                              0x0007a410
    static void MatrixFromDirection(const Coord4 *direction, MATRIX4 *matrix);
    // ... with row 3 the position (name ours).                                                     0x0007a440
    static void MatrixFromDirectionAt(const Coord4 *direction, const Coord4 *position, MATRIX4 *matrix);
    // The angle in turns from a to b (unit vectors), 0-1 round the y axis: the arc cosine of their dot product,
    // from 1 when their cross product points down (name ours).                                    0x0007a470
    static double AngleTurns(const Coord4 *a, const Coord4 *b);
    // The rotation of the frame looking along `direction`.                                         0x0007a4e0
    static void VU0_GenerateQuat(const Coord4 *direction, Coord4 *quat);
};

// ---- RCameraSpline

// RCameraSpline (0x70 bytes): a cubic through four control points - a Bezier curve (BuildSplineEx), or a
// Catmull-Rom segment between two points of its point list (BuildSpline) - and two rotations to blend along it.
// GetSegmentCurveStep and WRoadNav use the Bezier form for curved road segments; the player camera the rest.
class RCameraSpline {
public:
    enum SplineType : int32_t {
        kSplineBezier = 0,          // the control points are the ends and the handles
        kSplineCatmullRom = 1,      // the control points are four points on the path; the curve is halved
        kSplineUnbuilt = 2,         // as constructed (evaluated as a Bezier)
    };

    typedef CameraListNode<Coord4> PointNode;

    // The point list (std::list<Coord4>): the path BuildSpline finds its segment in
    struct PointList : CameraList<Coord4> {
        PointNode* BuyNode(PointNode *next, PointNode *prev, const Coord4 *value);   // 0x0007a850
        PointNode* BuyHead();                                                      // 0x0007a950
        PointNode** Erase(PointNode **result, PointNode *first, PointNode *last);  // 0x0007a900
        void IncreaseSize(uint32_t count);                                          // 0x0007ad50
    };
    static_assert(sizeof(PointList) == 0xc, "a list is 12 bytes");

    Coord4 points[4];           // +0x00 the control points
    Coord4 rotations[2];        // +0x40 the quaternions at the two ends
    int32_t type;               // +0x60 SplineType
    PointList pointList;        // +0x64

    RCameraSpline* Construct();                                                     // 0x0007acd0
    void Destruct();                                                                // 0x0007a9b0
    // The point on the curve at t (0-1), its w 1.                                                  0x0007a530
    void EvaluateSpline(float t, Coord4 *point);
    // The unit tangent at t, its w 1.                                                              0x0007a5c0
    void EvaluateTangent(float t, Coord4 *tangent);
    uint32_t GetPointListSize();                                                    // 0x0007a640
    // A Bezier curve from start to end with the two handles; nothing while the point list holds more than one
    // point.                                                                                       0x0007a650
    void BuildSplineEx(const Coord3 *start, const Coord3 *startControl, const Coord3 *end, const Coord3 *endControl);
    // The frame at t: its rotation blended between the two quaternions (`blendRotations`), or looking along the
    // blend of their z axes; row 3 the point on the curve.                                         0x0007a6d0
    void EvaluateSpline(float t, MATRIX4 *frame, bool blendRotations);
    void ClearSplinePtList();                                                       // 0x0007a9f0
    // The segment from `from` to `to`, leaving and arriving along the two directions (normalised here, in place,
    // unless zero), handles scaled by `tension` times the distance between them: a Bezier when the point list has
    // fewer than two points (which it then clears), else the Catmull-Rom segment of the list that ends at `to`
    // (nothing if `to` is not in it). The two rotations are taken when both are given.            0x0007aa20
    void BuildSpline(const Coord4 *from, Coord4 *fromDirection, const Coord4 *to, Coord4 *toDirection,
                     const Coord4 *fromRotation, const Coord4 *toRotation, float tension);
    void AddToSplinePtList(const Coord4 *point);                                    // 0x0007ae00
};
static_assert(sizeof(RCameraSpline) == 0x70, "RCameraSpline is 0x70 bytes");
static_assert(offsetof(RCameraSpline, rotations) == 0x40 && offsetof(RCameraSpline, type) == 0x60 &&
              offsetof(RCameraSpline, pointList) == 0x64, "RCameraSpline layout");

