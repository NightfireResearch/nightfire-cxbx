constexpr int kScale = 2;                       // each pixel drawn as 2x2
constexpr int kCellWidth = 5 * kScale;
constexpr int kCellHeight = 11 * kScale;
constexpr int kColumns = 23;                    // cells a texture row, a pixel between cells
constexpr int kAdvance = kCellWidth + 2;
constexpr uint8_t kAscent = 9 * kScale;         // the baseline under row 8
constexpr uint8_t kDescent = 2 * kScale;

// The font's file: the glyphs, in code order, drawn into the texture (opaque white on zero)
constexpr DebugFontFile MakeDebugFont() {
    DebugFontFile font = {
        { { 'F', 'N', 'T', 'X' }, sizeof(DebugFontFile), 0x016e, kGlyphs, 9, { 0, 0 }, kAscent, kDescent,
          offsetof(DebugFontFile, glyphs), 0, offsetof(DebugFontFile, imageHeader), 0xffffffff, kAscent + kDescent,
          0, 0x3f800000, 0.0f, 0.0f, 1.0f, 1.0f, { 1.0f, 1.0f }, 1, 0 },
        {},
        {},
        ShapeHeaderWord(0x64, offsetof(DebugFontFile, info) - offsetof(DebugFontFile, imageHeader)),
        256,
        182,
        0,
        0,
        {},
        { ShapeHeaderWord('i', 0), 0x40, 0x10 },
    };
    for (int i = 0; i < kGlyphs; i++) {
        const int x = 1 + i % kColumns * (kCellWidth + 1);
        const int y = 1 + i / kColumns * (kCellHeight + 1);
        FNTXGlyph &glyph = font.glyphs[i];
        glyph.code = kDebugGlyphs[i].code;
        glyph.width = kCellWidth;
        glyph.height = kCellHeight;
        glyph.texX = uint16_t(x);
        glyph.texY = uint16_t(y);
        glyph.advance = kAdvance;
        glyph.xOffset = 1;
        for (int row = 0; row < 11; row++) {
            for (int column = 0; column < 5; column++) {
                if ((kDebugGlyphs[i].rows[row] & (0x10 >> column)) == 0)
                    continue;
                for (int dy = 0; dy < kScale; dy++)
                    for (int dx = 0; dx < kScale; dx++)
                        font.pixels[y + row * kScale + dy][x + column * kScale + dx] = 0xff;
            }
        }
    }
    return font;
}

