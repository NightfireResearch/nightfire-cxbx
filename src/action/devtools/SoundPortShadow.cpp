void SoundPortShadow_Run(void) {
    struct Saved {
        void *at;
        size_t size;
        std::vector<uint8_t> bytes;
    };
    static const struct {
        uint32_t at;
        size_t size;
    } kGlobals[] = {
        {0x001f6680, 8 * HASHES},           // t_hashtable, the part the tests use
        {0x001fe684, 4},                    // m_nhti
        {0x001fe688, 0x20},                 // HashTypeRanges
        {0x0029a128, 0x18},                 // DynamicSoundList
        {0x0029a140, 0xc},                  // GlobalListenerPos
        {0x0029a180, 0x100},                // MusicEventList
        {0x0029a280, 4},                    // SoundInit
        {0x001f6580, sizeof(GameState_t)},  // GameState
        {0x0025fe38, sizeof(MPSettings_t)}, // MPSettings
        {0x001f661c, 44},                   // glb_viewer
        {0x001f6678, 4},                    // ScriptCam
        {0x001df138, 0x100},                // switch_channels
        {0x0029b240, 4},                    // GlobalVoiceHandle
        {0x00182734, 0x14},                 // MapMusicData, the request, the jump, the counts
        {0x00299328, 0x58},                 // the music's state, SFXPaused
        {0x002999f8, 0x14},                 // the level functions' turns
        {0x002980e8, 0x100},                // BackupEventList
        {0x00297fe8, 0x100},                // LastEventList
        {0x001ee260, 0x24},                 // MusicVars
        {0x00182b6c, 4},                    // the stream's jump
        {0x002997d8, 4},
        {0x002997ac, 4},
        {0x0027aed8, 4},                    // IOP_DelayUpdateTimer
        {0x00299464, 4},                    // the fade
        {0x00182a9c, 4},
        {0x00182aa8, 4},
        {0x00299474, 4},
        {0x00298a78, 4},                    // the music stream's status
        {0x001fe6d0, 0x158 * 4},            // PlayerInputs
        {0x001d6ac4, 2},                    // the distance tables
        {0x001d6af0, 0x100},
        {0x0018cdf8, 8},                    // the random words
    };
    std::vector<Saved> saved;
    for (const auto &g : kGlobals) {
        Saved s;
        s.at = (void *)(uintptr_t)g.at;
        s.size = g.size;
        s.bytes.resize(s.size);
        XbeOursRead(s.bytes.data(), g.at, s.size);
        saved.push_back(s);
    }

    regions.Clear();
    areaCount = 0;
    AddArea(&world, sizeof(world));
    for (const auto &g : kGlobals)
        AddArea((void *)(uintptr_t)g.at, g.size);
    NfWarnMuted++;
    cases = differ = nanChoices = 0;

    Group("lists and the hashtable", kLists, COUNT(kLists), 8000, InstallListFakes);
    Group("sounds", kSounds, COUNT(kSounds), 8000, InstallSoundFakes);
    Group("listeners", kListeners, COUNT(kListeners), 12000, InstallListenerFakes);
    Group("sound and music triggers", kTriggers, COUNT(kTriggers), 10000, InstallTriggerFakes);
    Group("level music", kLevelMusic, COUNT(kLevelMusic), 25000, InstallMusicFakes);
    Group("the music's frame", kMusicFrame, COUNT(kMusicFrame), 30000, InstallMusicFrameFakes);
    Group("input", kInput, COUNT(kInput), 10000, InstallInputFakes);
    Group("distance tables and lightning", kAnim, COUNT(kAnim), 10000, InstallAnimFakes);
    ShadowHook_RemoveAll();
    if (nanChoices != 0)
        printf("[soundport] %d cases matched with NaNs the x87 and SSE2 chose differently\n", nanChoices);

    NfWarnMuted--;
    for (auto &s : saved)
        XbeOursWrite((uint32_t)(uintptr_t)s.at, s.bytes.data(), s.size);
}
