// The sounds: some free, some in use, in a random order
void RandomSounds(void) {
    for (int i = 0; i < SOUNDS; i++)
        RandomSound(&world.sounds[i]);
    LLISTINFO_tag *lists[2] = {&GameSoundList.freeList, &GameSoundList.activeList};
    for (int l = 0; l < 2; l++) {
        lists[l]->head = lists[l]->tail = NULL;
        lists[l]->count = 0;
        lists[l]->elementSize = sizeof(DYNAMICSOUNDS);
    }
    for (int i = 0; i < SOUNDS; i++) {
        uint32_t which = R(3);
        if (which == 2)
            continue;
        LLISTINFO_tag *list = lists[which];
        // Free ones stopped; those in use in any state, sometimes the free state
        world.sounds[i].playbackState = which == 0 ? 3 : (char)(R(6) == 0 ? 3 + R(2) : R(3));
        LLNODE_tag *node = (LLNODE_tag *)&world.sounds[i];
        node->prev = list->tail;
        node->next = NULL;
        if (list->tail != NULL)
            list->tail->next = node;
        else
            list->head = node;
        list->tail = node;
        list->count++;
    }
}

