void InstallFakes(const unsigned *real) {
    for (const Fake &f : kFakes) {
        bool keep = false;
        for (int i = 0; i < 6 && real[i] != 0; i++)
            keep |= real[i] == f.at;
        if (!keep)
            ShadowHook_Install(f.at, f.fake);
    }
}

