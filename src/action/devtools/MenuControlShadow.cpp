    world.create.font = R(3) ? Format() : NULL;
    world.create.text = R(3) ? Text() : NULL;
    world.create.x = S(600);
    world.create.y = S(440);
    world.create.width = R(6) ? (short)R(700) : S(1000);
    world.create.height = R(6) ? (short)R(520) : S(1000);
