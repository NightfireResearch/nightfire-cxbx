void Test(const char *group, const Case *list, int count, int trials) {
    int groupCases = cases, groupDiffer = differ;
    for (int c = 0; c < count; c++) {
        current = &list[c];
        for (int trial = 0; trial < trials; trial++) {
            RandomWorld();
            cases++;
            if (!ShadowCompare(regions, "animport", current->name, trial, RunTheirs, RunOurs))
                differ++;
        }
    }
    printf("[animport] %s: %d cases, %d differ\n", group, cases - groupCases, differ - groupDiffer);
}

