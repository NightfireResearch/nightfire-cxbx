// The stack below, as zeros: AnimFrameSet blends in the unused bones of a buffer it leaves uninitialised, which ours
// zeroes
__declspec(noinline) void ZeroStack(void) {
    volatile uint32_t below[0x2000];
    for (int i = 0; i < 0x2000; i++)
        below[i] = 0;
}

uint32_t RunTheirs() {
    argPos = 0;
    ZeroStack();
    return current->run(true);
}

