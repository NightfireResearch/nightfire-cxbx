float Coefficient(int i) {
    static const float scale[6] = {0.6f, 0.05f, 0.003f, 0.0001f, 0.000002f, 0.00000003f};
    return ShadowRandFloat(-scale[i], scale[i]);
}

void Put32(std::vector<uint8_t> &v, uint32_t x) {
    for (int i = 0; i < 4; i++)
        v.push_back((uint8_t)(x >> (i * 8)));
}

// One track: keys of so many frames (frames << 6 | coefficient mask) covering numFrames - 1, each followed by its
// coefficients; the key words are taken from u32s low half first, the first from the head's high half
void BuildTrack(std::vector<uint8_t> &out, int numFrames, bool quatZ) {
    struct Key {
        uint word;
        std::vector<float> coefs;
    };
    std::vector<Key> keys;
    int left = numFrames - 1;
    do {
        int frames = left <= 1 ? left : 1 + (int)ShadowRand((uint)left);
        if (ShadowRand(4) == 0)
            frames = left;
        if (frames < 1)
            frames = 1;
        left -= frames;
        Key k;
        uint mask = ShadowRand(64);
        if (ShadowRand(3) == 0)
            mask = (1u << (1 + ShadowRand(6))) - 1;
        k.word = ((uint)frames << 6) | mask;
        for (int i = 0; i < 6; i++) {
            if (mask & (1u << i)) {
                float c = Coefficient(i);
                if (i == 0 && quatZ && ShadowRand(3) == 0)
                    c += 4.0f;
                k.coefs.push_back(c);
            }
        }
        keys.push_back(k);
    } while (left > 0);

    size_t start = out.size();
    Put32(out, keys[0].word << 16);
    for (float c : keys[0].coefs)
        Put32(out, Bits(c));
    for (size_t i = 1; i < keys.size(); i += 2) {
        uint high = i + 1 < keys.size() ? keys[i + 1].word : 0;
        Put32(out, keys[i].word | (high << 16));
        for (float c : keys[i].coefs)
            Put32(out, Bits(c));
        if (i + 1 < keys.size()) {
            for (float c : keys[i + 1].coefs)
                Put32(out, Bits(c));
        }
    }
    uint32_t size = (uint32_t)(out.size() - start);
    out[start] = (uint8_t)size;
    out[start + 1] = (uint8_t)(size >> 8);
}

