// An extent: mostly ordinary, sometimes a signed zero or a NaN
float RandomExtent() {
    switch (ShadowRand(12)) {
    case 0: return 0.0f;
    case 1: return -0.0f;
    case 2: return nanf("");
    default: return ShadowRandFloat(-6.0f, 6.0f);
    }
}

