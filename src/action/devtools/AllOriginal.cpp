// NIGHTFIRE_ORIGINAL_ONLY=<prefixes>: only the subsystems whose names start with one of them (comma-separated)
static bool IsGameCode(unsigned address) {
    const CodeRange *range = NULL;
    for (const CodeRange &r : kCodeRanges) {
        if (r.start > address)
            break;
        range = &r;
    }
    if (range == NULL || !range->game)
        return false;
    // NIGHTFIRE_ORIGINAL_AT=<addresses>: only these functions (hex, comma-separated), for bisecting
    const char *at = getenv("NIGHTFIRE_ORIGINAL_AT");
    if (at != NULL && at[0] != 0) {
        for (const char *p = at; *p != 0;) {
            char *end;
            unsigned a = (unsigned)strtoul(p, &end, 16);
            if (end == p)
                break;
            if (a == address)
                return true;
            p = *end == ',' ? end + 1 : end;
        }
        return false;
    }
    const char *only = getenv("NIGHTFIRE_ORIGINAL_ONLY");
    if (only == NULL || only[0] == 0)
        return true;
    for (const char *p = only; *p != 0;) {
        size_t n = strcspn(p, ",");
        if (n != 0 && strncmp(range->subsystem, p, n) == 0)
            return true;
        p += n;
        if (*p == ',')
            p++;
    }
    return false;
}

// {name: address} of every data symbol in our DLL's map, a C++ name by its last part; a name twice is left out
static std::unordered_map<std::string, unsigned> ReadMap(void) {
    std::unordered_map<std::string, unsigned> out;
    HMODULE self = NULL;
    GetModuleHandleExA(GET_MODULE_HANDLE_EX_FLAG_FROM_ADDRESS | GET_MODULE_HANDLE_EX_FLAG_UNCHANGED_REFCOUNT,
                       (LPCSTR)&ReadMap, &self);
    char path[MAX_PATH];
    GetModuleFileNameA(self, path, MAX_PATH);
    char *dot = strrchr(path, '.');
    if (dot != NULL)
        strcpy(dot, ".map");
    FILE *file = fopen(path, "r");
    if (file == NULL) {
        printf("[original] %s is missing: the owned globals cannot be found\n", path);
        return out;
    }
    unsigned preferred = 0x10000000;
    std::unordered_map<std::string, int> seen;
    char line[1024];
    while (fgets(line, sizeof(line), file) != NULL) {
        unsigned value;
        if (sscanf(line, " Preferred load address is %x", &value) == 1) {
            preferred = value;
            continue;
        }
        char mangled[512], obj[256];
        unsigned section, offset;
        if (sscanf(line, " %x:%x %511s %x %255s", &section, &offset, mangled, &value, obj) != 5)
            continue;
        std::string name;
        // a global variable is ?Name@@3<type>; a function's static (?Name@?1??Function...) is not one of ours
        size_t length = strcspn(mangled + 1, "@");
        if (mangled[0] == '?' && mangled[1] != '?' && mangled[1] != '$' && strncmp(mangled + 1 + length, "@@3", 3) == 0)
            name = std::string(mangled + 1, length);
        else if (mangled[0] == '_')
            name = mangled + 1;
        else
            continue;
        if (++seen[name] == 1)
            out[name] = value - preferred + (unsigned)(size_t)self;
        else
            out.erase(name);
    }
    fclose(file);
    return out;
}

// Every owned global's copy of ours, by the game's address
struct OwnedCopy {
    unsigned game, size, ours;
};
static std::vector<OwnedCopy> g_copies;

// The copies found in the map, once: the shadow tests' tables can ask before the injection has run
static void FindCopies(void) {
    static bool found;
    if (found)
        return;
    found = true;
    std::unordered_map<std::string, unsigned> symbols = ReadMap();
    for (const OwnedGlobal &g : kOwnedGlobals) {
        auto it = symbols.find(g.name);
        if (it == symbols.end())
            printf("[original] %s (0x%08x) is not in the map: the game's code keeps its own copy\n", g.name, g.address);
        else
            g_copies.push_back({g.address, g.size, it->second});
    }
    std::sort(g_copies.begin(), g_copies.end(), [](const OwnedCopy &a, const OwnedCopy &b) { return a.game < b.game; });
}

void AllOriginal_RelocateOwned(void) {
    static bool relocated;
    if (relocated)
        return;
    relocated = true;
    FindCopies();
    int sites = 0;
    for (const OwnedGlobal &g : kOwnedGlobals) {
        unsigned left;
        unsigned ours = AllOriginal_Ours(g.address, &left);
        for (unsigned i = 0; ours != 0 && i < g.count; i++)
            sites += XbeRelocate(kOwnedSites[g.first + i], g.address, g.size, (const void *)(size_t)ours);
    }
    printf("[original] %d owned globals: the game's code uses ours (%d sites)\n", (int)g_copies.size(), sites);
    fflush(stdout);
}

unsigned XbeOurs(unsigned game) {
    unsigned left;
    unsigned ours = AllOriginal_Ours(game, &left);
    return ours != 0 ? ours : game;
}

void XbeOursRead(void *to, unsigned game, size_t size) {
    while (size != 0) {
        unsigned left;
        unsigned ours = AllOriginal_Ours(game, &left);
        size_t part = size < left ? size : left;
        memcpy(to, (const void *)(size_t)(ours != 0 ? ours : game), part);
        to = (uint8_t *)to + part;
        game += (unsigned)part;
        size -= part;
    }
}

void XbeOursWrite(unsigned game, const void *from, size_t size) {
    while (size != 0) {
        unsigned left;
        unsigned ours = AllOriginal_Ours(game, &left);
        size_t part = size < left ? size : left;
        memcpy((void *)(size_t)(ours != 0 ? ours : game), from, part);
        from = (const uint8_t *)from + part;
        game += (unsigned)part;
        size -= part;
    }
}

void XbeOursFill(unsigned game, int value, size_t size) {
    while (size != 0) {
        unsigned left;
        unsigned ours = AllOriginal_Ours(game, &left);
        size_t part = size < left ? size : left;
        memset((void *)(size_t)(ours != 0 ? ours : game), value, part);
        game += (unsigned)part;
        size -= part;
    }
}

unsigned AllOriginal_Ours(unsigned game, unsigned *left) {
    if (game < 0x00010000 || game >= 0x00400000) {   // not in the game's image: the heap, the stack, our DLL
        *left = 0xffffffffu - game;
        return 0;
    }
    FindCopies();
    auto it = std::upper_bound(g_copies.begin(), g_copies.end(), game,
                               [](unsigned a, const OwnedCopy &c) { return a < c.game; });
    if (it != g_copies.begin() && game < (it - 1)->game + (it - 1)->size) {
        --it;
        *left = it->game + it->size - game;
        return it->ours + (game - it->game);
    }
    *left = it != g_copies.end() ? it->game - game : 0xffffffffu - game;
    return 0;
}

void AllOriginal_Install(void) {
    AllOriginal_RelocateOwned();

    // The game's functions: each original back in place, and our port leading to it
    std::vector<unsigned> keep;
    for (const void *f : kKeep)
        keep.push_back(XbeOriginal_EntryOf((unsigned)(size_t)f));
    // NIGHTFIRE_ORIGINAL_KEEP=<addresses>: these ours too (hex, comma-separated), for a hunt that has found them
    if (const char *more = getenv("NIGHTFIRE_ORIGINAL_KEEP")) {
        for (const char *p = more; *p != 0;) {
            char *end;
            unsigned a = (unsigned)strtoul(p, &end, 16);
            if (end == p)
                break;
            keep.push_back(a);
            p = *end == ',' ? end + 1 : end;
        }
    }
    struct Swap {
        unsigned at, target;
    };
    std::vector<Swap> swaps;
    int kept = 0;
    for (int i = 0; i < XbeOriginal_Count(); i++) {
        unsigned at = XbeOriginal_At(i);
        if (!IsGameCode(at))
            continue;
        bool keepThis = false;
        for (unsigned k : keep)
            keepThis |= k == at;
        if (keepThis) {
            kept++;
            continue;
        }
        swaps.push_back({at, XbeOriginal_Target(at)});
    }
    int restored = 0, redirected = 0, shared = 0;
    for (const Swap &s : swaps) {
        XbeOriginal_Restore(s.at, true);
        restored++;
        // A port the linker folded with another, or one too close to the next, keeps its own code
        bool clash = false;
        for (const Swap &o : swaps)
            clash |= &o != &s && o.target >= s.target && o.target < s.target + 5;
        if (clash || s.target == 0) {
            shared++;
            continue;
        }
        DWORD old;
        unsigned char jump[5] = {0xe9};
        unsigned rel = s.at - (s.target + 5);
        memcpy(jump + 1, &rel, 4);
        VirtualProtect((void *)(size_t)s.target, 5, PAGE_EXECUTE_READWRITE, &old);
        memcpy((void *)(size_t)s.target, jump, 5);
        VirtualProtect((void *)(size_t)s.target, 5, old, &old);
        redirected++;
    }
    FlushInstructionCache(GetCurrentProcess(), NULL, 0);
    printf("[original] NIGHTFIRE_ORIGINAL=game: %d functions run as the original, %d of our ports lead to them, %d left "
           "(shared or too close), %d kept ours\n", restored, redirected, shared, kept);
    fflush(stdout);
}
