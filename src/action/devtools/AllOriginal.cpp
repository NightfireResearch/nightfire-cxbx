struct OwnedGlobal {
    const char *name;
    unsigned address;   // the game's copy
    unsigned size;
    unsigned first;     // its sites in kOwnedSites
    unsigned count;
};

struct CodeRange {
    unsigned start;     // to the next range's start
    bool game;          // the game's code, not the platform layer or a library
    const char *subsystem;
};

