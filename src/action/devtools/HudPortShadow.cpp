    if (spr->backupOnscreenHeight == 0)
        spr->backupOnscreenHeight = 1;
    spr->onscreenWidth = (short)((int)R(700) - 20);
    spr->onscreenHeight = (short)((int)R(700) - 20);
    spr->spritesheetX = (short)R(256);
