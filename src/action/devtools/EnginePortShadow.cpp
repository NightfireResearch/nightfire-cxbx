// A frame of the pause film: its runs exactly fill the 0x4000 pixels
void WomanFrameData(void) {
    uint8_t *at = world.womanFile;
    uint left = 0x4000;
    bool clear = true;
    while (left != 0) {
        uint count;
        if (clear) {
            count = R(3) == 0 ? 0 : R(400);
            if (count > left)
                count = left;
            left -= count;
        } else {
            count = R(5);
        }
        *at++ = (uint8_t)(count >> 8);
        *at++ = (uint8_t)count;
        if (!clear) {
            for (uint i = 0; i < count; i++) {
                uint length = R(256);
                if (length > left)
                    length = left;
                left -= length;
                *at++ = (uint8_t)length;
            }
        }
        clear = !clear;
    }
}

