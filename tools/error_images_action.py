"""Generates the pictures of the action engine's error screens from the XBE, as src/action/engine/XboxErrorImages.inc.

    python tools/error_images_action.py            write it
    python tools/error_images_action.py --check    fail if it is out of date

Needs disc/default.xbe. XboxError.cpp draws two pictures the game keeps as data: the debug font's (0x0019a9c0, 64 by
64 halfwords, nonzero for a set pixel) and the disc error screen's (0x001b52e8, 0x20000 bytes: a line of the message
in each language), which it copies whole into a texture. They are written as arrays of words, as a converter would.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import own_globals_action as o  # noqa: E402

OUT = os.path.join(REPO, 'src', 'action', 'engine', 'XboxErrorImages.inc')
FONT, FONT_HALFWORDS = 0x0019a9c0, 0x1000
DISC, DISC_WORDS = 0x001b52e8, 0x8000


def rows(words, fmt, per_line):
    return ['    ' + ', '.join(fmt % w for w in words[i:i + per_line]) + ',' for i in range(0, len(words), per_line)]


def generate():
    font = struct.unpack('<%dH' % FONT_HALFWORDS, o.xbe_bytes(FONT, 2 * FONT_HALFWORDS))
    disc = struct.unpack('<%dI' % DISC_WORDS, o.xbe_bytes(DISC, 4 * DISC_WORDS))
    out = ['// THIS FILE IS GENERATED by tools/error_images_action.py from disc/default.xbe. DO NOT MODIFY.', '',
           "// The debug font's picture: 64 by 64, nonzero for a set pixel",
           '// XBE_GLOBAL(0x%08x, 0x%x)' % (FONT, 2 * FONT_HALFWORDS),
           'static const uint16_t FontImage[0x%x] = {' % FONT_HALFWORDS]
    out += rows(font, '%d', 32)
    out += ['};', '', "// The disc error screen's picture, as XboxError.cpp copies it into the texture",
            '// XBE_GLOBAL(0x%08x, 0x%x)' % (DISC, 4 * DISC_WORDS),
            'static const uint32_t DiscErrorImage[0x%x] = {' % DISC_WORDS]
    out += rows(disc, '0x%08x', 10)
    out += ['};', '']
    return '\n'.join(out)


def main():
    text = generate()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old.replace('\r\n', '\n') != text:
            sys.exit('%s is out of date: run tools/error_images_action.py' % OUT)
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, REPO))


if __name__ == '__main__':
    main()
