"""Compiles src/common/gfx/fxaa.hlsl into src/common/gfx/fxaaBytecode.h.

FXAA's shaders are our own HLSL. The backend no longer compiles HLSL at run time (DXVK's native build has no
compiler), so the bytecode is generated once with this script and committed. Run it by hand on Windows after
changing fxaa.hlsl:

    python tools/gfx/fxaa_bytecode.py

It calls D3DCompile from the system's d3dcompiler_47.dll with the arguments fxaa.cpp used to pass at run time
(entry points vsmain and psmain, vs_3_0 and ps_3_0, optimisation level 3), so the bytecode is what the game
used to compile for itself.
"""
import ctypes
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'src', 'common', 'gfx', 'fxaa.hlsl')
OUTPUT = os.path.join(ROOT, 'src', 'common', 'gfx', 'fxaaBytecode.h')
D3DCOMPILE_OPTIMIZATION_LEVEL3 = 1 << 15


class Blob:
    """An ID3DBlob, through its vtable: GetBufferPointer is slot 3, GetBufferSize 4, Release 2."""
    def __init__(self, pointer):
        self.pointer = pointer
        vtable = ctypes.cast(ctypes.cast(pointer, ctypes.POINTER(ctypes.c_void_p))[0], ctypes.POINTER(ctypes.c_void_p))
        prototype = ctypes.WINFUNCTYPE(ctypes.c_void_p, ctypes.c_void_p)
        self._buffer = prototype(vtable[3])
        self._size = ctypes.WINFUNCTYPE(ctypes.c_size_t, ctypes.c_void_p)(vtable[4])
        self._release = ctypes.WINFUNCTYPE(ctypes.c_ulong, ctypes.c_void_p)(vtable[2])

    def data(self):
        return ctypes.string_at(self._buffer(self.pointer), self._size(self.pointer))

    def release(self):
        self._release(self.pointer)


def compile_entry(compiler, text, entry, profile):
    code, errors = ctypes.c_void_p(), ctypes.c_void_p()
    hr = compiler.D3DCompile(text, len(text), b'fxaa', None, None, entry.encode(), profile.encode(),
                             D3DCOMPILE_OPTIMIZATION_LEVEL3, 0, ctypes.byref(code), ctypes.byref(errors))
    if errors.value:
        message = Blob(errors.value)
        sys.stderr.write(message.data().decode(errors='replace'))
        message.release()
    if hr != 0:
        sys.exit('compiling %s as %s failed (0x%08x)' % (entry, profile, hr & 0xFFFFFFFF))
    blob = Blob(code.value)
    data = blob.data()
    blob.release()
    return data


def as_array(name, data):
    words = [int.from_bytes(data[i:i + 4], 'little') for i in range(0, len(data), 4)]
    lines = ['static const DWORD %s[%d] = {' % (name, len(words))]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def main():
    compiler = ctypes.WinDLL('d3dcompiler_47.dll')
    compiler.D3DCompile.argtypes = [ctypes.c_char_p, ctypes.c_size_t, ctypes.c_char_p, ctypes.c_void_p, ctypes.c_void_p,
                                    ctypes.c_char_p, ctypes.c_char_p, ctypes.c_uint, ctypes.c_uint,
                                    ctypes.POINTER(ctypes.c_void_p), ctypes.POINTER(ctypes.c_void_p)]
    compiler.D3DCompile.restype = ctypes.c_long
    text = open(SOURCE, 'rb').read().replace(b'\r\n', b'\n')
    vertex = compile_entry(compiler, text, 'vsmain', 'vs_3_0')
    pixel = compile_entry(compiler, text, 'psmain', 'ps_3_0')
    with open(OUTPUT, 'w', newline='\n') as f:
        f.write('// Generated by tools/gfx/fxaa_bytecode.py from fxaa.hlsl (D3DCompile, vs_3_0 / ps_3_0, optimisation level 3).\n')
        f.write('// Do not edit: change fxaa.hlsl and run the script again.\n\n')
        f.write(as_array('g_fxaaVertexShader', vertex) + '\n\n')
        f.write(as_array('g_fxaaPixelShader', pixel) + '\n')
    print('wrote %s: %d + %d bytes' % (OUTPUT, len(vertex), len(pixel)))


if __name__ == '__main__':
    main()
