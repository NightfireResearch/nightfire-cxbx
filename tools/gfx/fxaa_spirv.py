"""Compiles src/common/gfx/fxaa.hlsl's pixel shader into src/common/gfx/fxaaSpirv.h, for the SDL GPU backend.

The SDL GPU backend (src/common/gfx/sdlGpuBackend.cpp) runs the same FXAA pixel shader as the D3D9 backend, as
SPIR-V. Like fxaaBytecode.h it is generated once and committed. Run it after changing fxaa.hlsl, on a machine with
glslang (Ubuntu: glslang-tools; WSL2 here) and, to check the result, spirv-val (spirv-tools):

    python3 tools/gfx/fxaa_spirv.py

glslang compiles the HLSL (entry point psmain, DirectX 9 compatible mode for sampler2D and tex2Dlod). Its
resources and inputs come out at set 0 and location 0; the backend's interface (src/common/gfx/shaderSpirv.h)
wants the sampler at set 2, the constants at set 3 and the texture coordinate at location 2, so those decorations
are rewritten in the binary. The vertex shader is the backend's own (a ShaderBuilder program).
"""
import os
import struct
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SOURCE = os.path.join(ROOT, 'src', 'common', 'gfx', 'fxaa.hlsl')
OUTPUT = os.path.join(ROOT, 'src', 'common', 'gfx', 'fxaaSpirv.h')

OP_DECORATE, OP_VARIABLE, OP_TYPE_POINTER = 71, 59, 32
DECORATION_LOCATION, DECORATION_DESCRIPTOR_SET = 30, 34
STORAGE_UNIFORM_CONSTANT, STORAGE_INPUT, STORAGE_UNIFORM = 0, 1, 2


def instructions(words):
    at = 5
    while at < len(words):
        count, op = words[at] >> 16, words[at] & 0xFFFF
        yield at, op, words[at + 1:at + count]
        at += count


def rebind(words):
    pointer_storage = {}
    variable_storage = {}
    for _, op, operands in instructions(words):
        if op == OP_TYPE_POINTER:
            pointer_storage[operands[0]] = operands[1]
        elif op == OP_VARIABLE:
            variable_storage[operands[1]] = operands[2]
    for at, op, operands in instructions(words):
        if op != OP_DECORATE:
            continue
        target, decoration = operands[0], operands[1]
        storage = variable_storage.get(target)
        if decoration == DECORATION_DESCRIPTOR_SET and storage == STORAGE_UNIFORM_CONSTANT:
            words[at + 3] = 2
        elif decoration == DECORATION_DESCRIPTOR_SET and storage == STORAGE_UNIFORM:
            words[at + 3] = 3
        elif decoration == DECORATION_LOCATION and storage == STORAGE_INPUT:
            words[at + 3] = 2
    return words


def main():
    with tempfile.TemporaryDirectory() as folder:
        spv = os.path.join(folder, 'fxaa.spv')
        subprocess.run(['glslangValidator', '-D', '-V', '-S', 'frag', '-e', 'psmain', '--hlsl-dx9-compatible',
                        '-o', spv, SOURCE], check=True, stdout=subprocess.DEVNULL)
        data = open(spv, 'rb').read()
        words = rebind(list(struct.unpack('<%dI' % (len(data) // 4), data)))
        open(spv, 'wb').write(struct.pack('<%dI' % len(words), *words))
        try:
            subprocess.run(['spirv-val', '--target-env', 'vulkan1.0', spv], check=True)
        except FileNotFoundError:
            sys.stderr.write('spirv-val is not installed: the module is not validated\n')
    lines = ['// Generated by tools/gfx/fxaa_spirv.py from fxaa.hlsl (glslang, psmain, sets and location rewritten for',
             '// shaderSpirv.h). Do not edit: change fxaa.hlsl and run the script again.',
             '',
             'static const uint32_t g_fxaaPixelSpirv[%d] = {' % len(words)]
    for i in range(0, len(words), 8):
        lines.append('    ' + ', '.join('0x%08x' % w for w in words[i:i + 8]) + ',')
    lines.append('};')
    with open(OUTPUT, 'w', newline='\r\n') as f:
        f.write('\n'.join(lines) + '\n')
    print('wrote %s (%d words)' % (OUTPUT, len(words)))


if __name__ == '__main__':
    main()
