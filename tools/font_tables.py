"""Generates the action engine's three fonts from the XBE, as src/action/gfx/FontData.inc.

    python tools/font_tables.py            write it
    python tools/font_tables.py --check    fail if it is out of date

Needs disc/default.xbe and the nf-cross Docker image (the layouts, tools/xbe_layout.py). FontTable (Font.cpp, 0x0017bd90)
names a texture and a FONT_tag for fonts 1 to 3: each FONT_tag has its kerning pairs (kernCount KERN_tags) and its
glyphs (count CHARDATA_tags, each pointing at its own run of the kerning pairs). They are written as the font tool
would have: the pairs, the glyphs and the font, each a table of its own, named by the font's number in FontTable.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import own_globals_action as o  # noqa: E402
import xbe_layout  # noqa: E402

OUT = os.path.join(REPO, 'src', 'action', 'gfx', 'FontData.inc')
SOURCE = 'src/action/gfx/Font.cpp'
FONT_TABLE, FONTS = 0x0017bd90, 5


def read(a, n):
    return o.xbe_bytes(a, n) or bytes(n)


def generate():
    names, functions = o.our_names()
    out = ['// THIS FILE IS GENERATED by tools/font_tables.py from disc/default.xbe. DO NOT MODIFY.', '',
           "// The fonts FontTable (Font.cpp) names: each one's kerning pairs, its glyphs and the font.", '']
    table = struct.unpack('<%dI' % (2 * FONTS), read(FONT_TABLE, 8 * FONTS))
    for i in range(FONTS):
        at = table[2 * i + 1]
        if at < 0x00010000:
            continue   # none (entry 0 holds 0xfc, entry 4 nothing)
        kern_count, kern, first, last, count, chars = struct.unpack('<IIHHII', read(at, 0x14))
        kern_name, chars_name, font_name = 'Font%dKern' % i, 'Font%dChars' % i, 'Font%d' % i
        arrays = [(kern, 6 * kern_count, kern_name)]
        names[kern], names[chars] = kern_name, chars_name
        for type_, name, start, n, size in (('KERN_tag', kern_name, kern, kern_count, 6),
                                            ('CHARDATA_tag', chars_name, chars, count, 0x18)):
            text = xbe_layout.initialiser(SOURCE, type_, n, start, read, names, functions, arrays)
            out.append('// XBE_GLOBAL(0x%08x, 0x%x)' % (start, size * n))
            out.append('static %s %s[%d] = %s;' % (type_, name, n, xbe_layout.wrap(text, '')))
        text = xbe_layout.initialiser(SOURCE, 'FONT_tag', None, at, read, names, functions, arrays)
        out.append('// XBE_GLOBAL(0x%08x, 0x1c)' % at)
        out.append('static FONT_tag %s = %s;' % (font_name, xbe_layout.wrap(text, '')))
        out.append('')
    return '\n'.join(out)


def main():
    text = generate()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old.replace('\r\n', '\n') != text:
            sys.exit('%s is out of date: run tools/font_tables.py' % OUT)
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, REPO))


if __name__ == '__main__':
    main()
