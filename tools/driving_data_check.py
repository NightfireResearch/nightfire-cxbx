#!/usr/bin/env python3
"""Checks the driving engine's game data in our source against the user's own Driving.xbe. Run by hand: the build
needs neither the XBE nor this script (docs/driving/standalone.md).

    python tools/driving_data_check.py                 check the vtables and every owned global's initial data
    python tools/driving_data_check.py --dll PATH      the built drivinginject.dll to read (default Release/; its
                                                       .map beside it, from the MSVC build's /MAP)
    python tools/driving_data_check.py --list          also print each global that matches
    python tools/driving_data_check.py --vtables       rewrite src/driving/Vtables.h/.cpp
    python tools/driving_data_check.py --action        the action engine's owned globals instead (default.xbe,
                                                       Release/actioninject.dll; it has no vtables file yet), with
                                                       --dll, --list and --allow as above (docs/action-standalone.md)

The initial data: every owned global (an XBE_GLOBAL tag above a definition of our own, tools/global_coverage.py)
whose definition has an initialiser is found in the DLL by the map file, and its bytes are compared with the XBE's at
the tagged address - so a typo in a typed table, a float that does not round-trip or a wrong layout shows up here. A
word the DLL relocates is a pointer of ours: it matches when the XBE's word points at the same text (a string), and
is counted, not compared, when both point at code. A global the map does not list (internal linkage, or folded away
by the linker) is reported, as is one whose size differs from its tag. `--allow NAME` accepts a global's difference
(an initial value of ours that differs from the game's on purpose); the list below says why for each.

The vtables: src/driving/Vtables.h/.cpp hold our copy of every game vtable the source names (Vtable_<Class> for a
class with one vtable of its own in tools/vtables_driving.json, else Vtable_<address>): the vtable's words in the XBE
up to the next vtable, each slot the injection table's port of that original (src/driving/autogenerated_injections.inc,
so run tools/preprocess.py or a build first). CODE_TABLES below names the other tables of the game's functions our
code indexes (the event tables), which get the same treatment. A slot of an original we have no port of keeps its
address; the header lists them. The check regenerates them in memory and compares; --vtables writes them.
"""
import json
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import global_coverage as gc   # noqa: E402

ENGINE = "action" if "--action" in sys.argv else "driving"
gc.use_engine(ENGINE)
SRC = os.path.join(ROOT, "src", ENGINE)
XBE = gc.XBE
DLL = os.path.join(ROOT, "Release", ENGINE + "inject.dll")
VT_H = os.path.join(SRC, "Vtables.h")
VT_CPP = os.path.join(SRC, "Vtables.cpp")
VTABLES = os.path.join(HERE, "vtables_driving.json")
FUNCTIONS = os.path.join(HERE, "functions_driving.json")
INJECTIONS = os.path.join(SRC, "autogenerated_injections.inc")
RETAIL_ENTRY_KEY = 0xA8FC57AB
CODE_SECTIONS = {".text", "D3DX", "D3D", "XGRPH", "DSOUND", "XMV", "XPP"}

# Tables of the game's functions, by event number (Scheduler.cpp's RegisterEvent): our name, the game's address, the
# entries, what they are
CODE_TABLES = [
    ("MakeEventCallbacks", 0x0018bf38, 283, "each event's MakeEvent callback"),
    ("ResolveEventCallbacks", 0x001b6660, 283, "each event's CARP resolver"),
]

# Owned globals whose initial value is ours on purpose, by name: why
ALLOWED = {
    "FontDriver": "points at our NullFontDriver (Realgraph.cpp), the game's null driver table at 0x001d1770 written "
                  "with our functions",
    "DebugFont": "a font of our own design in the original's FNTX layout and size (engine/DebugFont.cpp): the "
                 "game's debug font is not ours to ship",
}


class Xbe:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        if self.data[:4] != b"XBEH":
            sys.exit("%s is not an XBE" % path)
        d = self.data
        base = struct.unpack_from("<I", d, 0x104)[0]
        count = struct.unpack_from("<I", d, 0x11C)[0]
        headers = struct.unpack_from("<I", d, 0x120)[0] - base
        self.sections = []
        for i in range(count):
            flags, va, vs, ra, rs, name_at = struct.unpack_from("<IIIIII", d, headers + i * 0x38)
            at = name_at - base
            self.sections.append((d[at:d.index(b"\0", at)].decode("ascii", "replace"), va, va + vs, ra, rs))

    def section(self, address):
        for s in self.sections:
            if s[1] <= address < s[2]:
                return s
        return None

    def read(self, address, size):
        out = bytearray()
        while size > 0:
            s = self.section(address)
            if s is None:
                raise ValueError("0x%08x is outside every section" % address)
            name, va, end, ra, rs = s
            n = min(size, end - address)
            lo = address - va
            chunk = self.data[ra + lo: ra + min(rs, lo + n)] if lo < rs else b""
            out += chunk + b"\0" * (n - len(chunk))
            address += n
            size -= n
        return bytes(out)

    def string_at(self, address):
        s = self.section(address)
        if s is None or s[0] not in (".rdata", ".data"):   # .data: the render methods' parameter names
            return None
        raw = self.read(address, min(1024, s[2] - address))
        end = raw.find(b"\0")
        return raw[:end] if end >= 0 else None


class Dll:
    """A PE image read from its file: bytes by virtual address, and the words its base relocations fix up."""
    def __init__(self, path):
        d = self.data = open(path, "rb").read()
        pe = struct.unpack_from("<I", d, 0x3c)[0]
        if d[pe:pe + 4] != b"PE\0\0":
            sys.exit("%s is not a PE image" % path)
        sections = struct.unpack_from("<H", d, pe + 6)[0]
        optional = struct.unpack_from("<H", d, pe + 20)[0]
        opt = pe + 24
        self.base = struct.unpack_from("<I", d, opt + 28)[0]
        reloc_rva, reloc_size = struct.unpack_from("<II", d, opt + 96 + 5 * 8)
        self.sections = []
        for i in range(sections):
            at = opt + optional + 40 * i
            name = d[at:at + 8].rstrip(b"\0").decode("ascii", "replace")
            vsize, rva, rsize, raw = struct.unpack_from("<IIII", d, at + 8)
            self.sections.append((name, self.base + rva, max(vsize, rsize), raw, rsize))
        self.relocated = set()
        at, end = reloc_rva, reloc_rva + reloc_size
        while at < end:
            page, size = struct.unpack("<II", self.read(self.base + at, 8))
            if size < 8:
                break
            for k in range((size - 8) // 2):
                entry = struct.unpack("<H", self.read(self.base + at + 8 + 2 * k, 2))[0]
                if entry >> 12 == 3:   # IMAGE_REL_BASED_HIGHLOW
                    self.relocated.add(self.base + page + (entry & 0xfff))
            at += size

    def section(self, address):
        for s in self.sections:
            if s[1] <= address < s[1] + s[2]:
                return s
        return None

    def read(self, address, size):
        s = self.section(address)
        if s is None:
            raise ValueError("0x%08x is outside the DLL" % address)
        name, va, vsize, raw, rsize = s
        lo = address - va
        chunk = self.data[raw + lo: raw + min(rsize, lo + size)] if lo < rsize else b""
        return chunk + b"\0" * (size - len(chunk))

    def string_at(self, address):
        if self.section(address) is None:
            return None
        raw = self.read(address, 1024)
        end = raw.find(b"\0")
        return raw[:end] if end >= 0 else None


def read_map(path):
    """{name: [(address, object file)]} for every public data or function symbol: a C++ name by its last part."""
    symbols = {}
    for line in open(path, encoding="latin-1"):
        m = re.match(r"\s*[0-9a-fA-F]{4}:[0-9a-fA-F]{8}\s+(\S+)\s+([0-9a-fA-F]{8})\s+(?:f\s+)?(?:i\s+)?(\S+)\s*$", line)
        if not m:
            continue
        mangled, address, obj = m.group(1), int(m.group(2), 16), m.group(3)
        if mangled.startswith("?") and not mangled.startswith("??") and not mangled.startswith("?$"):
            name = mangled[1:].split("@")[0]
        elif mangled.startswith("_"):
            name = mangled[1:]
        else:
            continue
        symbols.setdefault(name, []).append((address, obj.split(":")[-1]))
    return symbols


def initialised(path, line):
    """Whether the definition at path:line has an initialiser."""
    lines = open(os.path.join(ROOT, path), encoding="utf-8", errors="replace").read().splitlines()
    text = ""
    for l in lines[line - 1:line + 3]:
        text += l.split("//")[0]
        if ";" in text or "{" in text or "=" in text:
            break
    return "=" in text.split(";")[0]


def file_backed(xbe, address, size):
    """Whether the XBE's file holds the global's bytes. Past a section's file data (.bss) the game's initial value is
    zero until its code - the static initialisers - writes one, and ours may be that value already."""
    s = xbe.section(address)
    return s is not None and address + size <= s[1] + s[4]


def check_data(xbe, dll_path, listing):
    map_path = os.path.splitext(dll_path)[0] + ".map"
    for path in (dll_path, map_path):
        if not os.path.exists(path):
            sys.exit("%s is missing: build %sinject with MSVC first (--dll names another build)" % (path, ENGINE))
    dll = Dll(dll_path)
    symbols = read_map(map_path)
    globals_ = [g for g in gc.read_source()[0] if g["owned"]]

    def locate(g):
        candidates = symbols.get(g["name"], [])
        obj = os.path.splitext(os.path.basename(g["file"]))[0] + ".obj"
        if len(candidates) > 1:
            candidates = [c for c in candidates if c[1].lower() == obj.lower()] or candidates
        return candidates

    # Where each owned global and vtable copy of ours is, by the game's address: a pointer of ours to one of them
    # matches the game's pointer to its copy
    ours_by_game = []
    for g in globals_:
        c = locate(g)
        if len(c) == 1:
            ours_by_game.append((g["address"], g["size"], c[0][0]))
    for m in re.finditer(r"^extern void \*(\w+)\[(\d+)\];\s*// (0x[0-9a-fA-F]+)", read_text(VT_H) or "", re.M):
        c = symbols.get(m.group(1), [])
        if len(c) == 1:
            ours_by_game.append((int(m.group(3), 16), 4 * int(m.group(2)), c[0][0]))

    def same_object(gword, target):
        return any(a <= gword < a + n and target == mine + (gword - a) for a, n, mine in ours_by_game)

    # A code pointer of ours matches the game's when it leads to the port the injection table puts over the game's
    # function: our names by address (the map), the ports by the game's address (the table's WriteJmpTo lines)
    names_at = {}
    for name, places in symbols.items():
        for address, obj in places:
            names_at.setdefault(address, set()).add(name)
    ports = {}
    for m in re.finditer(r"^WriteJmpTo\((0x[0-9a-fA-F]+),.*//\s*(\w+)\s*$", read_text(INJECTIONS) or "", re.M):
        ports[int(m.group(1), 16)] = m.group(2)

    def same_code(gword, target):
        return gword in ports and ports[gword] in names_at.get(target, ())

    owned = [g for g in globals_ if initialised(g["file"], g["line"])]
    problems, unchecked, matched, pointers, by_code = [], [], 0, 0, 0
    for g in sorted(owned, key=lambda g: g["address"]):
        where = "%s:%d %s (0x%08x, 0x%x)" % (g["file"], g["line"], g["name"], g["address"], g["size"])
        if not file_backed(xbe, g["address"], g["size"]):
            by_code += 1
            continue
        candidates = locate(g)
        if len(candidates) != 1:
            unchecked.append("%s: %s" % (where, "not in the map (internal linkage)" if not candidates else
                                         "%d symbols of that name in the map" % len(candidates)))
            continue
        ours = candidates[0][0]
        game = xbe.read(g["address"], g["size"])
        mine = dll.read(ours, g["size"])
        bad = []
        for offset in range(0, g["size"], 4):
            gw, mw = game[offset:offset + 4], mine[offset:offset + 4]
            gword = struct.unpack("<I", gw.ljust(4, b"\0"))[0]
            if ours + offset in dll.relocated and len(mw) == 4:
                target = struct.unpack("<I", mw)[0]
                text = xbe.string_at(gword)
                if text is not None and dll.string_at(target) == text:
                    continue
                if same_object(gword, target):
                    continue
                s, t = xbe.section(gword), dll.section(target)
                if s is not None and s[0] in CODE_SECTIONS and t is not None and t[0] == ".text":
                    if gword in ports and not same_code(gword, target):
                        bad.append((offset, gword, "a pointer of ours to %s, not the port of %s" % (
                            "/".join(sorted(names_at.get(target, ()))) or "0x%08x" % target,
                            ports[gword])))
                        continue
                    pointers += 1
                    continue
                bad.append((offset, gword, "a pointer of ours to 0x%08x" % target))
            elif gw != mw:
                bad.append((offset, gword, mw.hex()))
        if bad and g["name"] not in ALLOWED:
            problems.append("%s: %d words differ from the XBE's, first %s" % (
                where, len(bad), ", ".join("+0x%x game %08x ours %s" % b for b in bad[:4])))
            continue
        if listing:
            print("ok   %s%s" % (where, " (allowed: %s)" % ALLOWED[g["name"]] if bad else ""))
        matched += 1
    for line in unchecked:
        print("not checked: " + line)
    print("%s_data_check: %d initialised owned globals: %d match the XBE (%d code pointers in them, each the port "
          "of the game's where the injection table names one), %d in .bss (set by the game's code, not compared), "
          "%d not checked, %d differ" %
          (ENGINE, len(owned), matched, pointers, by_code, len(unchecked), len(problems)))
    return problems


# ---- the vtables

def vtable_names():
    """{address: our name} for the game's vtables: Vtable_<Class> for a class with one vtable of its own (from
    tools/vtables_driving.json), Vtable_<address> for the rest."""
    data = json.load(open(VTABLES))
    names = {}
    for cls, info in data["classes"].items():
        ident = cls.replace("::", "_")
        if len(info["own"]) == 1 and re.fullmatch(r"[A-Za-z_]\w*", ident):
            names[int(info["own"][0], 16)] = "Vtable_" + ident
    taken = {}
    for address, name in list(names.items()):
        if name in taken:   # two classes that flatten to one name
            names[address] = "Vtable_%08x" % address
            names[taken[name]] = "Vtable_%08x" % taken[name]
        taken[name] = address
    return names, [int(a, 16) for a in data["vtables"]]


def source_files():
    for folder, dirs, files in os.walk(SRC):
        for f in sorted(files):
            if f.endswith((".c", ".cpp", ".h", ".hpp")) and not f.startswith("autogenerated") and \
                    f not in ("Vtables.h", "Vtables.cpp"):
                yield os.path.join(folder, f)


def vtable_files(xbe):
    """The text of Vtables.h and Vtables.cpp: our copy of each game vtable the source names, the slots our functions -
    the injection table's for each original - so an object we construct dispatches to our code."""
    names, starts = vtable_names()
    by_name = {n: a for a, n in names.items()}
    wanted = set()
    for path in source_files():
        for m in re.finditer(r"\bVtable_(\w+)\b", open(path, encoding="utf-8", errors="replace").read()):
            name = "Vtable_" + m.group(1)
            if name in by_name:
                wanted.add(by_name[name])
            elif re.fullmatch(r"[0-9a-f]{8}", m.group(1)):
                wanted.add(int(m.group(1), 16))
            else:
                sys.exit("%s: %s is not a vtable tools/vtables_driving.json knows" % (os.path.relpath(path, ROOT), name))
    if not os.path.exists(INJECTIONS):
        sys.exit("%s is missing: run python tools/preprocess.py (or a build) first" % os.path.relpath(INJECTIONS, ROOT))
    inj = open(INJECTIONS, encoding="utf-8").read()
    ours = {int(a, 16): e for a, e in re.findall(r"WriteJmpTo\((0x[0-9a-f]+), (XbeAddress\(.*?\))\);", inj)}
    functions = {int(f["address"], 16): f["name"] for f in json.load(open(FUNCTIONS, encoding="utf-8"))}
    boundaries = sorted(set(starts) | wanted)
    header = ["// Our copies of the game's vtables and of its tables of event callbacks: each slot is our port of the",
              "// original the game's table names. Written by tools/driving_data_check.py --vtables from Driving.xbe and",
              "// the injection table; python tools/driving_data_check.py checks them.", "",
              "#ifndef DRIVING_VTABLES_H_", "#define DRIVING_VTABLES_H_", ""]
    body = ["// Our copies of the game's vtables (Vtables.h).", "",
            '#include "../common/xbeAbi.h"', '#include "../common/xbeOverload.h"',
            '#include "autogenerated_injection_includes.inc"', '#include "Vtables.h"', ""]
    missing = []
    for address in sorted(wanted):
        name = names.get(address, "Vtable_%08x" % address)
        k = boundaries.index(address)
        end = boundaries[k + 1] if k + 1 < len(boundaries) else address + 0x400
        slots = []
        at = address
        while at < end:
            word = struct.unpack("<I", xbe.read(at, 4))[0]
            s = xbe.section(word)
            if s is None or s[0] not in CODE_SECTIONS:
                break
            slots.append(word)
            at += 4
        if not slots:
            sys.exit("0x%08x (%s) holds no code address" % (address, name))
        header.append("extern void *%s[%d];   // 0x%08x" % (name, len(slots), address))
        body.append("void *%s[%d] = {   // 0x%08x" % (name, len(slots), address))
        for i, word in enumerate(slots):
            if word in ours:
                body.append("    (void *)%s,   // %d" % (ours[word], i))
            else:
                missing.append((name, i, word, functions.get(word, "?")))
                body.append("    (void *)0x%08x,   // %d: %s, not ours" % (word, i, functions.get(word, "?")))
        body.append("};")
        body.append("")
    for name, address, count, what in CODE_TABLES:
        header.append("extern void *%s[%d];   // 0x%08x, %s" % (name, count, address, what))
        body.append("void *%s[%d] = {   // 0x%08x, %s" % (name, count, address, what))
        for i in range(count):
            word = struct.unpack("<I", xbe.read(address + 4 * i, 4))[0]
            if word == 0:
                body.append("    nullptr,   // %d" % i)
            elif word in ours:
                body.append("    (void *)%s,   // %d" % (ours[word], i))
            else:
                missing.append((name, i, word, functions.get(word, "?")))
                body.append("    (void *)0x%08x,   // %d: %s, not ours" % (word, i, functions.get(word, "?")))
        body.append("};")
        body.append("")
    header.append("")
    if missing:
        header.append("// Slots still holding an original's address (no port of it):")
        for name, i, word, fname in missing:
            header.append("//   %s[%d] 0x%08x %s" % (name, i, word, fname))
        header.append("")
    header += ["#endif // DRIVING_VTABLES_H_", ""]
    return "\n".join(header), "\n".join(body), len(wanted), len(missing)


def read_text(path):
    return open(path, encoding="utf-8").read().replace("\r\n", "\n") if os.path.exists(path) else None


def main():
    if not os.path.exists(XBE):
        sys.exit("driving_data_check.py: %s is missing: put your own copy of the XBE in disc/ (see README.md)" %
                 os.path.relpath(XBE, ROOT))
    xbe = Xbe(XBE)
    problems = []
    if ENGINE == "action":
        main_data(xbe, problems)
        return
    header, body, count, missing = vtable_files(xbe)
    if "--vtables" in sys.argv:
        for path, text in ((VT_H, header), (VT_CPP, body)):
            if read_text(path) != text:
                with open(path, "w", encoding="utf-8", newline="\n") as f:
                    f.write(text)
        print("driving_data_check: wrote %d vtables, %d slots without a port" % (count, missing))
        return
    for path, text in ((VT_H, header), (VT_CPP, body)):
        if read_text(path) != text:
            problems.append("%s differs from the XBE and the injection table: python tools/driving_data_check.py "
                            "--vtables rewrites it" % os.path.relpath(path, ROOT))
    print("driving_data_check: %d vtables, %d slots without a port" % (count, missing))
    main_data(xbe, problems)


def main_data(xbe, problems):
    dll = DLL
    if "--dll" in sys.argv:
        dll = sys.argv[sys.argv.index("--dll") + 1]
    for name in [sys.argv[i + 1] for i, a in enumerate(sys.argv) if a == "--allow"]:
        ALLOWED[name] = "--allow"
    problems += check_data(xbe, dll, "--list" in sys.argv)
    if problems:
        sys.exit("\n".join(problems))


if __name__ == "__main__":
    main()
