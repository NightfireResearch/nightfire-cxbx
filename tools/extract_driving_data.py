#!/usr/bin/env python3
"""The driving engine's game data, taken from the user's own Driving.xbe at build time (docs/driving/standalone.md).

    python tools/extract_driving_data.py           write the generated files (the build runs this)
    python tools/extract_driving_data.py --list    also print what each global got

Our source holds no copy of the game's tables. A global whose initial value is game data is defined without one and
names itself to this script with XBE_INITIAL (src/driving/data/XbeData.h):

    // XBE_GLOBAL(0x001d9d88, 0x100)
    uint16_t PanAzimuth[128];
    XBE_INITIAL(PanAzimuth);

For each, the address and size come from the XBE_GLOBAL tag above the definition, and the bytes from the XBE's file
data (zero past it, in .bss). A word that points at a NUL-terminated string in .rdata becomes a pointer to the same text
as a string literal of ours; any other word pointing into the image stops the script, since our copy cannot point
there - write such a table in the source, with our own names. A tag ending in `raw` takes the bytes as they are.

Our copies of the game's vtables come from here too: the source names one as Vtable_<Class> (a class with one vtable
of its own in tools/vtables_driving.json) or Vtable_<address>, and the slots - the vtable's words in the XBE up to the
next vtable - are our functions, taken from the injection table (src/driving/autogenerated_injections.inc, so the
build runs tools/preprocess.py first). An object we construct then dispatches straight to our code. CODE_TABLES
below names the other tables of the game's functions our code indexes (the event tables) and gets the same treatment.
A slot of an original we have no port of keeps its address; the header lists them.

Written (gitignored, like the other generated files):
  src/driving/autogenerated_data.h      XbeDataSize_<name> and XbeData_<name> for each global
  src/driving/autogenerated_data.cpp    the bytes and the relocations
  src/driving/autogenerated_vtables.h/.cpp   the vtables and code tables
  src/driving/devtools/autogenerated_code_map.inc   tools/code_ranges_driving.txt as a table, for
                                        NIGHTFIRE_TRAP_ORIGINAL (devtools/StandaloneTraps.cpp)
A file is rewritten only when its text changes, so an unchanged build recompiles nothing.
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
SRC = os.path.join(ROOT, "src", "driving")
XBE = os.path.join(ROOT, "disc", "Driving.xbe")
CODE_RANGES = os.path.join(HERE, "code_ranges_driving.txt")
OUT_H = os.path.join(SRC, "autogenerated_data.h")
OUT_CPP = os.path.join(SRC, "autogenerated_data.cpp")
OUT_CODE_MAP = os.path.join(SRC, "devtools", "autogenerated_code_map.inc")
OUT_VT_H = os.path.join(SRC, "autogenerated_vtables.h")
OUT_VT_CPP = os.path.join(SRC, "autogenerated_vtables.cpp")
VTABLES = os.path.join(HERE, "vtables_driving.json")
FUNCTIONS = os.path.join(HERE, "functions_driving.json")
INJECTIONS = os.path.join(SRC, "autogenerated_injections.inc")
IMAGE_START, IMAGE_END = 0x00010000, 0x00254F40
RETAIL_ENTRY_KEY = 0xA8FC57AB


class Xbe:
    def __init__(self, path):
        self.data = open(path, "rb").read()
        if self.data[:4] != b"XBEH":
            sys.exit("%s is not an XBE" % path)
        d = self.data
        base = struct.unpack_from("<I", d, 0x104)[0]
        count = struct.unpack_from("<I", d, 0x11C)[0]
        headers = struct.unpack_from("<I", d, 0x120)[0] - base
        self.sections = []
        for i in range(count):
            flags, va, vs, ra, rs, name_at = struct.unpack_from("<IIIIII", d, headers + i * 0x38)
            at = name_at - base
            self.sections.append((d[at:d.index(b"\0", at)].decode("ascii", "replace"), va, va + vs, ra, rs))
        self.entry = struct.unpack_from("<I", d, 0x128)[0] ^ RETAIL_ENTRY_KEY

    def section(self, address):
        for s in self.sections:
            if s[1] <= address < s[2]:
                return s
        return None

    def read(self, address, size):
        out = bytearray()
        while size > 0:
            s = self.section(address)
            if s is None:
                raise ValueError("0x%08x is outside every section" % address)
            name, va, end, ra, rs = s
            n = min(size, end - address)
            lo = address - va
            chunk = self.data[ra + lo: ra + min(rs, lo + n)] if lo < rs else b""
            out += chunk + b"\0" * (n - len(chunk))
            address += n
            size -= n
        return bytes(out)

    def string_at(self, address):
        """The text of a NUL-terminated printable string in .rdata starting at address, or None."""
        s = self.section(address)
        if s is None or s[0] != ".rdata":
            return None
        raw = self.read(address, min(1024, s[2] - address))
        end = raw.find(b"\0")
        if end < 0:
            return None
        if address > s[1] and self.read(address - 1, 1) != b"\0" and address % 4 != 0:
            return None   # the middle of another string
        text = raw[:end]
        if not all(32 <= c < 127 or c in (9, 10, 13) or c >= 0xa0 for c in text):
            return None
        return text


def c_string(raw):
    out = []
    for c in raw:
        if c == 0x22 or c == 0x5c:
            out.append("\\" + chr(c))
        elif 32 <= c < 127:
            out.append(chr(c))
        else:
            out.append("\\%03o" % c)
    return '"' + "".join(out) + '"'


def source_files():
    for folder, dirs, files in os.walk(SRC):
        for f in sorted(files):
            if f.endswith((".c", ".cpp", ".h", ".hpp")) and not f.startswith("autogenerated"):
                yield os.path.join(folder, f)


def find_initials():
    """(name, address, size, raw, file, line) for every XBE_INITIAL(name) in our source."""
    found = []
    for path in source_files():
        text = open(path, encoding="utf-8", errors="replace").read()
        names = re.findall(r"^\s*XBE_INITIAL\(\s*(\w+)\s*\)", text, re.M)
        if not names:
            continue
        lines = text.splitlines()
        rel = os.path.relpath(path, ROOT).replace("\\", "/")
        for name in names:
            tag = None
            for i, line in enumerate(lines):
                m = re.search(r"//\s*XBE_GLOBAL\(\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\)(.*)", line)
                if m:
                    tag = (int(m.group(1), 16), int(m.group(2), 0), "raw" in m.group(3).split(), i + 1)
                    continue
                if tag and re.search(r"\b%s\s*(\[[^\]]*\]\s*)*(;|=|\{)" % re.escape(name), line) \
                        and not line.lstrip().startswith(("XBE_INITIAL", "//", "#")):
                    found.append((name, tag[0], tag[1], tag[2], rel, i + 1))
                    break
                if line.strip() and not line.lstrip().startswith("//"):
                    tag = None
            else:
                sys.exit("%s: XBE_INITIAL(%s) has no definition under an XBE_GLOBAL tag in the same file" % (rel, name))
    return found


def write_if_changed(path, text):
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != text:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)


CODE_SECTIONS = {".text", "D3DX", "D3D", "XGRPH", "DSOUND", "XPP"}
# Tables of the game's functions, by event number (Scheduler.cpp's RegisterEvent): our name, the game's address, the
# entries, what they are
CODE_TABLES = [
    ("MakeEventCallbacks", 0x0018bf38, 283, "each event's MakeEvent callback"),
    ("ResolveEventCallbacks", 0x001b6660, 283, "each event's CARP resolver"),
]


def vtable_names():
    """{address: our name} for the game's vtables: Vtable_<Class> for a class with one vtable of its own (from
    tools/vtables_driving.json), Vtable_<address> for the rest."""
    import json
    data = json.load(open(VTABLES))
    names = {}
    for cls, info in data["classes"].items():
        ident = cls.replace("::", "_")
        if len(info["own"]) == 1 and re.fullmatch(r"[A-Za-z_]\w*", ident):
            names[int(info["own"][0], 16)] = "Vtable_" + ident
    taken = {}
    for address, name in list(names.items()):
        if name in taken:   # two classes that flatten to one name
            names[address] = "Vtable_%08x" % address
            names[taken[name]] = "Vtable_%08x" % taken[name]
        taken[name] = address
    return names, [int(a, 16) for a in data["vtables"]]


def generate_vtables(xbe):
    """src/driving/autogenerated_vtables.h/.cpp: our copy of each game vtable the source names (Vtable_<Class> or
    Vtable_<address>), the slots our functions - the injection table's for each original - so an object we
    construct dispatches to our code without going through the original's entry. A slot of an original we have no
    port of keeps its address (a standalone build has to give it one); the generated header lists them."""
    names, starts = vtable_names()
    by_name = {n: a for a, n in names.items()}
    wanted = set()
    for path in source_files():
        for m in re.finditer(r"\bVtable_(\w+)\b", open(path, encoding="utf-8", errors="replace").read()):
            name = "Vtable_" + m.group(1)
            if name in by_name:
                wanted.add(by_name[name])
            elif re.fullmatch(r"[0-9a-f]{8}", m.group(1)):
                wanted.add(int(m.group(1), 16))
            else:
                sys.exit("%s: %s is not a vtable tools/vtables_driving.json knows" % (os.path.relpath(path, ROOT), name))
    inj = open(INJECTIONS, encoding="utf-8").read()
    ours = {int(a, 16): e for a, e in re.findall(r"WriteJmpTo\((0x[0-9a-f]+), (XbeAddress\(.*?\))\);", inj)}
    import json
    functions = {int(f["address"], 16): f["name"] for f in json.load(open(FUNCTIONS, encoding="utf-8"))}
    boundaries = sorted(set(starts) | wanted)
    header = ["// Generated by tools/extract_driving_data.py from Driving.xbe and the injection table - do not edit.",
              "// Our copies of the game's vtables (see generate_vtables there).", "",
              "#ifndef DRIVING_AUTOGENERATED_VTABLES_H_", "#define DRIVING_AUTOGENERATED_VTABLES_H_", ""]
    body = ["// Generated by tools/extract_driving_data.py from Driving.xbe and the injection table - do not edit.", "",
            '#include "../common/xbeAbi.h"', '#include "../common/xbeOverload.h"',
            '#include "autogenerated_injection_includes.inc"', '#include "autogenerated_vtables.h"', ""]
    missing = []
    for address in sorted(wanted):
        name = names.get(address, "Vtable_%08x" % address)
        k = boundaries.index(address)
        end = boundaries[k + 1] if k + 1 < len(boundaries) else address + 0x400
        slots = []
        at = address
        while at < end:
            word = struct.unpack("<I", xbe.read(at, 4))[0]
            s = xbe.section(word)
            if s is None or s[0] not in CODE_SECTIONS:
                break
            slots.append(word)
            at += 4
        if not slots:
            sys.exit("0x%08x (%s) holds no code address" % (address, name))
        header.append("extern void *%s[%d];   // 0x%08x" % (name, len(slots), address))
        body.append("void *%s[%d] = {   // 0x%08x" % (name, len(slots), address))
        for i, word in enumerate(slots):
            if word in ours:
                body.append("    (void *)%s,   // %d" % (ours[word], i))
            else:
                missing.append((name, i, word, functions.get(word, "?")))
                body.append("    (void *)0x%08x,   // %d: %s, not ours" % (word, i, functions.get(word, "?")))
        body.append("};")
        body.append("")
    # The other tables of the game's functions our code indexes: the same, with their NULLs
    for name, address, count, what in CODE_TABLES:
        header.append("extern void *%s[%d];   // 0x%08x, %s" % (name, count, address, what))
        body.append("void *%s[%d] = {   // 0x%08x, %s" % (name, count, address, what))
        for i in range(count):
            word = struct.unpack("<I", xbe.read(address + 4 * i, 4))[0]
            if word == 0:
                body.append("    nullptr,   // %d" % i)
            elif word in ours:
                body.append("    (void *)%s,   // %d" % (ours[word], i))
            else:
                missing.append((name, i, word, functions.get(word, "?")))
                body.append("    (void *)0x%08x,   // %d: %s, not ours" % (word, i, functions.get(word, "?")))
        body.append("};")
        body.append("")
    header.append("")
    if missing:
        header.append("// Slots still holding an original's address (no port of it):")
        for name, i, word, fname in missing:
            header.append("//   %s[%d] 0x%08x %s" % (name, i, word, fname))
        header.append("")
    header += ["#endif // DRIVING_AUTOGENERATED_VTABLES_H_", ""]
    write_if_changed(OUT_VT_H, "\n".join(header))
    write_if_changed(OUT_VT_CPP, "\n".join(body))
    print("extract_driving_data.py: %d vtables, %d slots without a port" % (len(wanted), len(missing)))


def main():
    if not os.path.exists(XBE):
        sys.exit("extract_driving_data.py: %s is missing. The driving engine's game data is taken from your own copy "
                 "of Driving.xbe at build time: put it in disc/ (see README.md)." % os.path.relpath(XBE, ROOT))
    xbe = Xbe(XBE)
    listing = "--list" in sys.argv

    initials = find_initials()
    seen = {}
    for name, address, size, raw, path, line in initials:
        if name in seen:
            sys.exit("%s:%d: XBE_INITIAL(%s) - another global of that name is extracted at %s" % (path, line, name,
                                                                                                    seen[name]))
        seen[name] = "%s:%d" % (path, line)

    header = ["// Generated by tools/extract_driving_data.py from Driving.xbe - do not edit.",
              "// The initial values of the globals named by XBE_INITIAL (data/XbeData.h).", "",
              "#ifndef DRIVING_AUTOGENERATED_DATA_H_", "#define DRIVING_AUTOGENERATED_DATA_H_", ""]
    body = ["// Generated by tools/extract_driving_data.py from Driving.xbe - do not edit.", "",
            '#include "data/XbeData.h"', ""]
    problems = []
    for name, address, size, raw, path, line in sorted(initials, key=lambda t: t[1]):
        data = xbe.read(address, size)
        padded = data + b"\0" * (-len(data) % 4)
        words = list(struct.unpack("<%dI" % (len(padded) // 4), padded))
        relocations = []
        if not raw:
            for i, w in enumerate(words):
                if i * 4 + 4 > size or not IMAGE_START <= w < IMAGE_END:
                    continue
                text = xbe.string_at(w)
                if text is not None:
                    relocations.append((i * 4, c_string(text), w))
                    words[i] = 0
                else:
                    problems.append("%s:%d: %s+0x%x holds 0x%08x, an address in the XBE (%s) that is not a string: "
                                    "write the table in the source, or tag it `raw` if it is a number" %
                                    (path, line, name, i * 4, w, (xbe.section(w) or ("?",))[0]))
        header.append("constexpr uint32_t XbeDataSize_%s = 0x%x;   // %s:%d, 0x%08x" % (name, size, path, line, address))
        header.append("extern const XbeBlob XbeData_%s;" % name)
        body.append("// %s (%s:%d), 0x%08x" % (name, path, line, address))
        body.append("static const uint32_t %s_words[%d] = {" % (name, len(words)))
        for i in range(0, len(words), 8):
            body.append("    " + ", ".join("0x%08x" % w for w in words[i:i + 8]) + ",")
        body.append("};")
        if relocations:
            body.append("static const XbeRelocation %s_relocations[%d] = {" % (name, len(relocations)))
            for offset, literal, was in relocations:
                body.append("    { 0x%x, %s },   // 0x%08x" % (offset, literal, was))
            body.append("};")
            body.append("extern const XbeBlob XbeData_%s = { %s_words, 0x%x, %s_relocations, %d };" %
                        (name, name, size, name, len(relocations)))
        else:
            body.append("extern const XbeBlob XbeData_%s = { %s_words, 0x%x, nullptr, 0 };" % (name, name, size))
        body.append("")
        if listing:
            print("%-28s %08x +0x%-5x %d strings  %s:%d" % (name, address, size, len(relocations), path, line))
    if problems:
        sys.exit("\n".join(problems))
    header += ["", "#endif // DRIVING_AUTOGENERATED_DATA_H_", ""]
    write_if_changed(OUT_H, "\n".join(header))
    write_if_changed(OUT_CPP, "\n".join(body))

    generate_vtables(xbe)

    ranges = [l.split() for l in open(CODE_RANGES) if l.strip() and not l.startswith("#")]
    write_if_changed(OUT_CODE_MAP, "// Generated by tools/extract_driving_data.py from tools/code_ranges_driving.txt - "
                                   "do not edit.\n" + "".join("{0x%s, 0x%s},\n" % (lo, hi) for lo, hi in ranges))
    print("extract_driving_data.py: %d globals' initial data from %s, %d code ranges" %
          (len(initials), os.path.relpath(XBE, ROOT), len(ranges)))


if __name__ == "__main__":
    main()
