def read_clang_logs(directory):
    seen = {}
    for f in sorted(os.listdir(directory)):
        if not f.endswith(".log"):
            continue
        for l in open(os.path.join(directory, f), encoding="utf-8", errors="replace"):
            m = re.match(r"^(.+?):(\d+):\d+: (error|warning): (.*)$", l.strip())
            if not m:
                continue
            path = os.path.normpath(m.group(1)).replace(os.sep, "/")
            msg = m.group(4)
            if "static assertion" in msg:
                cat = "static_assert"
            elif "naked" in msg:
                cat = "naked"
            elif any(s in msg for s in ("redefinition", "redeclared", "undefined template", "no matching")):
                cat = "calling-convention templates"
            elif "[-W" in msg:
                cat = re.search(r"\[-W([\w-]+)\]", msg).group(1)
            else:
                cat = "other"
            seen.setdefault((cat, path, int(m.group(2))), msg)
    return seen


