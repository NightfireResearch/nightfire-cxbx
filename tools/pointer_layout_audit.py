#!/usr/bin/env python3
"""What a 64-bit build of the standalone driving engine has to change: the structures whose layout depends on the
size of a pointer, the layout checks that would fail, the conversions between pointers and 32-bit integers, the x87
assembly and the calling conventions (docs/driving/64-bit.md).

    python tools/pointer_layout_audit.py                  the counts
    python tools/pointer_layout_audit.py --md             the same as the Markdown tables docs/driving/64-bit.md keeps
    python tools/pointer_layout_audit.py --list KIND      every occurrence of one kind (a prefix will do: "cast.")
    python tools/pointer_layout_audit.py --file PATH      every finding in the files whose path contains PATH
    python tools/pointer_layout_audit.py --struct NAME    one structure: its pointer-sized members and its checks
    python tools/pointer_layout_audit.py --clang-log DIR  also summarise a 64-bit syntax check's logs (one per source,
                                                          --probe-script prints the script that makes them) and
                                                          compare its failed layout checks with this tool's
    python tools/pointer_layout_audit.py --probe-script   the 64-bit syntax check, for the nf-cross image

It reads the standalone executable's sources (CMakeLists.txt: drivinginject's list less devtools and the injection,
as the driving_standalone target takes it) and every header under src/driving and src/common, outside devtools/;
--harness adds driving_standalone_test's three devtools files. Generated files (src/driving/autogenerated_*) are read
when a build has written them. The reading is textual - a header parser, not a compiler - so the counts are a
measure to re-run as the port proceeds, and the --clang-log comparison says how far to trust them.

Kinds (--list):
  struct.memory         a structure with pointer-sized members that nothing loads from a file: on 64-bit it grows
  struct.file           a structure read in place from the game's data (the LOADERS table below, and what they
                        embed): its pointers are 32-bit words in the file and must stay 32-bit
  struct.candidate      a pointer-bearing structure whose comment says it is a record, a file or a packet: to look at
  member.long           a `long` member: 4 bytes on Windows (LLP64), 8 on 64-bit Linux and macOS (LP64)
  assert.size           a static_assert on the size of a pointer-bearing structure: fails on 64-bit
  assert.offset         a static_assert on the offset of a member after a pointer-sized one: fails on 64-bit
  assert.unknown        a size or offset check on a type the parser cannot place (a template parameter, a typedef)
  cast.ptr_to_u32       a pointer made a 32-bit integer explicitly ((uint32_t)(uintptr_t)p, int(uintptr_t(p))...):
                        compiles silently on 64-bit and truncates
  cast.u32_to_ptr       a 32-bit integer made a pointer through uintptr_t: right only below 4 GB
  cast.int_ptr          a C-style cast between a pointer and int/uint32_t/DWORD without uintptr_t
  mask.addr32           an address masked with a 32-bit constant (& 0xffffff80, & ~3u): clears the high half
  alloc.literal         an object allocated by a literal size rather than sizeof: wrong once its structure grows
  alloc.ptr4            an allocation of an array of pointers sized `n << 2`, `n * 4` or a literal: too small
  word.stream           a pointer read out of a uint32_t word stream (`(T *)*p++`, `(T *)p[i]`)
  print.ptr             a printf-style format given a pointer as %x through a cast
  asm.x87               a naked function with x87 arithmetic (the transcendentals and the x87 chains)
  asm.adaptor           a naked register-argument adaptor (AUTOLTCG, *Regs, Eax...) for originals: injection only
  asm.injected          a naked function inside #ifndef NIGHTFIRE_STANDALONE
  asm.other             any other naked function
  callconv              __thiscall, __stdcall, __fastcall, WINAPI/NTAPI/CALLBACK
"""
