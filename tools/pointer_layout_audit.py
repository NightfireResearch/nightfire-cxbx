# Structures

class Member:
    def __init__(self, name, kind, base, line):
        self.name, self.kind, self.base, self.line = name, kind, base, line


class Struct:
    def __init__(self, name, src, line, bases):
        self.name, self.src, self.line, self.bases = name, src, line, bases
        self.members = []          # in order; nested anonymous aggregates flattened
        self.reasons = set()       # why it is pointer-bearing
        self.klass = "plain"


STRUCT_RE = re.compile(r"\b(struct|class|union)\s+((?:alignas\s*\([^()]*\)\s*|__declspec\s*\([^()]*\)\s*)*)"
                       r"([A-Za-z_]\w*)\s*(?:final\s*)?(?::\s*([^{};()]*?))?\s*\{")
FUNCPTR_RE = re.compile(r"\(\s*(?:__\w+\s+)?(?:[\w:]+::)?\*\s*(?:const\s+)?([A-Za-z_]\w*)\s*((?:\[[^\]]*\])*)\s*\)\s*\(")


def parse_members(src, body, body_start, typedefs):
    """The data members of an aggregate body, in order."""
    members = []
    i, n, stmt, stmt_start = 0, len(body), "", 0
    while i < n:
        c = body[i]
        if c == "{":
            end = match_brace(body, i)
            head = stmt.strip()
            if re.search(r"\b(struct|union|class)\b[^;]*$", head) and not re.search(r"\)\s*$", head):
                inner = body[i + 1:end]
                nm = re.search(r"\b(?:struct|union|class)\s+(?:alignas\s*\([^()]*\)\s*)?([A-Za-z_]\w*)?", head)
                if nm and nm.group(1):
                    stmt = nm.group(1) + " "        # the declarators that follow are of this type
                else:
                    members += parse_members(src, inner, body_start + i + 1, typedefs)
                    stmt = "__anon__ "
                i = end + 1
                continue
            if re.search(r"\benum\b", head):
                stmt = "int "
                i = end + 1
                continue
            if "=" in head and "operator" not in head:
                i = end + 1              # a default member initialiser
                continue
            if re.search(r"[A-Za-z_]\w*\s*(\[[^\]]*\])*$", head) and "(" not in head:
                i = end + 1              # brace initialiser
                continue
            stmt, i = "", end + 1        # a function body
            continue
        if c == ";":
            members += parse_statement(src, stmt, src.line_of(body_start + stmt_start), typedefs)
            stmt, i = "", i + 1
            stmt_start = i
            continue
        if not stmt.strip():
            stmt_start = i
        stmt += c
        i += 1
    return members


def parse_statement(src, s, line, typedefs):
    s = re.sub(r"\b(public|private|protected)\s*:", " ", s)
    s = re.sub(r"\balignas\s*\([^()]*\)|__declspec\s*\((?:[^()]|\([^()]*\))*\)", " ", s).strip()
    if s.startswith("__anon__"):
        return []
    if not s or re.match(r"(typedef|using|friend|static_assert|template|enum|static|constexpr|inline|virtual|"
                         r"explicit|operator|~|return|namespace)\b", s):
        return []
    fp = FUNCPTR_RE.search(s)
    if fp:
        return [Member(fp.group(1), "funcptr", "", line)]
    if "(" in s:
        return []                    # a method
    s = split_top(s, "=")[0]
    parts = split_top(s, ",")
    first = remove_templates(parts[0]).strip()
    m = re.match(r"^(.*?)([A-Za-z_]\w*)\s*((?:\[[^\]]*\])*)\s*(?::\s*\w+)?\s*$", first, re.S)
    if not m or not m.group(1).strip():
        return []
    prefix = m.group(1)
    words = [w for w in re.findall(r"[A-Za-z_]\w*", prefix) if w not in QUALIFIERS]
    if not words:
        words = ["int"]
    base = words[-1]
    if "long" in words and words.count("long") == 1 and "double" not in words:
        base = "long"
    out = []
    names = [(m.group(2), prefix)] + [(re.findall(r"[A-Za-z_]\w*", p)[-1] if re.findall(r"[A-Za-z_]\w*", p) else "?",
                                       prefix.replace("*", "").replace("&", "") + p) for p in parts[1:]]
    for name, decl in names:
        pointer = "*" in decl or "&" in decl
        out.append(Member(name, "pointer" if pointer else "value", base, line))
    return out


def parse_structs(sources):
    typedefs = {}
    pointer_typedefs = set(POINTER_TYPES)
    size_typedefs = set(SIZE_VARIANT)
    for src in sources:
        code = src.code
        for m in re.finditer(r"\btypedef\s+[^;{}]*?\(\s*(?:__\w+\s+)?(?:[\w:]+::)?\*\s*([A-Za-z_]\w*)\s*\)\s*\(", code):
            pointer_typedefs.add(m.group(1))
        for m in re.finditer(r"\busing\s+([A-Za-z_]\w*)\s*=\s*[^;]*\(\s*(?:__\w+\s*)?(?:[\w:]+::)?\*\s*\)", code):
            pointer_typedefs.add(m.group(1))
        for m in re.finditer(r"\btypedef\s+([^;{}()]*?)\s*(\*?)\s*([A-Za-z_]\w*)\s*;", code):
            target, star, name = m.group(1), m.group(2), m.group(3)
            if star or "*" in target:
                pointer_typedefs.add(name)
            else:
                typedefs[name] = re.findall(r"[A-Za-z_]\w*", remove_templates(target))
        for m in re.finditer(r"\busing\s+([A-Za-z_]\w*)\s*=\s*([^;()]*);", code):
            if "*" in m.group(2):
                pointer_typedefs.add(m.group(1))
            else:
                typedefs[m.group(1)] = re.findall(r"[A-Za-z_]\w*", remove_templates(m.group(2)))
    # typedefs of the size-variant integers (DWORD on LP64 is the Win32 header's concern, not ours)
    changed = True
    while changed:
        changed = False
        for name, words in typedefs.items():
            words = [w for w in words if w not in QUALIFIERS]
            if not words:
                continue
            if words[-1] in size_typedefs and name not in size_typedefs:
                size_typedefs.add(name)
                changed = True
            if words[-1] in pointer_typedefs and name not in pointer_typedefs:
                pointer_typedefs.add(name)
                changed = True
    structs = []
    for src in sources:
        code = src.code
        for m in STRUCT_RE.finditer(code):
            if re.search(r"\b(enum)\s*$", code[max(0, m.start() - 6):m.start()]):
                continue
            open_at = m.end() - 1
            end = match_brace(code, open_at)
            bases = []
            if m.group(4):
                for b in split_top(m.group(4), ","):
                    w = re.findall(r"[A-Za-z_]\w*", remove_templates(b))
                    w = [x for x in w if x not in ("public", "private", "protected", "virtual")]
                    if w:
                        bases.append(w[-1])
            s = Struct(m.group(3), src, src.line_of(m.start()), bases)
            s.members = parse_members(src, code[open_at + 1:end], open_at + 1, typedefs)
            structs.append(s)
    by_name = defaultdict(list)
    for s in structs:
        by_name[s.name].append(s)
    for s in structs:
        for mem in s.members:
            if mem.kind == "value":
                if mem.base in pointer_typedefs:
                    mem.kind = "handle"
                elif mem.base == "long":
                    mem.kind = "long"
                elif mem.base in size_typedefs:
                    mem.kind = "sizevar"
            if re.search(r"vtable|vtbl|vptr", mem.name, re.I) and mem.kind in ("pointer", "value"):
                mem.kind = "vtable" if mem.kind == "pointer" else "vtable32"
    # pointer-bearing, to a fixed point: own members, embedded members, bases
    for s in structs:
        for mem in s.members:
            if mem.kind in ("pointer", "funcptr", "handle", "sizevar", "vtable"):
                s.reasons.add(mem.kind)
            if mem.kind == "long":
                s.reasons.add("long")
    changed = True
    while changed:
        changed = False
        for s in structs:
            before = len(s.reasons)
            for mem in s.members:
                if mem.kind == "value" and mem.base not in NO_POINTER_BASES:
                    t = resolve(by_name, mem.base, s.src)
                    if t is not None and t is not s and t.reasons - {"long"}:
                        s.reasons.add("embedded")
                        mem.kind = "embedded"
            for b in s.bases:
                t = resolve(by_name, b, s.src)
                if t is not None and t.reasons - {"long"}:
                    s.reasons.add("base")
            if len(s.reasons) != before:
                changed = True
    return structs, by_name


def resolve(by_name, name, src):
    """The structure a name means in src: one defined in the same file, else the same directory, else any."""
    cands = by_name.get(name, [])
    if len(cands) <= 1:
        return cands[0] if cands else None
    for c in cands:
        if c.src is src:
            return c
    d = os.path.dirname(src.rel)
    for c in cands:
        if os.path.dirname(c.src.rel) == d:
            return c
    return cands[0]


def bearing(s):
    return bool(s.reasons - {"long"})


def classify_structs(structs, by_name):
    roots = {}
    for loader, what, names in LOADERS:
        for nm in names:
            roots.setdefault(nm, loader)
    file_structs = set()
    for s in structs:
        if s.name in roots:
            file_structs.add(id(s))
            s.loader = roots[s.name]
    changed = True
    while changed:                    # what a file structure embeds is laid out in the file too
        changed = False
        for s in structs:
            if id(s) not in file_structs:
                continue
            for mem in s.members:
                if mem.kind in ("value", "embedded"):
                    for t in by_name.get(mem.base, []):
                        if id(t) not in file_structs:
                            file_structs.add(id(t))
                            t.loader = s.loader
                            changed = True
    for s in structs:
        if id(s) in file_structs:
            s.klass = "file" if bearing(s) else "file.plain"
        elif bearing(s):
            s.klass = "candidate" if FILE_HINT.search(s.src.comment_near(s.line, 2)) else "memory"
        else:
            s.klass = "plain"


