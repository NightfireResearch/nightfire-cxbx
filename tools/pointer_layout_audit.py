def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--md", action="store_true")
    ap.add_argument("--list")
    ap.add_argument("--file")
    ap.add_argument("--struct")
    ap.add_argument("--clang-log")
    ap.add_argument("--harness", action="store_true")
    ap.add_argument("--probe-script", action="store_true")
    ap.add_argument("--sources", action="store_true", help="print the standalone source list")
    args = ap.parse_args()
    if args.probe_script:
        sys.stdout.write(PROBE)
        return
    cpp = standalone_sources() + (HARNESS if args.harness else [])
    if args.sources:
        print("\n".join(cpp))
        return
    files = [f for f in cpp + header_files() if os.path.exists(os.path.join(ROOT, f))]
    files = list(dict.fromkeys(files))
    sources = [Source(f) for f in files]
    structs, by_name = parse_structs(sources)
    classify_structs(structs, by_name)
    checks = layout_checks(sources, by_name)
    code = scan_code(sources)
    asm = scan_asm([s for s in sources if s.rel in cpp or s.rel.endswith((".h", ".hpp", ".inc"))])
    callers = asm_callers(asm, sources)

    findings = []
    for s in structs:
        if s.klass in ("file", "memory", "candidate"):
            kinds = Counter(m.kind for m in s.members)
            desc = ", ".join(f"{k} {v}" for k, v in sorted(kinds.items()) if k not in ("value",))
            findings.append(("struct." + s.klass, s.src.rel, s.line, f"{s.name}: {desc or ''} "
                             f"[{', '.join(sorted(s.reasons))}]"))
        for m in s.members:
            if m.kind == "long":
                findings.append(("member.long", s.src.rel, m.line, f"{s.name}::{m.name}"))
    findings += checks + code
    for kind, rel, line, name, x87 in asm:
        findings.append((kind, rel, line, f"{name} {' '.join(x87)}  (named {callers[name.split('::')[-1]]}x)"))

    if args.struct:
        for s in by_name.get(args.struct, []):
            print(f"{s.name} ({s.src.rel}:{s.line}) {s.klass} bases={s.bases} reasons={sorted(s.reasons)}")
            for m in s.members:
                print(f"   {m.kind:9} {m.base:24} {m.name}")
        for f in findings:
            if f[0].startswith("assert") and re.search(r"\b" + re.escape(args.struct) + r"\b", f[3]):
                print(f"{f[0]:16} {f[1]}:{f[2]} {f[3]}")
        return
    if args.list or args.file:
        for f in sorted(findings, key=lambda f: (f[0], f[1], f[2])):
            if args.list and not f[0].startswith(args.list):
                continue
            if args.file and args.file not in f[1]:
                continue
            print(f"{f[0]:18} {f[1]}:{f[2]}  {f[3]}")
        return

    count = Counter(f[0] for f in findings)
    n_struct = len(structs)
    n_bearing = sum(1 for s in structs if bearing(s))
    member_kinds = Counter(m.kind for s in structs for m in s.members)
    asserts_total = sum(count[k] for k in ("assert.size", "assert.offset", "assert.unknown", "assert.stable"))
    x87_ops = Counter(o for kind, _, _, _, x87 in asm if kind == "asm.x87" for o in x87)
    x87_names = [(name, callers[name.split("::")[-1]]) for kind, _, _, name, _ in asm if kind == "asm.x87"]
    cc = Counter(f[3] for f in findings if f[0] == "callconv")

    def table(rows, head):
        if args.md:
            print("| " + " | ".join(head) + " |")
            print("|" + "|".join("---:" if i else "---" for i in range(len(head))) + "|")
            for r in rows:
                print("| " + " | ".join(str(x) for x in r) + " |")
        else:
            for r in rows:
                print("  " + "  ".join(f"{str(x):<40}" if i == 0 else f"{str(x):>8}" for i, x in enumerate(r)))
        print()

    print(f"{len(sources)} files ({len(cpp)} sources{' with the harness' if args.harness else ''}), "
          f"{n_struct} structures, {n_bearing} with pointer-sized members\n")
    table([("structures in memory only (grow on 64-bit)", count["struct.memory"]),
           ("structures read in place from files (LOADERS)", count["struct.file"]),
           ("candidates: records, files, packets by their comment", count["struct.candidate"]),
           ("members: pointers", member_kinds["pointer"]),
           ("members: function pointers", member_kinds["funcptr"]),
           ("members: vtable pointers", member_kinds["vtable"]),
           ("members: vtables held as 32-bit integers", member_kinds["vtable32"]),
           ("members: handles (HANDLE, pointer typedefs)", member_kinds["handle"]),
           ("members: size_t/uintptr_t and kin", member_kinds["sizevar"]),
           ("members: embedded pointer-bearing structures", member_kinds["embedded"]),
           ("members: long (8 bytes on LP64 only)", count["member.long"]),
           ("pointer-sized members of the structures read from files",
            sum(1 for s in structs if s.klass == "file" for m in s.members
                if m.kind in ("pointer", "funcptr", "handle", "vtable", "sizevar")))], ("Structures", "Count"))
    table([("static_asserts on sizes and offsets", asserts_total),
           ("stay true (no pointer-sized member involved)", count["assert.stable"]),
           ("fail: size of a pointer-bearing structure", count["assert.size"]),
           ("fail: offset after a pointer-sized member", count["assert.offset"]),
           ("  of those failing, on structures read from files", len(FILE_CHECKS)),
           ("unknown to the parser", count["assert.unknown"])], ("Layout checks", "Count"))
    by_file = Counter(f[1] for f in findings if f[0] in ("assert.size", "assert.offset"))
    table(by_file.most_common(12), ("Failing checks by file", "Count"))
    table([(k, count[k]) for k in ("cast.ptr_to_u32", "cast.u32_to_ptr", "cast.int_ptr", "mask.addr32", "word.stream",
                                   "alloc.literal", "alloc.ptr4", "print.ptr")], ("Integer/pointer", "Count"))
    table([("naked functions with x87 arithmetic", count["asm.x87"]),
           ("register-argument adaptors (injection only)", count["asm.adaptor"]),
           ("inside #ifndef NIGHTFIRE_STANDALONE", count["asm.injected"]),
           ("other naked functions", count["asm.other"])], ("Assembly", "Count"))
    table(sorted(x87_ops.items(), key=lambda kv: (-kv[1], kv[0])), ("x87 instruction (functions using it)", "Count"))
    table(sorted(x87_names, key=lambda kv: -kv[1]), ("x87 function", "Uses of its name"))
    table(sorted(cc.items(), key=lambda kv: -kv[1]), ("Calling convention", "Uses"))

    if args.clang_log:
        seen = read_clang_logs(args.clang_log)
        cats = Counter(k[0] for k in seen)
        table(cats.most_common(), ("64-bit syntax check (distinct lines)", "Count"))
        starts = defaultdict(list)
        for (rel, first), last in SPANS.items():
            starts[rel].append((first, last))
        def to_start(rel, line):           # clang reports the failing operand's line
            for first, last in starts.get(rel, []):
                if first <= line <= last:
                    return (rel, first)
            return (rel, line)
        clang_asserts = {to_start(k[1], k[2]) for k in seen if k[0] == "static_assert"}
        ours = {(f[1], f[2]) for f in findings if f[0] in ("assert.size", "assert.offset")}
        unknown = {(f[1], f[2]) for f in findings if f[0] == "assert.unknown"}
        stable = {(f[1], f[2]) for f in findings if f[0] == "assert.stable"}
        table([("failing in both", len(clang_asserts & ours)),
               ("this tool only", len(ours - clang_asserts)),
               ("clang only, tool said unknown", len(clang_asserts & unknown)),
               ("clang only, tool said stable", len(clang_asserts & stable)),
               ("clang only, not seen by the tool", len(clang_asserts - ours - unknown - stable))],
              ("Failed layout checks: tool vs clang", "Lines"))
        if not args.md:
            for p in sorted(clang_asserts & stable)[:20]:
                print("  clang fails, tool said stable:", f"{p[0]}:{p[1]}")
            for p in sorted(ours - clang_asserts)[:20]:
                print("  tool says fails, clang passes:", f"{p[0]}:{p[1]}")


if __name__ == "__main__":
    main()
