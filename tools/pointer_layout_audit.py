# Layout checks

def balanced(code, i):
    """The text inside the parentheses that open at code[i]."""
    j = match_brace(code, i, "(", ")")
    return code[i + 1:j]


def find_struct(by_name, name, src):
    return resolve(by_name, name, src)


def preceding_pointer(s, field, by_name, seen=None):
    """Whether a pointer-sized member (or a pointer-bearing base) lies before `field` in s: True, False or None."""
    seen = seen or set()
    if id(s) in seen:
        return None
    seen.add(id(s))
    for b in s.bases:
        t = resolve(by_name, b, s.src)
        if t is not None and bearing(t):
            return True
    found_ptr = False
    for mem in s.members:
        if mem.name == field:
            if not found_ptr and mem.kind in ("pointer", "funcptr", "handle", "sizevar", "vtable", "embedded"):
                # a pointer the comment places at 4 mod 8 moves to the next 8 on 64-bit
                at = re.search(r"\+\s*(0x[0-9a-fA-F]+)\b", s.src.comments.get(mem.line, ""))
                return bool(at) and int(at.group(1), 16) % 8 == 4
            return found_ptr
        if mem.kind in ("pointer", "funcptr", "handle", "sizevar", "vtable", "embedded"):
            found_ptr = True
    for b in s.bases:                  # an inherited member
        t = resolve(by_name, b, s.src)
        if t is not None:
            r = preceding_pointer(t, field, by_name, seen)
            if r is not None:
                return r
    return None


SPANS = {}                             # a check's first line -> its last
FILE_CHECKS = set()                    # failing checks on a structure read from a file: these must hold on 64-bit


def layout_checks(sources, by_name):
    findings = []
    for src in sources:
        code = src.code
        for m in re.finditer(r"\bstatic_assert\s*\(", code):
            inner = balanced(code, m.end() - 1)
            line = src.line_of(m.start())
            kinds = []
            file_layout = False
            for sm in re.finditer(r"\bsizeof\s*\(", inner):
                arg = balanced(inner, sm.end() - 1).strip()
                if "*" in arg and re.fullmatch(r"[\w:\s<>,]*\*\s*", arg):
                    kinds.append(("assert.size", "pointer"))
                    continue
                words = re.findall(r"[A-Za-z_]\w*", remove_templates(arg))
                words = [w for w in words if w not in QUALIFIERS]
                if not words or not re.fullmatch(r"[\w:\s<>,\[\]]+", arg):
                    kinds.append(("assert.unknown", arg))
                    continue
                name = words[-1]
                if name in NO_POINTER_BASES or name in ("float", "double"):
                    continue
                if name in SIZE_VARIANT or name in POINTER_TYPES:
                    kinds.append(("assert.size", name))
                    continue
                s = find_struct(by_name, name, src)
                if s is None:
                    kinds.append(("assert.unknown", name))
                elif bearing(s):
                    kinds.append(("assert.size", name))
                    file_layout = file_layout or s.klass == "file"
            for om in re.finditer(r"\boffsetof\s*\(", inner):
                arg = balanced(inner, om.end() - 1)
                parts = split_top(arg, ",")
                if len(parts) < 2:
                    continue
                words = re.findall(r"[A-Za-z_]\w*", remove_templates(parts[0]))
                field = re.findall(r"[A-Za-z_]\w*", parts[1])
                s = find_struct(by_name, words[-1], src) if words else None
                if s is None or not field:
                    kinds.append(("assert.unknown", parts[0].strip()))
                    continue
                r = preceding_pointer(s, field[0], by_name)
                if r is None:
                    if bearing(s):
                        kinds.append(("assert.unknown", s.name + "::" + field[0]))
                elif r:
                    kinds.append(("assert.offset", s.name + "::" + field[0]))
                    file_layout = file_layout or s.klass == "file"
            SPANS[(src.rel, line)] = src.line_of(m.end() + len(inner))
            outside = re.sub(r"\b(sizeof|offsetof)\s*\((?:[^()]|\([^()]*\))*\)", " ", inner)
            fixed = {"pointer"} | SIZE_VARIANT | POINTER_TYPES
            if kinds and not any(k[1] in fixed for k in kinds) and len(re.findall(r"\bsizeof\s*\(", inner)) >= 2 and \
                    not re.search(r"\b(0x[0-9a-fA-F]+|\d+)\b", outside):
                kinds = []                      # sizes compared with each other: both change alike
            if kinds:
                order = ["assert.size", "assert.offset", "assert.unknown"]
                kinds.sort(key=lambda k: order.index(k[0]))
                findings.append((kinds[0][0], src.rel, line, ", ".join(sorted(set(k[1] for k in kinds)))))
                if file_layout and kinds[0][0] != "assert.unknown":
                    FILE_CHECKS.add((src.rel, line))
            elif re.search(r"\b(sizeof|offsetof)\s*\(", inner):
                findings.append(("assert.stable", src.rel, line, ""))
    return findings


