# Integer/pointer conversions, assembly, calling conventions

CAST_PATTERNS = [
    ("cast.ptr_to_u32", re.compile(
        r"\(\s*(?:u?int(?:32_t)?|unsigned(?:\s+int)?|DWORD|uint|int32_t)\s*\)\s*\(\s*uintptr_t\s*\)|"
        r"\b(?:u?int(?:32_t)?|unsigned|DWORD|int32_t)\s*\(\s*(?:uintptr_t\s*\(|reinterpret_cast\s*<\s*uintptr_t\s*>)|"
        r"static_cast\s*<\s*(?:u?int(?:32_t)?|unsigned|DWORD|int32_t|uint8_t|uint16_t)\s*>\s*\(\s*"
        r"(?:reinterpret_cast\s*<\s*uintptr_t\s*>|uintptr_t\s*\()")),
    ("cast.u32_to_ptr", re.compile(
        r"reinterpret_cast\s*<\s*[^<>]*\*\s*>\s*\(\s*(?:uintptr_t\s*\(|\(\s*uintptr_t\s*\))|"
        r"\(\s*(?:const\s+)?[A-Za-z_][\w:]*\s*\*+\s*\)\s*\(\s*uintptr_t\s*\)")),
    ("cast.int_ptr", re.compile(
        r"reinterpret_cast\s*<\s*(?:u?int(?:32_t)?|unsigned|DWORD|int32_t|long)\s*>|"
        r"\(\s*(?:uint32_t|int32_t|DWORD)\s*\)\s*(?:&\s*\w|\w+\s*->\s*\w+\s*\))")),
    ("mask.addr32", re.compile(
        r"uintptr_t[^;]*&\s*0x[fF][0-9a-fA-F]{7}\b|uintptr_t[^;]*&\s*~\s*(?:0x[0-9a-fA-F]+|\d+)[uU]\b")),
    ("word.stream", re.compile(
        r"\(\s*(?:const\s+)?[A-Za-z_][\w:]*\s*\*+\s*\)\s*(?:\*\s*\w+\s*\+\+|\w+\s*\[[^\]]+\])(?!\s*\.)")),
]
ALLOC_PTR4 = re.compile(r"\(\s*(?:const\s+)?[A-Za-z_][\w:]*\s*\*\s*\*\s*\)\s*[\w:]*(?:alloc|Alloc|malloc|Malloc)\w*"
                        r"\s*\(([^;]*)")
PRINT_PTR = re.compile(r"%(?:0?8)?[lI]*[xX][^\"]*\"[^;]*?\((?:uint32_t|unsigned|DWORD|int)\)\s*\(?\s*(?:uintptr_t|void\s*\*)|"
                       r"%(?:0?8)?[xX][^\"]*\"[^;]*?(?:uint32_t|unsigned)\(\s*uintptr_t")
ALLOC_LITERAL = re.compile(r"\b[A-Za-z_]\w*(?:Alloc|alloc|Malloc|malloc)\w*\s*\(\s*(0x[0-9a-fA-F]+|[0-9]{2,})\s*[,)]")
CALLCONV = re.compile(r"\b(__thiscall|__stdcall|__fastcall|WINAPI|NTAPI|CALLBACK|APIENTRY)\b")
X87_OPS = re.compile(r"^\s*(f[a-z0-9]+)\b", re.M)
TRANSCENDENTAL = {"fsin", "fcos", "fsincos", "fptan", "fpatan", "fyl2x", "fyl2xp1", "f2xm1", "fscale", "fprem",
                  "fprem1", "frndint"}


def scan_code(sources):
    findings = []
    for src in sources:
        code = src.code
        for kind, rx in CAST_PATTERNS:
            for m in rx.finditer(code):
                line = src.line_of(m.start())
                if line in src.injected:
                    continue
                findings.append((kind, src.rel, line, src.text.split("\n")[line - 1].strip()[:120]))
        for m in ALLOC_PTR4.finditer(code):
            args = m.group(1)
            if re.search(r"<<\s*2\b|\*\s*4\b|\b4\s*\*|^\s*(0x[0-9a-fA-F]+|\d+)\s*[,)]", args):
                line = src.line_of(m.start())
                findings.append(("alloc.ptr4", src.rel, line, src.text.split("\n")[line - 1].strip()[:120]))
        for m in ALLOC_LITERAL.finditer(code):
            line = src.line_of(m.start())
            if line not in src.injected:
                findings.append(("alloc.literal", src.rel, line, src.text.split("\n")[line - 1].strip()[:120]))
        # printf formats are in strings, which strip() blanked: read the raw lines
        for k, raw in enumerate(src.text.split("\n"), 1):
            if PRINT_PTR.search(raw) and k not in src.injected:
                findings.append(("print.ptr", src.rel, k, raw.strip()[:120]))
        for m in CALLCONV.finditer(code):
            line = src.line_of(m.start())
            findings.append(("callconv", src.rel, line, m.group(1)))
    return findings


def scan_asm(sources):
    """Every naked function: name, class, x87 instructions, and how often its name is used elsewhere."""
    items = []
    for src in sources:
        lines = src.text.split("\n")
        for k, l in enumerate(lines):
            m = re.search(r"__declspec\(naked\)\s+[^(]*?\b(\w+(?:::\w+)*)\s*\(", l)
            if not m:
                continue
            body, depth, started, j = [], 0, False, k
            while j < len(lines):
                body.append(re.sub(r"//.*", "", lines[j]))
                depth += lines[j].count("{") - lines[j].count("}")
                started = started or "{" in lines[j]
                if started and depth <= 0:
                    break
                j += 1
            ops = X87_OPS.findall("\n".join(body[1:]))
            x87 = sorted(set(o for o in ops if o not in ("float",)))
            tag = lines[k - 1].strip() if k > 0 else ""
            name = m.group(1)
            if (k + 1) in src.injected:
                kind = "asm.injected"
            elif x87:
                kind = "asm.x87"
            elif "AUTOLTCG" in tag or re.search(r"Regs?[AB]?$|Eax$|EsiEdi$|^FUN_|RegisterArgs$", name):
                kind = "asm.adaptor"
            else:
                kind = "asm.other"
            items.append((kind, src.rel, k + 1, name, x87))
    return items


def asm_callers(items, sources):
    """References to each naked function's name outside its own definition and declarations."""
    counts = Counter()
    names = {i[3].split("::")[-1] for i in items}
    rx = re.compile(r"\b(" + "|".join(sorted(map(re.escape, names), key=len, reverse=True)) + r")\s*\(")
    for src in sources:
        for m in rx.finditer(src.code):
            line_text = src.code[src.line_starts[src.line_of(m.start()) - 1]:].split("\n")[0]
            if "__declspec(naked)" in line_text or re.match(r"\s*(?:[\w:<>*&]+\s+)+[\w:]+\s*\([^)]*\)\s*;", line_text):
                continue
            counts[m.group(1)] += 1
    return counts


