def strip(text):
    """Comments, strings and preprocessor lines blanked (newlines kept); the comments by line."""
    out = []
    comments = defaultdict(str)
    i, n, line = 0, len(text), 1
    while i < n:
        c = text[i]
        if c == "\n":
            line += 1
            out.append(c)
            i += 1
        elif text.startswith("//", i):
            j = text.find("\n", i)
            j = n if j < 0 else j
            comments[line] += " " + text[i + 2:j]
            out.append(" " * (j - i))
            i = j
        elif text.startswith("/*", i):
            j = text.find("*/", i + 2)
            j = n if j < 0 else j + 2
            chunk = text[i:j]
            for k, part in enumerate(chunk.split("\n")):
                comments[line + k] += " " + part
            out.append(re.sub(r"[^\n]", " ", chunk))
            line += chunk.count("\n")
            i = j
        elif c in "\"'":
            j = i + 1
            while j < n and text[j] != c and text[j] != "\n":
                j += 2 if text[j] == "\\" else 1
            out.append(c + " " * (j - i - 1) + (c if j < n and text[j] == c else ""))
            i = j + 1 if j < n and text[j] == c else j
        else:
            out.append(c)
            i += 1
    code = "".join(out)
    # preprocessor lines (with continuations) blanked
    lines = code.split("\n")
    cont = False
    for k, l in enumerate(lines):
        if cont or l.lstrip().startswith("#"):
            cont = l.rstrip().endswith("\\")
            lines[k] = " " * len(l)
        else:
            cont = False
    return "\n".join(lines), comments


def match_brace(code, i, open_ch="{", close_ch="}"):
    depth = 0
    for j in range(i, len(code)):
        if code[j] == open_ch:
            depth += 1
        elif code[j] == close_ch:
            depth -= 1
            if depth == 0:
                return j
    return len(code) - 1


def remove_templates(s):
    prev = None
    while prev != s:
        prev = s
        s = re.sub(r"<[^<>]*>", "", s)
    return s


def split_top(s, sep):
    parts, depth, cur = [], 0, ""
    for c in s:
        if c in "<([{":
            depth += 1
        elif c in ">)]}":
            depth -= 1
        if c == sep and depth == 0:
            parts.append(cur)
            cur = ""
        else:
            cur += c
    parts.append(cur)
    return parts


def overlay_fields():
    """The generated overlay classes' fields (XBE_FIELDS_<name> in src/driving/autogenerated_layouts.h), when a build
    has written them: an overlay class's members are that macro's expansion."""
    path = os.path.join(ROOT, "src/driving/autogenerated_layouts.h")
    if not os.path.exists(path):
        return {}
    text = open(path, encoding="utf-8").read()
    return {m.group(1): m.group(2).replace("\\\n", " ")
            for m in re.finditer(r"#define XBE_FIELDS_(\w+) \\\n((?:.*\\\n)*.*)", text)}


OVERLAYS = overlay_fields()


class Source:
    def __init__(self, rel):
        self.rel = rel
        self.text = open(os.path.join(ROOT, rel), encoding="utf-8", errors="replace").read()
        self.code, self.comments = strip(self.text)
        # XBE_FIELDS(Name) expanded on its own line; XBE_CLASS_SIZE and XBE_FIELD read as the checks they are
        self.code = re.sub(r"\bXBE_FIELDS\s*\(\s*(\w+)\s*\)",
                           lambda m: " ".join(OVERLAYS.get(m.group(1), "").split()), self.code)
        self.code = re.sub(r"\bXBE_CLASS_SIZE\s*\(\s*([\w:]+)\s*,", r"static_assert(sizeof(\1) ==", self.code)
        self.code = re.sub(r"\bXBE_FIELD\s*\(\s*([\w:]+)\s*,\s*([\w.\[\]]+)\s*,",
                           r"static_assert(offsetof(\1, \2) ==", self.code)
        self.line_starts = [0]
        for m in re.finditer("\n", self.code):
            self.line_starts.append(m.end())
        self.injected = self.injected_lines()

    def line_of(self, pos):
        lo, hi = 0, len(self.line_starts)
        while lo + 1 < hi:
            mid = (lo + hi) // 2
            if self.line_starts[mid] <= pos:
                lo = mid
            else:
                hi = mid
        return lo + 1

    def comment_near(self, line, before=3):
        return " ".join(self.comments.get(k, "") for k in range(max(1, line - before), line + 1))

    def injected_lines(self):
        """Lines the standalone build leaves out (#ifndef NIGHTFIRE_STANDALONE, or #ifdef's #else)."""
        out, stack = set(), []
        for k, l in enumerate(self.text.split("\n"), 1):
            s = l.strip()
            if s.startswith("#if"):
                stack.append("inj" if re.match(r"#ifndef\s+NIGHTFIRE_STANDALONE\b", s) else
                             "sa" if re.match(r"#ifdef\s+NIGHTFIRE_STANDALONE\b", s) else "x")
            elif s.startswith("#el") and stack:
                stack[-1] = {"inj": "sa", "sa": "inj"}.get(stack[-1], "x")
            elif s.startswith("#endif") and stack:
                stack.pop()
            if "inj" in stack:
                out.add(k)
        return out


