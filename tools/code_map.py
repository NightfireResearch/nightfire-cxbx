#!/usr/bin/env python3
"""Which bytes of Driving.xbe are instructions: tools/code_ranges_driving.txt, for NIGHTFIRE_TRAP_ORIGINAL
(src/driving/devtools/StandaloneTraps.cpp), which fills them with int3 so that running any of the original code
faults at once. Data kept inside the code sections - D3D's state, XAPI's device tables, the jump tables - is left
out, so filling the instructions breaks nothing our code still reads.

    python tools/code_map.py          write tools/code_ranges_driving.txt (committed: CI has no disc, and the
                                      build's Python may lack capstone)

From every function in tools/functions_driving.json, and every address the injection table patches (some are
functions Ghidra does not have), the walk follows the function's own control flow, as tools/abi_facts.py does:
straight on, both ways at a conditional jump, into a jump table's targets, past a call, and it stops at a RET, a jump
out of the function (a tail call) or an int3. Each instruction reached is a range; ranges are merged.
tools/extract_driving_data.py turns the file into the table the injection DLL is built with. Code no entry reaches
(an original Ghidra never made a function, that nothing patches) is not in it, so not trapped.
"""
import json
import os
import re
import sys

try:
    import capstone
    from capstone import x86
except ImportError:
    sys.exit("capstone is needed: python -m pip install capstone")

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from abi_facts import Image, jump_table_targets   # noqa: E402

OUT = os.path.join(HERE, "code_ranges_driving.txt")
CODE_SECTIONS = {".text", "D3DX", "D3D", "XGRPH", "DSOUND", "XPP"}


def main():
    image = Image(os.path.join(ROOT, "disc", "Driving.xbe"))
    symbols = json.load(open(os.path.join(HERE, "functions_driving.json"), encoding="utf-8"))
    entries = {int(s["address"], 16) for s in symbols}
    # Functions Ghidra does not have but a FUNC_AT replaces (their bodies after the jump), from the injection table
    injections = os.path.join(ROOT, "src", "driving", "autogenerated_injections.inc")
    if os.path.exists(injections):
        entries |= {int(a, 16) for a in re.findall(r"WriteJmpTo\((0x[0-9a-f]+)", open(injections).read())}
    starts = sorted(entries)
    bounds = {a: (starts[i + 1] if i + 1 < len(starts) else a + 0x10000) for i, a in enumerate(starts)}
    ranges = []
    for start in starts:
        end = bounds[start]
        work, seen = [start], set()
        while work:
            address = work.pop()
            while start <= address < end and address not in seen:
                seen.add(address)
                insn = image.insn(address)
                if insn is None:
                    break
                ranges.append((address, address + insn.size))
                ops = insn.operands
                if insn.mnemonic in ("ret", "int3", "hlt", "ud2", "retf", "iret", "iretd"):
                    break
                if insn.mnemonic == "jmp":
                    if ops and ops[0].type == x86.X86_OP_IMM:
                        work.append(ops[0].imm)
                    else:
                        work.extend(jump_table_targets(image, insn, start, end) or [])
                    break
                if insn.group(x86.X86_GRP_JUMP) and ops and ops[0].type == x86.X86_OP_IMM:
                    work.append(ops[0].imm)
                address += insn.size
    ranges.sort()
    merged = []
    for lo, hi in ranges:
        if merged and lo <= merged[-1][1]:
            merged[-1][1] = max(merged[-1][1], hi)
        else:
            merged.append([lo, hi])
    with open(OUT, "w", newline="\n") as f:
        f.write("# Instruction bytes of Driving.xbe reached from its functions' entries (tools/code_map.py): start end\n")
        for lo, hi in merged:
            f.write("%08x %08x\n" % (lo, hi))
    print("%d ranges, %d bytes of instructions -> %s" % (len(merged), sum(h - l for l, h in merged),
                                                         os.path.relpath(OUT, ROOT)))


if __name__ == "__main__":
    main()
