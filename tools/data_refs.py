"""Finds every instruction in an XBE that refers to a block of data, for moving that data into our source.

A table the game's code uses in place can be moved into our source only if the original code that can still run -
an original a shadow test runs, the all-original runs, a table of the game's pointing at it - uses ours too:
otherwise the game reads or writes its own copy while our code uses ours, and a pointer one of them stores into
the table differs from the other's. So the injector points every reference at our definition instead
(XbeRelocate, src/common/xbeRelocate.h); this script finds the references, once, from the binary.

  python tools/data_refs.py action      # writes tools/data_refs_action.json

The blocks are the globals tagged `relocate` in our source: `// XBE_GLOBAL(0x0016199c, 0x4) readonly relocate` on
the line before the definition (tools/global_coverage.py). The json maps each one's name to its sites.

Method: every dword in the code sections whose value falls inside a block is a candidate; each is kept only if
decoding the containing function (from its entry, in functions_<side>.json) finds an instruction with that dword
as its displacement or immediate at exactly that place. Candidates that do not decode are listed, never
patched: a stray match in data or inside another instruction must not be rewritten. References from data (a
table of the game's holding a pointer into the block) and through a base folded outside it are not found.
"""
import bisect
import json
import os
import re
import struct
import sys

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
XBE = {'action': 'default.xbe', 'driving': 'Driving.xbe'}


TAG = re.compile(r"//\s*XBE_GLOBAL\(\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+|\d+)\s*\)(.*)")
DEFINITION = re.compile(r"(\w+)\s*(\[[^\]]*\])*\s*(=[^;]*)?[;{=]")


def owned(side):
    """[(name, address, size, path, relocate)] for every global of ours with an XBE_GLOBAL tag (a definition after
    the tag, not a #define), in file order; relocate is whether the tag says so."""
    out = []
    for root, dirs, files in sorted(os.walk(os.path.join(REPO, 'src', side))):
        dirs[:] = sorted(x for x in dirs if x != 'devtools')
        for file in sorted(files):
            if not file.endswith(('.c', '.cpp', '.h')):
                continue
            path = os.path.join(root, file)
            lines = open(path, encoding='utf-8', errors='replace').read().splitlines()
            for i, line in enumerate(lines):
                m = TAG.search(line)
                if not m:
                    continue
                following = next((l for l in lines[i + 1:] if l.strip()), '')
                code = following.split('//')[0]
                if not code.strip() or code.lstrip().startswith('#') or code.lstrip().startswith('extern'):
                    continue
                d = DEFINITION.search(code)
                relocate = 'relocate' in m.group(3).split()
                assert d or not relocate, '%s:%d: a relocate tag must be followed by a definition' % (path, i + 1)
                if d:
                    out.append((d.group(1), int(m.group(1), 16), int(m.group(2), 0), os.path.relpath(path, REPO),
                                relocate))
    return out


def relocated(side):
    """[(name, address, size, path)] for every global of ours tagged `relocate`, in file order."""
    return [(n, a, sz, p) for n, a, sz, p, r in owned(side) if r]


def port_names(side):
    """{the game's function address: the names of our port} from the injection table (tools/preprocess.py writes it),
    with the C core of a register adaptor (_Name) beside Name."""
    path = os.path.join(REPO, 'src', side, 'autogenerated_injections.inc')
    out = {}
    for m in re.finditer(r"^WriteJmpTo\((0x[0-9a-fA-F]+),.*//\s*(\w+)\s*$", open(path, encoding='utf-8').read(), re.M):
        out[int(m.group(1), 16)] = {m.group(2), '_' + m.group(2)}
    return out


def source_words(side):
    """{function name: the set of identifiers its body uses} for every function defined in our source, outside
    devtools; and {macro: the identifiers it expands to} for every object-like #define on one line, for the names a
    block goes by (`#define DirFileHash ((HASHCODE)DirFileHashValue)` goes by DirFileHashValue)."""
    bodies, aliases = {}, {}
    definition = re.compile(r"^[A-Za-z_](?:[\w \t\*&:<>,]|__declspec\(\w+\))*?\b(?!__declspec\b)(\w+)\s*"
                            r"\([^;{}]*\)\s*(?:const\s*)?\{", re.M)
    for root, dirs, files in os.walk(os.path.join(REPO, 'src', side)):
        dirs[:] = [x for x in dirs if x != 'devtools']
        for file in files:
            if not file.endswith(('.c', '.cpp', '.h')):
                continue
            text = open(os.path.join(root, file), encoding='utf-8', errors='replace').read()
            for m in re.finditer(r"^\s*#\s*define\s+(\w+)[ \t]+([^\n]*?)\s*(?://[^\n]*)?$", text, re.M):
                if not re.search(r"0x[0-9a-fA-F]{5,}", m.group(2)):   # not one of the game's addresses
                    aliases.setdefault(m.group(1), set()).update(re.findall(r"[A-Za-z_]\w*", m.group(2)))
            for m in definition.finditer(text):
                depth, i = 1, m.end()
                while depth and i < len(text):
                    depth += {'{': 1, '}': -1}.get(text[i], 0)
                    i += 1
                bodies.setdefault(m.group(1), set()).update(re.findall(r"\w+", text[m.end():i]))
    return bodies, aliases


def owned_blocks(side):
    """Every owned global with a name, sorted by address; a second tag naming one already listed is left out."""
    seen, out = set(), []
    for name, address, size, path, relocate in owned(side):
        if name in seen or not size:
            continue
        seen.add(name)
        out.append({'name': name, 'lo': address, 'hi': address + size, 'relocate': relocate})
    out.sort(key=lambda b: (b['lo'], -b['hi']))
    return out


def sections(d):
    base = struct.unpack_from('<I', d, 0x104)[0]
    count = struct.unpack_from('<I', d, 0x11c)[0]
    at = struct.unpack_from('<I', d, 0x120)[0] - base
    out = []
    for i in range(count):
        flags, va, vsize, raw, rawsize, name = struct.unpack_from('<6I', d, at + i * 56)
        out.append((d[name - base:d.index(b'\0', name - base)].decode(), flags, va, raw, rawsize))
    return out


def main():
    side = sys.argv[1] if len(sys.argv) > 1 else 'action'
    import capstone
    import capstone.x86
    d = open(os.path.join(REPO, 'disc', XBE[side]), 'rb').read()
    blocks = owned_blocks(side)
    # Ghidra's functions, and every entry the injection table patches: three drone controls a table points at were
    # never made functions (NDrone2_ControlDTYPE_Ninja's 0x0003f910), and decoding them from the function before would
    # miss their references
    ghidra_funcs = set(int(f['address'], 16) for f in json.load(open(os.path.join(REPO, 'tools', 'functions_%s.json' % side))))
    funcs = sorted(ghidra_funcs | set(port_names(side)))
    code = [s for s in sections(d) if s[0] == '.text']   # the game's code; the libraries never name its data
    # Ghidra's data references, (instruction, target): an operand is only rewritten where Ghidra agrees it is an
    # address, not a number that happens to fall inside the block
    xrefs = {}
    for t, f, fn, k in json.load(open(os.path.join(REPO, 'tools', 'xrefs_%s.json' % side))):
        if k in 'RWD':
            xrefs.setdefault(int(f, 16), []).append(int(t, 16))

    def read(va, n):
        for name, flags, sva, raw, size in sections(d):
            if sva <= va < sva + size:
                return d[raw + va - sva:raw + va - sva + n]
        return b''

    md = capstone.Cs(capstone.CS_ARCH_X86, capstone.CS_MODE_32)
    md.detail = True
    result, problems = {}, []
    # A register-indexed operand is the block's only if our port of the function it is in names the block (or a macro
    # for it): a base folded from another table can land inside it at any offset (Player_WeaponFiring's
    # DecryptorDigits[digit - '0'] is 0x001819f0, inside RadarIcons); so is an immediate, which can be the end of the
    # table before it (SFX's loop over 0x00298e7c.. stops at 0x00299338, MusicNowPlaying's start) or an address the
    # linker happened to put inside it (WeaponDataTableInit stores 0x001820a0, inside MapMusic, into weapon_data). A
    # plain [address] operand names the block itself, and a function with no port of its own (a chunk Ghidra split
    # off) has nothing to check against.
    ports = port_names(side)
    bodies, aliases = source_words(side)

    def goes_by(name):
        names = {name}
        while True:
            more = {a for a, b in aliases.items() if b & names} - names
            if not more:
                return names
            names |= more

    def port_names_it(fn, names):
        """Whether the port, or a function of ours it names (an adaptor's C core, a helper), names the block."""
        for p in ports.get(fn, ()):
            words = bodies.get(p, set())
            if names & words or any(names & bodies.get(w, set()) for w in words if w in bodies):
                return True
        return False

    def operand(site):
        """The instruction whose 4-byte displacement or immediate is at site, and its function's entry, or None."""
        i = bisect.bisect_right(funcs, site) - 1
        if i < 0:
            return None, None
        for insn in md.disasm(read(funcs[i], site - funcs[i] + 16), funcs[i]):
            if insn.address > site:
                break
            if insn.address + insn.size <= site:
                continue
            rel = site - insn.address
            if (insn.disp_size == 4 and insn.disp_offset == rel) or (insn.imm_size == 4 and insn.imm_offset == rel):
                return insn, funcs[i]
            break
        return None, None

    starts = [b['lo'] for b in blocks]
    ends = {}
    for b in blocks:
        ends.setdefault(b['hi'], []).append(b)
    for b in blocks:
        b['sites'], b['ends'], b['users'], b['names'] = [], [], set(), goes_by(b['name'])
    his = sorted(ends)
    for name, flags, sva, raw, size in code:
        blob = d[raw:raw + size]
        for off in range(len(blob) - 3):
            v = struct.unpack_from('<I', blob, off)[0]
            # A loop's bound: the block's end, or a little past it where the loop walks a field (MenuManager_Init's
            # manager[i].closeAction stops at 0x0025fcd4, the next element's field), when no block holds it
            j = bisect.bisect_right(his, v) - 1
            k = bisect.bisect_right(starts, v) - 1
            outside = k < 0 or v >= blocks[k]['hi']
            while j >= 0 and v - his[j] <= 0x200 and (v == his[j] or outside):
                for b in ends[his[j]]:
                    b['ends'].append(sva + off)
                j -= 1
            # Where two blocks overlap (a table that reads on into the next, as the game's does), an address belongs
            # to the one starting nearest below it
            i = bisect.bisect_right(starts, v) - 1
            # past the nearest one's end but inside a block that starts before it and holds it (BondMoments[0x65],
            # after WireAnim inside BondMoments)
            while i >= 0 and v >= blocks[i]['hi'] and i > 0 and blocks[i - 1]['hi'] > blocks[i]['lo']:
                i -= 1
            if i < 0 or v >= blocks[i]['hi']:
                continue
            b = blocks[i]
            site = sva + off
            insn, fn = operand(site)
            # A base folded for an index that starts at one lands just before the block it indexes (manager[i]'s
            # through 0x0025f1c9, inside save_space_text): the next block, when the port names it and not this one
            if insn is not None and fn in ports and i + 1 < len(blocks) and blocks[i + 1]['lo'] - v <= 0x200 \
                    and not port_names_it(fn, b['names']) and port_names_it(fn, blocks[i + 1]['names']) \
                    and any(op.type == capstone.x86.X86_OP_MEM and (op.mem.base or op.mem.index) for op in insn.operands):
                b = blocks[i + 1]
            lo, hi = b['lo'], b['hi']
            if insn is None:
                problems.append('%s: 0x%x (value 0x%x, in %s) does not decode as an operand - left alone' %
                                (b['name'], site, v, name))
            elif not any(min(lo, v) <= t < hi for t in xrefs.get(insn.address, [])) and not (
                    fn not in ghidra_funcs and not any(op.type == capstone.x86.X86_OP_MEM and (op.mem.base or op.mem.index)
                                                       for op in insn.operands) and insn.disp_size == 4):
                # (code Ghidra never made a function has no references from it; there a plain [address] operand,
                # decoded from the patched entry, is taken as it is)
                problems.append('%s: 0x%x (value 0x%x) has no reference from Ghidra into the block - left alone' %
                                (b['name'], site, v))
            elif (v - lo) % 2 and any(op.type == capstone.x86.X86_OP_MEM and (op.mem.base or op.mem.index)
                                      for op in insn.operands) and fn in ports and not port_names_it(fn, b['names']):
                # An odd offset through a register in a function whose port does not name the block: a base folded
                # from another table (Inflate's length tables index 0x0018cc5b + 257 + n). Where the port names the
                # block it is a byte field of an array of structures (manager[i]'s at +0x1d1).
                problems.append('%s: 0x%x (%s %s) indexes from inside the block at an odd offset - left alone' %
                                (b['name'], site, insn.mnemonic, insn.op_str))
            elif (any(op.type == capstone.x86.X86_OP_MEM and (op.mem.base or op.mem.index) for op in insn.operands)
                  or insn.imm_size == 4 and insn.imm_offset == site - insn.address) \
                    and fn in ports and not port_names_it(fn, b['names']):
                problems.append('%s: 0x%x (%s %s) is in 0x%x, whose port does not name the block - left alone' %
                                (b['name'], site, insn.mnemonic, insn.op_str, fn))
            else:
                b['sites'].append(site)
                b['users'].add(fn)
    # The block's end, or just past it, as a loop's bound: only a comparison with it as the immediate (not a read of
    # whatever follows the block), in a function that walks the block, and not a site some block has already. Where
    # several blocks could end there, the largest: the array the loop walks, not a scalar after it
    taken = set(site for b in blocks for site in b['sites'])
    bounds = {}
    for b in blocks:
        for site in b['ends']:
            insn, fn = operand(site)
            if site not in taken and insn is not None and insn.mnemonic == 'cmp' and insn.imm_size == 4 and \
                    insn.imm_offset == site - insn.address and fn in b['users']:
                if site not in bounds or b['hi'] - b['lo'] > bounds[site]['hi'] - bounds[site]['lo']:
                    bounds[site] = b
    for site, b in bounds.items():
        b['sites'].append(site)
    for b in blocks:
        result[b['name']] = ['0x%x' % x for x in sorted(b['sites'])]
        print('%s 0x%x..0x%x: %d references%s' % (b['name'], b['lo'], b['hi'], len(b['sites']),
                                                  '' if b['relocate'] else ' (the all-original runs only)'))
    for p in problems:
        print('  ' + p)
    out = os.path.join(REPO, 'tools', 'data_refs_%s.json' % side)
    json.dump(result, open(out, 'w'), indent=1)
    print('wrote', out)


if __name__ == '__main__':
    main()
