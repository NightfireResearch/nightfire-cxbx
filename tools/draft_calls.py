"""Calls from ported code into drafts: game functions we define in C++ but do not patch in.

A port that calls one of the game's functions by its C++ name reaches our definition of it, if there is one. When
that definition is not patched over the original (NOAUTOINJECT, NOINJECT, UNINJECTABLE, or no tag at all), it is a
draft nobody has checked against the original, and the game only ever ran the original there before. Calling the
original by address, as Script.cpp does for Break_DoBreak, is usually what is wanted until the draft is finished.

    python tools/draft_calls.py                    # every .cpp under src/action
    python tools/draft_calls.py src/action/engine/Script.cpp ...

Prints each call into a draft as file:line, with the draft's file. Static helpers that share a game function's
name are listed too; check those by eye.
"""

import json
import os
import re
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(__file__), '..'))
ACTION = os.path.join(REPO, 'src', 'action')


def main():
    functions = {f['name'] for f in json.load(open(os.path.join(REPO, 'tools', 'functions_action.json')))}
    injections = open(os.path.join(ACTION, 'autogenerated_injections.inc')).read()
    patched = set(re.findall(r'WriteJmpTo\([^;]*;\s*//\s*(\w+)', injections))

    sources = []
    for root, _, files in os.walk(ACTION):
        if 'devtools' in root.replace('\\', '/').split('/'):
            continue   # shadow tests call both sides on purpose
        for name in files:
            if name.endswith('.cpp'):
                sources.append(os.path.join(root, name))
    text = {path: open(path, encoding='utf-8', errors='replace').read() for path in sources}

    definition = re.compile(r'^[A-Za-z_][\w\s\*&:<>,]*?\b(\w+)\s*\([^;{)]*(?:\([^)]*\)[^;{)]*)*\)\s*\{', re.M)
    drafts = {}
    for path, body in text.items():
        for match in definition.finditer(body):
            name = match.group(1)
            if name in functions and name not in patched:
                drafts.setdefault(name, os.path.relpath(path, REPO))

    targets = [os.path.abspath(p) for p in sys.argv[1:]] or sources
    found = 0
    for path in targets:
        body = text.get(path) or open(path, encoding='utf-8', errors='replace').read()
        own = os.path.relpath(path, REPO)
        defined_here = {m.group(1) for m in definition.finditer(body)}
        macros = set(re.findall(r'^\s*#define\s+(\w+)', body, re.M))
        for number, line in enumerate(body.splitlines(), 1):
            code = line.split('//')[0]
            for name in re.findall(r'\b(\w+)\s*\(', code):
                if name in drafts and name not in macros and drafts[name] != own and name not in defined_here:
                    print(f'{own}:{number}: calls {name}, a draft in {drafts[name]}')
                    found += 1
    print(f'{found} calls into {len(drafts)} drafts', file=sys.stderr)
    return 1 if found else 0


if __name__ == '__main__':
    sys.exit(main())
