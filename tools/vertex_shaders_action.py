"""Generates the action engine's vertex shader programs from the XBE.

    python tools/vertex_shaders_action.py            write src/action/engine/Direct3D/VertexShaders.inc
    python tools/vertex_shaders_action.py --check    fail if it is out of date

Needs disc/default.xbe. VtxShaderFunctionTokenTable (0x001b4d78) points at 128 programs of NV2A microcode, one after
another from 0x0019cd08: each an 8-byte header (0x78 0x20, the instruction count, five zeros) and 16 bytes per
instruction. They are written as the XDK's shader assembler wrote its output, one array of words each, in the
table's order, and d3dSeam.cpp's table names them.
"""
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
sys.path.insert(0, HERE)
import global_coverage as gc  # noqa: E402

OUT = os.path.join(REPO, 'src', 'action', 'engine', 'Direct3D', 'VertexShaders.inc')
TABLE = (0x001b4d78, 128)
FIRST, END = 0x0019cd08, 0x001b4d78


def generate():
    nonzero, read, entry = gc.read_xbe()
    ptrs = struct.unpack('<%dI' % TABLE[1], read(TABLE[0], 4 * TABLE[1]))
    out = ['// THIS FILE IS GENERATED by tools/vertex_shaders_action.py from disc/default.xbe. DO NOT MODIFY.', '',
           "// The vertex shader programs VtxShaderFunctionTokenTable points at (d3dSeam.cpp), in its order: NV2A",
           "// microcode, an 8-byte header (0x78 0x20, the instruction count) and four words an instruction.", '']
    at = FIRST
    for i, p in enumerate(ptrs):
        assert p == at, 'program %d at 0x%08x, not after the one before (0x%08x)' % (i, p, at)
        head = read(p, 8)
        assert head[:2] == b'\x78\x20' and head[3:] == b'\0' * 5, 'program %d header %s' % (i, head.hex())
        words = 2 + 4 * head[2]
        data = struct.unpack('<%dI' % words, read(p, 4 * words))
        out.append('// XBE_GLOBAL(0x%08x, 0x%x) readonly' % (p, 4 * words))
        out.append('static const uint32_t VtxShaderProgram%d[%d] = {' % (i, words))
        for j in range(0, words, 8):
            out.append('    ' + ', '.join('0x%08x' % w for w in data[j:j + 8]) + ',')
        out.append('};')
        at = p + 4 * words
    assert at == END, 'the programs end at 0x%08x, not 0x%08x' % (at, END)
    out.append('')
    out.append('#define VTX_SHADER_PROGRAMS_INIT { \\')
    for i in range(0, len(ptrs), 5):
        out.append('    ' + ', '.join('VtxShaderProgram%d' % k for k in range(i, min(i + 5, len(ptrs)))) + ', \\')
    out.append('}')
    out.append('')
    return '\n'.join(out)


def main():
    text = generate()
    if '--check' in sys.argv:
        old = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if old.replace('\r\n', '\n') != text:
            sys.exit('%s is out of date: run tools/vertex_shaders_action.py' % OUT)
        return
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', os.path.relpath(OUT, REPO))


if __name__ == '__main__':
    main()
