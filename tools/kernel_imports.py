# Stage B step 4.1 of docs/cxbx-removal-plan.md: which of the XBE's xboxkrnl imports are actually reached from
# game code, as opposed to only from the statically linked Microsoft libraries the seams have already replaced.
#
# Usage: python tools/kernel_imports.py <default.xbe> [--all] [--cxbx <path to a Cxbx-Reloaded checkout>]
#
# Everything is derived rather than assumed:
#  - the kernel thunk table address comes out of the XBE header, where it is stored XOR'd; trying both the
#    retail and debug keys and keeping whichever lands inside a section doubles as a sanity check;
#  - ordinal-to-name comes from Cxbx-Reloaded's xbox.h, which annotates every export with EXPORTNUM(n);
#  - call sites are found by scanning for the two encodings that can reach an import thunk - "call dword ptr
#    [abs32]" (FF 15) and "jmp dword ptr [abs32]" (FF 25) - with an operand inside the table;
#  - each call site is attributed to the function containing it, via tools/functions_action.json;
#  - and any call site inside a function the project injects over is discounted, by reading the addresses out
#    of src/action/autogenerated_injections.inc. Those call sites still exist in the image but never execute,
#    so without this the report cannot show progress - it looked identical before and after the whole file
#    layer was replaced.
#
# On classification: there is no address at which game code stops and the statically linked libraries begin.
# The linker interleaved them - XAPILIB functions alone run from 0x000e9a24 to 0x001588db, with game code
# either side - so bracketing by address gives a confidently wrong answer. Ghidra's namespaces only cover
# what has been labelled, which leaves most library code sitting in "Global".
#
# So this does not try to decide. It reports every caller of every import, and separates imports by whether
# any caller is a function somebody has already named, on the grounds that this project's naming effort has
# gone into game code and the untouched FUN_xxxxxxxx functions are overwhelmingly library internals. That is
# a heuristic for ordering the reading, not a verdict: the listing is the evidence.
import struct, sys, os, re, json, collections

XOR_KT_RETAIL, XOR_KT_DEBUG = 0x5B6D40B6, 0xEFB1F152
LIBRARY_NAMESPACES = {'D3D8', 'DSOUND', 'XAPILIB', 'XGRAPHC', 'XONLINE', 'XNET'}

def load_xbe(path):
    d = open(path, 'rb').read()
    assert d[:4] == b'XBEH', '%s is not an XBE' % path
    base = struct.unpack_from('<I', d, 0x104)[0]
    nsec = struct.unpack_from('<I', d, 0x11c)[0]
    secptr = struct.unpack_from('<I', d, 0x120)[0] - base
    secs = [struct.unpack_from('<IIIII', d, secptr + i * 0x38)[1:] for i in range(nsec)]
    return d, secs, struct.unpack_from('<I', d, 0x158)[0]

def to_offset(secs, va):
    for vaddr, vsize, raw, rawsize in secs:
        if vaddr <= va < vaddr + vsize and va - vaddr < rawsize:
            return raw + (va - vaddr)
    return None

def read_thunks(d, secs, raw_thunk):
    for key, kind in ((XOR_KT_RETAIL, 'retail'), (XOR_KT_DEBUG, 'debug')):
        va = raw_thunk ^ key
        off = to_offset(secs, va)
        if off is None:
            continue
        ordinals, n = [], 0
        while True:
            value = struct.unpack_from('<I', d, off + n * 4)[0]
            if value == 0:
                break
            if not (value & 0x80000000) or (value & 0x7fffffff) > 0x1000:
                ordinals = []
                break
            ordinals.append(value & 0x7fffffff)
            n += 1
            if n > 512:
                break
        if ordinals:
            return va, ordinals, kind
    raise SystemExit('could not locate the kernel thunk table')

def ordinal_names(cxbx_root):
    # The exports are declared across a dozen headers (kernel.h, rtl.h, nt.h, xbox.h, io.h, ex.h, mm.h, ...),
    # so gather EXPORTNUM from all of them rather than guessing which one holds a given ordinal.
    root = os.path.join(cxbx_root, 'src', 'core', 'kernel')
    if not os.path.isdir(root):
        return {}
    text = ''
    for dirpath, dirnames, filenames in os.walk(root):
        for fn in filenames:
            if fn.endswith('.h'):
                text += open(os.path.join(dirpath, fn), encoding='utf-8', errors='replace').read() + chr(10)
    names = {}
    # The declaration may put the name on the EXPORTNUM line or wrap before the argument list, so take the
    # last identifier before whichever of "(" or ";" ends the declarator.
    for m in re.finditer(r'EXPORTNUM\((\d+)\)([^;(]*)', text):
        words = [w for w in re.findall(r'\w+', m.group(2)) if not w.isdigit()]
        if words:
            names[int(m.group(1))] = words[-1]
    return names

def main():
    args = [a for a in sys.argv[1:] if not a.startswith('--')]
    show_all = '--all' in sys.argv
    cxbx = 'Cxbx-Reloaded'
    if '--cxbx' in sys.argv:
        cxbx = sys.argv[sys.argv.index('--cxbx') + 1]
        args = [a for a in args if a != cxbx]

    d, secs, raw_thunk = load_xbe(args[0])
    thunk_va, ordinals, kind = read_thunks(d, secs, raw_thunk)
    names = ordinal_names(cxbx)

    # Functions the project injects over: their bodies never run, so any kernel call inside them is dead.
    replaced = set()
    inc = 'src/action/autogenerated_injections.inc'
    if os.path.exists(inc):
        for m in re.finditer(r'WriteJmpTo\((0x[0-9a-fA-F]+)', open(inc).read()):
            replaced.add(int(m.group(1), 16))

    entries = json.load(open('tools/functions_action.json'))
    funcs = sorted(((int(f['address'], 16), f['name'], f.get('namespace', 'Global')) for f in entries),
                   key=lambda t: t[0])

    def containing(va):
        lo, hi, best = 0, len(funcs) - 1, None
        while lo <= hi:
            mid = (lo + hi) // 2
            if funcs[mid][0] <= va:
                best, lo = funcs[mid], mid + 1
            else:
                hi = mid - 1
        return best

    print('%s: %d kernel imports, thunk table at VA 0x%08x (%s XOR key)'
          % (os.path.basename(args[0]), len(ordinals), thunk_va, kind))
    libs = sorted(LIBRARY_NAMESPACES & {ns for a, n, ns in funcs})
    for ns in libs:
        addrs = [a for a, n, k in funcs if k == ns]
        print('  %-8s %d functions, 0x%08x .. 0x%08x' % (ns, len(addrs), min(addrs), max(addrs)))
    print('  (they interleave with game code, so callers are listed rather than classified by address)')
    if not names:
        print('  (no ordinal names: %s/src/core/kernel not found)' % cxbx)

    slot_va = {thunk_va + i * 4: ordinals[i] for i in range(len(ordinals))}
    callers = collections.defaultdict(set)
    for vaddr, vsize, raw, rawsize in secs:
        blob = d[raw:raw + rawsize]
        for m in re.finditer(rb'\xff[\x15\x25]', blob):
            if m.start() + 6 > len(blob):
                continue
            operand = struct.unpack_from('<I', blob, m.start() + 2)[0]
            if operand in slot_va:
                callers[slot_va[operand]].add(vaddr + m.start())

    named, anonymous, unused, done = [], [], [], []
    for ordinal in ordinals:
        name = names.get(ordinal, 'ordinal %d' % ordinal)
        seen, sites, live = {}, 0, 0
        for site in sorted(callers.get(ordinal, ())):
            fn = containing(site)
            if fn is None:
                seen[('0x%08x' % site, site, '?')] = 1
                sites += 1
                live += 1
                continue
            addr, fname, ns = fn
            if ns == 'xboxkrnl.exe':
                continue                    # the import stub itself, not a caller
            sites += 1
            if addr not in replaced:
                live += 1
            seen[(fname, addr, ns)] = seen.get((fname, addr, ns), 0) + 1
        if not seen:
            unused.append(name)
            continue
        if live == 0:
            done.append((name, seen, sites))
            continue
        identified = [k for k in seen
                      if not k[0].startswith('FUN_') and k[2] not in LIBRARY_NAMESPACES and k[1] not in replaced]
        (named if identified else anonymous).append((name, seen, sites))

    def dump(rows, heading):
        print('\n%s\n' % heading)
        for name, seen, sites in sorted(rows):
            print('  %-34s %d call site(s)' % (name, sites))
            for (fname, addr, ns) in sorted(seen, key=lambda k: k[1]):
                tag = '' if ns in ('Global', '?') else '  [%s]' % ns
                if addr in replaced:
                    tag += '  (replaced)'
                print('      0x%08x  %s%s' % (addr, fname, tag))

    if done:
        print('\n%d imports whose every caller has been replaced - these no longer run:\n' % len(done))
        for name, seen, sites in sorted(done):
            print('  %-34s %s' % (name, ', '.join(sorted(k[0] for k in seen))))

    dump(named, '%d imports still reached from live code somebody has named - read these first:' % len(named))
    if show_all:
        dump(anonymous, '%d imports whose callers are all unnamed or in a library namespace:' % len(anonymous))
    else:
        print('\n%d imports whose callers are all unnamed or in a library namespace (--all to list).' % len(anonymous))
    print('%d imports with no direct call site found%s.' % (len(unused), ': ' + ', '.join(sorted(unused)) if show_all else ''))

main()
